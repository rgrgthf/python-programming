# ============================================================
# GitHub 远程仓库 — 把代码传到云端
# ============================================================
# Git = 本地工具（你电脑上的时光机）
# GitHub = 云端平台（把时光机的内容存到网上，还能协作）
# 关系：Git 负责管理，GitHub 负责托管和分享。

# ============================================================
# 一、注册 GitHub 账号
# ============================================================
# 1. 打开 https://github.com
# 2. 点 Sign up 注册（用邮箱）
# 3. 用户名建议：和你的邮箱前缀类似，方便别人认（如 nammu-xx）
# 4. 登录后，右上角头像 → Settings → 可以设置头像/简介

# ============================================================
# 二、创建远程仓库（Repository）
# ============================================================
# 网页操作：
# 1. 右上角 "+" → New repository
# 2. 填 Repository name（如 python-study）
# 3. 可选：写 Description（一句话说明这个项目是干嘛的）
# 4. 建议勾选：
#    - Public（公开，别人能看） 或 Private（私有，仅自己）
#    - Add a README file（生成说明文件，好习惯）
# 5. 点 Create repository

# ============================================================
# 三、本地项目连接 GitHub（push 上传）
# ============================================================
# 方法 A：本地已有仓库，关联到 GitHub
#   git remote add origin https://github.com/你的用户名/仓库名.git
#   git branch -M main                # 把主分支命名为 main
#   git push -u origin main           # 首次推送（-u 记住关联）

# 方法 B：把 GitHub 上的仓库克隆到本地（新手推荐，最简单）
#   git clone https://github.com/你的用户名/仓库名.git
#   会把这个仓库整个下载到当前文件夹
#   之后直接在克隆的文件夹里 add/commit/push

# ============================================================
# 四、日常三连：commit + push
# ============================================================
# 改了代码后：
#   git add .
#   git commit -m "说明这次改了什么"
#   git push            # 推送到 GitHub
#
# commit = 存本地档
# push   = 把本地档上传到云端（别人才能看到）

# ============================================================
# 五、pull — 拉取更新
# ============================================================
# 场景1：换电脑/多人协作，GitHub 上有别人（或你另一台电脑）的更新
#   git pull            # 拉取远程最新代码到本地

# 场景2：先 pull 再 push 是好习惯
#   git pull
#   git push
# 先看云端有没有新改动，有就先合过来，避免 push 被拒

# ============================================================
# 六、第一次 push 的身份验证（重要！）
# ============================================================
# 现在 GitHub 不允许用密码登录命令行，需要令牌（token）：
#
# 方法①（推荐）：GitHub CLI 或 Git Credential Manager
#   装 Git 时如果勾了 Git Credential Manager，
#   push 时会自动弹出浏览器让你登录一次，之后就不用再输。
#
# 方法②：Personal Access Token
#   GitHub → Settings → Developer settings
#   → Personal access tokens → Generate new token
#   → 勾选 repo 权限 → 生成后复制
#   → push 时用户名填你的 GitHub 用户名，密码填 token
#   ⚠️ token 只显示一次，务必保存好！

# ============================================================
# 七、你的第一个 GitHub 项目（建议动手做）
# ============================================================
# 建议把你的 Python 学习笔记传到 GitHub：
#   1. GitHub 上新建仓库 python-study（Private）
#   2. 本地：git remote add origin https://github.com/你/python-study.git
#   3. git push -u origin main
# 好处：
#   - 换电脑/重装系统不丢笔记
#   - 展示给老师/复试老师看（内容就是你的努力证明）
#   - 养成专业习惯

# ============================================================
# 六、易错点汇总 + 自测
# ============================================================
# 易错点：
# 1. origin = 远程仓库的【默认名字】；origin/main = 远程的分支
# 2. git push 推本地到远程，git pull 拉远程到本地
# 3. 先 pull 再 push，否则可能被拒绝（远程有新提交）
# 4. GitHub 在国内访问不稳：加速器/代理可解
#
# 【基础】origin 是什么？push/pull 分别干什么？
# 【中等】为什么 push 前要先 pull？
# 【挑战】push 被拒绝（rejected）怎么处理？
