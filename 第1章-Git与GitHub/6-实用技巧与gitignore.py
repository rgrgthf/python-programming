# ============================================================
# 一、.gitignore — 告诉 Git"哪些文件不要管"
# ============================================================
# 有些文件不该进版本控制：
#   - 临时文件（__pycache__、.pyc）
#   - 生成的文件（运行产生的 txt/csv/png）
#   - 隐私文件（密码、token、.env）
#   - 大文件（数据集、模型权重）
#
# 在仓库根目录创建 .gitignore 文件，内容示例：

#   # Python 缓存
#   __pycache__/
#   *.pyc
#
#   # 生成的临时文件
#   *.txt
#   *.png
#   output/
#
#   # 隐私
#   .env
#   config.json

# 写法规则：
#   __pycache__/    → 忽略整个文件夹
#   *.pyc           → 忽略所有 .pyc 文件（* 是通配符）
#   !important.txt  → 例外：这个文件还是要管（! 表示取反）
#   /only_root.txt  → 只在根目录的才忽略

# ⚠️ 注意：已经被 git 跟踪的文件，.gitignore 管不了
# 想让它失效：git rm --cached 文件名（从跟踪中移除，但保留磁盘文件）

# ============================================================
# 二、git add . 前先 status
# ============================================================
# 养成习惯：
#   git status          # 看哪些文件会被 add
#   git add .
#   git commit -m "..."
# 避免把不该提交的文件（如临时文件）不小心提交上去

# ============================================================
# 三、常用组合命令
# ============================================================
# 快速提交（add + commit 一条）：
#   git commit -am "说明"
#   ⚠️ 只对"已跟踪且修改"的文件有效，新文件还是要先 add

# 查看更简洁的历史：
#   git log --oneline --graph    # 带分支图

# 撤销最后一次 commit（保留改动）：
#   git reset --soft HEAD~1

# ============================================================
# 四、什么时候该 commit？（好习惯）
# ============================================================
# ✅ 完成一个小功能时
# ✅ 文件能正常跑通时
# ✅ 准备尝试大改动之前（先存档，改坏了能回来）
# ❌ 代码跑不起来、改到一半时（除非你想留"事故现场"）

# 提交信息规范：
#   "完成第18章pandas笔记"    ✅ 清楚
#   "更新"                    ❌ 没信息量
#   "修复浓度计算除零问题"     ✅ 具体
#   "fix bug"                 ❌ 什么 bug？

