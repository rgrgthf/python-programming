# ============================================================
# 团队协作工作流 — 用 GitHub 多人开发
# ============================================================
# 这是你"迟早要学"的核心：多人一起开发一个项目。
# GitHub 协作的招牌功能：Fork + Pull Request（PR）

# ============================================================
# 一、两种协作模式
# ============================================================
# 模式①：同一个仓库，加你为 Collaborator（协作者）
#   适合：小团队，相互信任，直接 push
#   操作：仓库 Owner → Settings → Collaborators → 加人
#   之后大家都能直接 push/pull

# 模式②：Fork + Pull Request（开源项目标准流程）
#   适合：开源项目 / 不熟悉的团队 / 保护主线
#   流程：Fork（复制到你的账号）→ 改 → PR（请求合并）

# ============================================================
# 二、Pull Request（PR）— 代码合并申请
# ============================================================
# PR = 你跟仓库主人说："我改好了，请把我的改动合并进去"
# 整个流程：
#
# 1. 看到别人的项目 → 点右上角 Fork
#    → 你的账号下多了一个副本
#
# 2. 克隆自己的副本到本地：
#    git clone https://github.com/你/别人的仓库.git
#
# 3. 建分支、改代码、提交：
#    git checkout -b my-fix
#    # 改代码...
#    git add .
#    git commit -m "修复了xxx"
#
# 4. 推送到你的副本：
#    git push -u origin my-fix
#
# 5. 回到 GitHub，你账号的仓库页面会出现
#    "Compare & pull request" 按钮 → 点它
#    → 写清楚改了什么 → Create pull request
#
# 6. 仓库主人看到 PR，review 后 Merge（合并）或关闭

# ============================================================
# 三、多人协作的黄金规则
# ============================================================
# 1. 动手前先 git pull（拿最新代码）
# 2. 一个功能一个分支（别直接在 main 上乱改）
# 3. 提交信息写清楚（"修复bug"不如"修复浓度计算为0的bug"）
# 4. 冲突别慌：手动解决后 add + commit
# 5. 大改动先开 issue 讨论，再动手

# ============================================================
# 四、Issue — 问题追踪
# ============================================================
# GitHub 的 Issue = 项目里的"待办/问题清单"
#   - 发现 bug → 提 Issue 描述
#   - 想加功能 → 提 Issue 建议
#   - 在 PR 里写 "Fixes #3" 可以自动关联并关闭 Issue #3
# 团队里用 Issue 管理任务，比微信群靠谱得多

# ============================================================
# 五、README — 项目说明书
# ============================================================
# 每个仓库都该有 README.md，告诉别人：
#   - 这个项目是干什么的
#   - 怎么运行/安装
#   - 目录结构
# 用 Markdown 写（# 标题、- 列表、``` 代码块）
# GitHub 会自动渲染 README.md 在仓库首页

# ============================================================
# 六、你目前最该掌握的协作技能（按顺序）
# ============================================================
# 1. ✅ clone / add / commit / push / pull
# 2. ✅ branch / checkout / merge（会切换和合并）
# 3. ⬜ 看懂并解决 merge conflict
# 4. ⬜ Fork 别人的项目 + 发起 PR
# 5. ⬜ 用 Issue 管理任务
#
# 等你和同学/导师合作做项目时，1~3 是底线，4 是加分项。
# 现在不用全学，先把 1~3 练熟。
