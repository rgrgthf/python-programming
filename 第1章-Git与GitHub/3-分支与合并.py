# ============================================================
# Git 分支与合并 — 多线并行开发
# ============================================================
# 分支（branch）= 在主线之外开一条"平行时间线"。
# 类比：写完初稿后，复制一份改第二版，两版同时存在，互不干扰。

# ============================================================
# 一、为什么需要分支？
# ============================================================
# 场景：主线是"正式版"，你想实验一个新功能，
# 直接改主线有风险（改坏了正式版），所以：
#   - 开一个分支 feature-xxx
#   - 在分支里随便折腾
#   - 稳定后再合并回主线

# 团队协作时尤其重要：
#   小明在分支A做功能1，小红在分支B做功能2，
#   互不影响，各自完成后合并。

# ============================================================
# 二、分支基础命令
# ============================================================
# 查看当前分支（* 表示当前在哪个分支）：
#   git branch
# → * main

# 创建新分支：
#   git branch feature-实验
# 切换分支：
#   git checkout feature-实验
#   # 或者一步完成：创建+切换
#   git checkout -b feature-实验

# 现在你在 feature-实验 分支上做的修改，
# 不会影响 main 分支——两条线完全独立！

# 删除分支（合并完不需要了）：
#   git branch -d feature-实验

# ============================================================
# 三、合并 — git merge
# ============================================================
# 分支做好后，切回主线再合并：
#   git checkout main          # 先回主线
#   git merge feature-实验      # 把分支的改动合并进来

# 合并后 main 就有了分支里做的所有修改

# ============================================================
# 四、⚠️ 合并冲突（conflict）— 团队协作必遇
# ============================================================
# 冲突 = 两个人改了【同一行】，Git 不知道该听谁的。
# 合并时 Git 会提示：
#   CONFLICT (content): Merge conflict in xxx.py
# 文件里会出现冲突标记：
#
#   <<<<<<< HEAD
#   print("小明的版本")
#   =======
#   print("小红的版本")
#   >>>>>>> feature-小红

# 解决步骤：
#   1. 打开冲突文件，看到 <<<<<<< ======= >>>>>>>
#   2. 手动选择/合并：保留该留的，删掉标记符号
#   3. 保存后 git add 那个文件
#   4. git commit 完成合并

# 别慌：冲突是正常的，不是错误，协商解决就行。

# ============================================================
# 五、完整分支流程（练习建议）
# ============================================================
# 1. git checkout -b practice     # 建分支
# 2. 改点代码
# 3. git add . && git commit -m "在分支上的改动"
# 4. git checkout main            # 回主线
# 5. git merge practice           # 合并

# ============================================================
# 六、分支策略小建议（个人用）
# ============================================================
# 个人项目可以简单点：
#   main = 稳定版（能跑、能展示）
#   开发时开分支 = 实验新东西
# 团队协作才需要规范的分支模型（如 main/develop/feature）
#
# 你现在自己学习，main 一个分支就够，
# 但【会建分支、会切分支、会合并】这个技能必须掌握，
# 因为团队协作时这是基本功。
