# ============================================================
# 一、为什么需要 Git？
# ============================================================
# 没有 Git 的痛苦：
#   report_final.py
#   report_final2.py
#   report_final_真的最终版.py
#   report_最终版_别再改了.py     ← 文件名灾难！

# Git 解决三个核心问题：
#   1. 历史记录：每次改动都有记录，能回退
#   2. 多版本：同一时间维护不同版本（分支）
#   3. 协作：多人同时改同一个项目不冲突

# ============================================================
# 二、核心概念（三个仓库区）
# ============================================================
# Git 的工作区有三个"区域"：
#
#   工作区(你看到的文件) → git add → 暂存区 → git commit → 本地仓库
#       ↓
#   git push → 远程仓库(GitHub)
#
#   - 工作区（Working）：你正在编辑的文件
#   - 暂存区（Staging）：准备提交的改动（add 后）
#   - 本地仓库（Local）：已经提交的历史（commit 后）
#   - 远程仓库（Remote）：GitHub 上的备份/共享

# ============================================================
# 三、检查是否已安装
# ============================================================
# 你的电脑已经装了 Git（PATH 里有 C:\Program Files\Git\bin）
# 验证：
#   git --version
#   → git version 2.x.x

# 如果没有：https://git-scm.com/download/win 下载安装，一路下一步

# ============================================================
# 四、第一次使用前必须配置（重要！）
# ============================================================
# 告诉 Git 你是谁（提交记录会带上你的名字）
# 在终端执行（把内容换成你自己的）：
#   git config --global user.name "你的名字"
#   git config --global user.email "你的邮箱@example.com"

# 查看配置是否生效：
#   git config --global --list

# --global 表示全局生效（所有项目都用这个身份）
# 也可以给单个项目单独配置（去掉 --global 即可）：
#   git config user.name "项目专用名字"

# ============================================================
# 五、Git 的工作哲学（记住这三句话）
# ============================================================
# 1. Git 只记录"提交过的"改动，没 commit 的不算数
# 2. commit 是安全的（可以回退），大胆提交
# 3. push 才是上传到 GitHub（commit 只在本地）

