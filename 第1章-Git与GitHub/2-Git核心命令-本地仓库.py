# ============================================================
# Git 核心命令 — 本地仓库操作
# ============================================================
# 所有命令在【终端】执行（PowerShell 就行）。
# 这一节掌握：init / add / commit / status / log —— 够你日常用 80%。

# ============================================================
# 一、git init — 把文件夹变成 Git 仓库
# ============================================================
# 在你的项目文件夹里执行一次：
#   cd 你的项目文件夹
#   git init
# 执行后会出现一个隐藏的 .git 文件夹（Git 的"大脑"）

# ⚠️ 注意：你的 Python药学学习体系 已经是 Git 仓库了（有 .git）
# 如果在这里 git init 会提示 already exists

# ============================================================
# 二、git status — 查看当前状态（最常用！）
# ============================================================
#   git status
# 会告诉你：
#   - 哪些文件被修改了（红色 = 未暂存）
#   - 哪些文件在暂存区（绿色 = 已 add）
#   - 有没有新文件/删除的文件
# 养成习惯：动手前先 git status 看状态

# ============================================================
# 三、git add — 把改动放入暂存区
# ============================================================
#   git add 文件名.py        # 添加一个文件
#   git add .               # 添加当前目录所有改动（常用）
#   git add 文件夹/          # 添加整个文件夹

# add 之后文件进入"暂存区"，但还没真正记录

# ============================================================
# 四、git commit — 提交（存档）
# ============================================================
#   git commit -m "提交说明"
# 示例：
#   git add .
#   git commit -m "完成第8章笔记"

# commit 后改动就"存档"进本地仓库了
# -m 后面是提交说明：写清楚这次改了什么（别写"改了点东西"）

# 修改了文件后重复：add + commit 就是标准循环
#   git add .
#   git commit -m "修改了xxx"

# ============================================================
# 五、git log — 查看提交历史
# ============================================================
#   git log
# 会列出所有 commit：
#   commit 7a3f2b9...
#   Author: 你的名字 <邮箱>
#   Date: ...
#      提交说明

# 简洁版（一行一个提交）：
#   git log --oneline
# → 7a3f2b9 (HEAD) 完成第8章笔记
# → 1b8c4d2 添加第7章测试

# 退出 log 视图：按 q

# ============================================================
# 六、git diff — 查看改了什么
# ============================================================
#   git diff               # 看未暂存的改动（还没 add 的）
#   git diff --cached      # 看已暂存的改动（已 add 的）
# 红色 - 是删除/旧内容，绿色 + 是新增/新内容

# ============================================================
# 七、回退操作（后悔药）
# ============================================================
# ① 撤销"未暂存"的改动（回到上次 commit 的状态）：
#   git checkout -- 文件名
#   ⚠️ 会丢失所有未提交的修改，慎用！

# ② 把文件从暂存区撤出（不取消修改）：
#   git restore --staged 文件名

# ③ 回退到上一个 commit（保留改动在磁盘）：
#   git reset --soft HEAD~1

# ============================================================
# 八、标准工作流总结（背下来）
# ============================================================
# 改代码 → git status（看状态）→ git add . → git commit -m "说明"
# 三个命令一套，写完一个功能就存一个档。
#
# 你现在的 Python药学学习体系 已经能用这套流程了，
# 建议每完成一章就 commit 一次，留个档。

# ============================================================
# 六、易错点汇总 + 自测
# ============================================================
# 易错点：
# 1. 先 git init 建仓库，再 add/commit
