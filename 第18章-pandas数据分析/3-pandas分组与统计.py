# ============================================================
# pandas 分组与统计 — 实验数据按组汇总
# ============================================================
# 实验最常见操作：按组（对照/给药）计算均值、标准差、显著性。
# groupby 就是"按某列分组，再对每组做统计"。

import pandas as pd

# 模拟一份实验结果：3 个组，每组 4 个重复
data = {
    "组别": (["对照"] * 4 + ["低剂量"] * 4 + ["高剂量"] * 4),
    "细胞存活率": [95, 93, 97, 94, 78, 82, 80, 76, 45, 50, 47, 42],
}
df = pd.DataFrame(data)
print(df)

# ============================================================
# 一、groupby 分组统计
# ============================================================
# 按组算平均值
print(df.groupby("组别")["细胞存活率"].mean())
# 组别
# 对照      94.75
# 低剂量    79.00
# 高剂量    46.00

# 一次算多个统计量
print(df.groupby("组别")["细胞存活率"].agg(["mean", "std", "min", "max", "count"]))
# std = 标准差（论文里"均值±标准差"就是 mean/std）

# 保留两位小数的输出：
result = df.groupby("组别")["细胞存活率"].agg(["mean", "std"])
print(result.round(2))


# ============================================================
# 二、describe — 一键描述统计
# ============================================================
print(df["细胞存活率"].describe())
# count 12.0
# mean  71.166667
# std   20.5...
# min   42.0
# 25%   ...
# 50%   ...
# 75%   ...
# max   97.0


# ============================================================
# 三、组内再做计算
# ============================================================
# 每组的"抑制率" = 100 - 存活率（新增一列）
df["抑制率(%)"] = 100 - df["细胞存活率"]
print(df)

# 按组求每组的总和
print(df.groupby("组别")["抑制率(%)"].sum())


# ============================================================
# 四、多列分组统计
# ============================================================
# 按（组别 + 时间点）分组
data2 = {
    "组别": ["对照"] * 6 + ["给药"] * 6,
    "时间点": [0, 1, 2, 4, 8, 12] * 2,
    "浓度": [100, 98, 95, 90, 85, 80, 100, 70, 55, 40, 30, 22],
}
df2 = pd.DataFrame(data2)
print(df2.groupby(["组别", "时间点"])["浓度"].mean())
# 这就是"不同时间点的血药浓度"表格的雏形（药代动力学数据）


# ============================================================
# 五、排序
# ============================================================
# 按某列排序
print(df.sort_values("细胞存活率", ascending=False))   # 存活率从高到低
print(df.sort_values("细胞存活率"))                     # 从低到高
# 按组排序 + 组内按存活率
print(df.sort_values(["组别", "细胞存活率"]))


# ============================================================
# 六、应用函数到每一行/每一列
# ============================================================
# apply：对每个元素做自定义操作
df["存活率开根号"] = df["细胞存活率"].apply(lambda x: x ** 0.5)
print(df)

# 例子：把浓度列四舍五入
df["抑制率(%)"] = df["抑制率(%)"].round(1)


# ============================================================
# 七、实战：一份标准的三组实验报告格式
# ============================================================
summary = (
    df.groupby("组别")["细胞存活率"]
      .agg(["mean", "std", "count"])
      .round(2)
)
print(summary)
# 这样算出来的"均值±标准差"就是论文/报告里的：
#   对照组：94.75 ± 1.71
#   低剂量：79.00 ± 2.58
#   高剂量：46.00 ± 3.37
# 之后在 scipy 里对它做 t 检验 / ANOVA（阶段二）
