# 使用前：import matplotlib.pyplot as plt
# 中文显示需要设置字体（Windows 用 SimHei）

import matplotlib.pyplot as plt

# 中文字体设置（Windows，保证中文标签不乱码）
plt.rcParams["font.sans-serif"] = ["SimHei"]       # 黑体
plt.rcParams["axes.unicode_minus"] = False          # 解决负号显示问题


# ============================================================
# 一、折线图（时间/浓度变化）
# ============================================================
x = [0, 1, 2, 4, 8, 12]              # 时间点
y = [100, 98, 92, 80, 65, 50]        # 血药浓度

plt.plot(x, y, marker="o")           # marker="o" 画数据点
plt.xlabel("时间 (h)")
plt.ylabel("血药浓度 (μg/mL)")
plt.title("血药浓度-时间曲线")
plt.show()                           # 显示图（本地运行才看得到）


# ============================================================
# 二、柱状图（组间比较，实验标配）
# ============================================================
groups = ["对照", "低剂量", "高剂量"]
values = [94.75, 79.00, 46.00]
errors = [1.71, 2.58, 3.37]          # 标准差（误差线）

plt.bar(groups, values, yerr=errors, capsize=5)
plt.ylabel("细胞存活率 (%)")
plt.title("不同剂量组的细胞存活率")
plt.show()
# yerr=errors：画误差线（就是论文里的"均值±标准差"）
# capsize=5：误差线顶端的小横线


# ============================================================
# 三、散点图（标准曲线！）
# ============================================================
conc = [0.0, 0.1, 0.2, 0.4, 0.8, 1.6]    # 标准浓度
abs_ = [0.001, 0.082, 0.158, 0.331, 0.654, 1.302]  # 吸光度

plt.scatter(conc, abs_)
plt.xlabel("浓度 (mg/mL)")
plt.ylabel("吸光度")
plt.title("标准曲线")
plt.show()
# 之后阶段二用 scipy 拟合出回归直线，就能算未知浓度了


# ============================================================
# 四、箱线图（看数据分布）
# ============================================================
import pandas as pd

data = {
    "组别": ["对照"] * 5 + ["给药"] * 5,
    "存活率": [95, 93, 97, 94, 96, 50, 45, 47, 52, 48],
}
df = pd.DataFrame(data)

df.boxplot(column="存活率", by="组别")
plt.title("两组存活率分布")
plt.suptitle("")       # 去掉自动加的标题
plt.show()
# 箱线图一眼看出：中位数、四分位、异常点


# ============================================================
# 五、一张图画多条线（组间对比）
# ============================================================
t = [0, 1, 2, 4, 8, 12]
ctrl = [100, 99, 98, 97, 96, 95]
drug = [100, 90, 82, 70, 58, 45]

plt.plot(t, ctrl, marker="o", label="对照")     # label=图例名
plt.plot(t, drug, marker="s", label="给药")
plt.xlabel("时间 (h)")
plt.ylabel("浓度")
plt.legend()           # 显示图例
plt.title("给药组 vs 对照组")
plt.show()


