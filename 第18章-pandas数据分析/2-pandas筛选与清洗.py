# ============================================================
# pandas 数据筛选与清洗 — 实验数据的"去粗取精"
# ============================================================
# 实验数据往往有脏数据：缺失、异常值、重复、类型不对。
# 这一章解决"怎么把数据整理干净"。

import pandas as pd

# 构造一份带脏数据的实验记录（模拟）
data = {
    "样品":   ["A1", "A2", "A3", "B1", "B2", "B3", "C1"],
    "组别":   ["对照", "对照", "给药", "给药", "给药", "给药", "对照"],
    "浓度":   [10.5, 8.2, 9.8, None, 7.9, 1000, 9.1],   # None=缺失, 1000=异常
    "抑制率": [5, 12, 25, 48, 76, 92, None],
}
df = pd.DataFrame(data)
print("原始数据：")
print(df)

# ============================================================
# 一、处理缺失值（None / NaN）
# ============================================================
print(df.isna())             # 每个位置是不是缺失 → True/False 表
print(df.isna().sum())       # 每列缺几个
print(df.isnull().sum())     # 同上（isna/isnull 等价）

# ① 删除有缺失的行（简单粗暴，适合缺失少）
df_clean = df.dropna()       # 删掉任何含缺失值的行
print(df_clean)

# ② 填充缺失值
df_fill = df.fillna(0)                       # 填 0
df_fill2 = df.fillna(df["浓度"].mean())      # 填该列平均值（更常用）
print(df_fill2)


# ============================================================
# 二、处理重复值
# ============================================================
# 构造重复数据
df2 = pd.concat([df, df.iloc[[0]]], ignore_index=True)  # 复制一行
print("含重复行数：", len(df2))
df2 = df2.drop_duplicates()                  # 删除重复行
print("去重后行数：", len(df2))


# ============================================================
# 三、按条件筛选行（实验数据最常用的操作！）
# ============================================================
# 筛选出"给药组"的行
drug = df[df["组别"] == "给药"]
print(drug)

# 筛选浓度大于 9 的
high = df[df["浓度"] > 9]
print(high)

# 多条件：给药组 且 浓度 > 8
sel = df[(df["组别"] == "给药") & (df["浓度"] > 8)]
# 注意：pandas 里 & 是"且"，| 是"或"，不是 and/or！
# 而且每个条件都要加括号

# 反向筛选：不是对照组的
not_ctrl = df[df["组别"] != "对照"]

# 筛选缺失值：浓度为空的行
na_rows = df[df["浓度"].isna()]
print(na_rows)


# ============================================================
# 四、处理异常值（超出合理范围）
# ============================================================
# 浓度 1000 明显是录入错误。可以用条件把它替换或删掉：
df["浓度"] = df["浓度"].where(df["浓度"] < 100, df["浓度"].mean())
# where(条件, 不满足时的值)：满足条件保留原值，不满足替换
print(df)

# 更直观的做法：先看描述统计，找出异常
print(df.describe())   # 每列统计：count/mean/std/min/25%/50%/75%/max
# 看 max 是否离谱，再看 min 是否合理


# ============================================================
# 五、数据类型转换
# ============================================================
# 读取数据后，数字列可能是字符串（尤其 Excel 里带单位）
df["浓度"] = df["浓度"].astype(float)      # 转成 float
print(df.dtypes)

# 更稳妥：pd.to_numeric（转不了变成 NaN，不报错）
df["浓度"] = pd.to_numeric(df["浓度"], errors="coerce")
print(df.dtypes)


# ============================================================
# 六、列名清洗与重命名
# ============================================================
df = df.rename(columns={"抑制率": "抑制率(%)"})   # 改列名
print(df.columns)

# 去掉列名里的空格（仪器导出常见）
df.columns = [c.strip() for c in df.columns]
print(df.columns)


# ============================================================
# 七、实战：完整清洗流程（照着套就行）
# ============================================================
def clean_experiment(df):
    """实验数据清洗模板"""
    df = df.copy()                              # 别改原数据
    df = df.drop_duplicates()                   # 1. 去重
    df = df.dropna(how="all")                   # 2. 删全空行
    df["浓度"] = pd.to_numeric(df["浓度"], errors="coerce")  # 3. 类型转换
    df = df.fillna({"浓度": df["浓度"].mean()}) # 4. 缺失值用均值填
    return df

clean_df = clean_experiment(df)
print(clean_df)
