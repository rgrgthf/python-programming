# 八、易错点汇总
# ============================================================
# 1. read_csv 遇到中文/编码问题：加 encoding="utf-8"
#    （Windows 默认 GBK，UTF-8 文件不指定会乱码/报错）
# 2. df["列名"] 和 df.列名 基本等价，但列名有空格/特殊字符时
#    必须用 df["列名"] 这种写法
# 3. df.head()/tail() 返回【新表】，不修改原表
# 4. df.shape 是 (行, 列) 元组，别和 len(df)（行数）搞混
# 5. loc[行标签, 列名] 用名字；iloc[行位置, 列位置] 用位置，
#    两个都带 []，不是 df.loc.xxx
# 6. 取一列返回 Series，取多列/多行返回 DataFrame

