# 四、从列表/字典创建 DataFrame
# ============================================================
# 从字典创建（键=列名，值=列数据）
data = {
    "药物浓度": [1, 2, 4, 8, 16, 32],
    "抑制率":   [5, 12, 25, 48, 76, 92],
    "重复":     [1, 1, 1, 1, 1, 1],
}
df = pd.DataFrame(data)
print(df)
#    药物浓度  抑制率  重复
# 0        1     5     1
# 1        2    12     1
# ...


# ============================================================
# 五、查看数据的基本信息
# ============================================================
df = pd.DataFrame({
    "组别": ["对照", "给药", "对照", "给药"],
    "浓度": [10.5, 8.2, 9.8, 7.9],
})

print(df.head())        # 看前 5 行（默认）
print(df.tail(3))       # 看后 3 行
print(df.shape)         # → (4, 2)（行数, 列数）
print(df.columns)       # → Index(['组别', '浓度'], dtype='object')（列名）
print(df.dtypes)        # 每列的数据类型
print(df.info())        # 总览：行数、列数、每列非空数量、类型


# ============================================================
# 六、取值：列、行、单元格
# ============================================================
# 取一列（返回 Series）
print(df["浓度"])          # 按列名取
print(df["浓度"].mean())   # 该列平均值 → 9.1

# 取多列
print(df[["组别", "浓度"]])

# 按位置取：iloc[行, 列]
print(df.iloc[0])          # 第一行
print(df.iloc[0, 1])       # 第一行第二列 → 10.5
print(df.iloc[:, 1])       # 所有行第二列

# 按标签取：loc[行标签, 列名]
print(df.loc[0, "组别"])   # → 对照
print(df.loc[0:1, "浓度"]) # 前两行的浓度列


