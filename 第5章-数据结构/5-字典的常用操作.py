# ============================================================
# 字典的常用操作 — 查、增、删、改 全套
# ============================================================
# 字典方法很多，重点记住常用的这几个。

d = {"name": "小明", "age": 18, "city": "北京"}

# ============================================================
# 一、查
# ============================================================
print(d.keys())            # 所有键 → dict_keys(['name', 'age', 'city'])
print(d.values())          # 所有值 → dict_values(['小明', 18, '北京'])
print(d.items())           # 所有键值对 → dict_items([...])
# keys/values/items 返回的是"视图"，转成列表用 list()

print(d.get("city", "未知"))  # → 北京（带默认值，安全取值）
print(d.get("phone", "无"))   # → 无（键不存在返回默认值）


# ============================================================
# 二、增 / 改
# ============================================================
d["phone"] = "13800000000"   # 新增键值对
print(d)
d["age"] = 19                # 修改已有键
print(d)

# setdefault：键不存在才设置默认值（存在就不动）
d.setdefault("height", 175)
print(d.get("height"))       # → 175
d.setdefault("height", 180)  # 键已存在，不覆盖
print(d.get("height"))       # → 175（还是 175）

# update：用一个字典更新另一个
d.update({"city": "上海", "hobby": "编程"})
print(d)   # city 被改，hobby 被加


# ============================================================
# 三、删
# ============================================================
d.pop("phone")               # 删除指定键，返回其值
print(d)

x = d.pop("not_exist", "没了")  # 带默认值，不存在也不会报错
print(x)                     # → 没了

d.popitem()                  # 删除并返回"最后一个"键值对（Python 3.7+ 有序）
print(d)

d.clear()                    # 清空字典
print(d)                     # → {}


# ============================================================
# 四、字典推导式（了解，和列表推导式一个套路）
# ============================================================
# 生成 1~5 的平方字典：{1:1, 2:4, 3:9, 4:16, 5:25}
squares = {i: i * i for i in range(1, 6)}
print(squares)   # → {1: 1, 2: 4, 3: 9, 4: 16, 5: 25}

# 翻转字典（键值互换）
d = {"a": 1, "b": 2}
rev = {v: k for k, v in d.items()}
print(rev)       # → {1: 'a', 2: 'b'}


# ============================================================
# 五、字典 vs 列表 怎么选？
# ============================================================
# 需要"按编号/位置"存 → 列表
# 需要"按名字/键"快速查找 → 字典
#
# 查字典比查列表快得多：列表要一个个找（线性查找），
# 字典直接按键定位（哈希查找），数据量大时差距巨大。

# 例如：存学生成绩
# 列表法（要记住下标）
scores_list = [90, 85, 92]          # 第0个=语文？
# 字典法（一看就懂）
scores_dict = {"语文": 90, "数学": 85, "英语": 92}
print(scores_dict["数学"])           # → 85


# ============================================================
# 六、实战：统计每个元素出现的次数（通用套路）
# ============================================================
words = ["apple", "banana", "apple", "orange", "banana", "apple"]
counts = {}
for w in words:
    counts[w] = counts.get(w, 0) + 1   # get 默认 0，一次搞定！
print(counts)
# → {'apple': 3, 'banana': 2, 'orange': 1}
# 这行是统计次数的"一行流"写法，比 if-else 更简洁
