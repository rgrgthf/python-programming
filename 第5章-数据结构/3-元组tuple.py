# ============================================================
# 元组 tuple — 不可变的列表
# ============================================================
# 元组用圆括号 () 创建，功能像"只读的列表"：
# 能索引、切片、遍历，但【创建后不能修改】。
# 适用场景：不希望被意外改动的数据（如坐标、配置、日期）。

# ============================================================
# 一、创建元组
# ============================================================
t = (1, 2, 3)            # 标准写法
print(t)                 # → (1, 2, 3)
print(type(t))           # → <class 'tuple'>

t2 = 1, 2, 3             # 不加括号也行（逗号是关键）
print(t2)                # → (1, 2, 3)

t3 = tuple([1, 2, 3])    # 从列表转换
print(t3)                # → (1, 2, 3)

empty = ()               # 空元组
print(empty)             # → ()


# ============================================================
# 二、⚠️ 单元素元组 — 必须加逗号！
# ============================================================
a = (5)          # 没有逗号！这只是个整数 5
print(type(a))   # → <class 'int'>（不是元组！）

b = (5,)         # 有逗号才是元组
print(type(b))   # → <class 'tuple'>
# 记住：单元素元组 = (值,)


# ============================================================
# 三、索引、切片、遍历 — 和列表完全一样
# ============================================================
t = (10, 20, 30, 40, 50)
print(t[0])      # → 10
print(t[-1])     # → 50
print(t[1:3])    # → (20, 30)（切片结果还是元组）
print(20 in t)   # → True

for x in t:
    print(x, end=" ")   # → 10 20 30 40 50
print()


# ============================================================
# 四、元组不可变 — 与列表的最大区别
# ============================================================
t = (1, 2, 3)
# t[0] = 100        ← 报错！TypeError: 'tuple' object does not support item assignment
# t.append(4)       ← 报错！元组没有 append 方法
# 元组创建后就不能增、删、改


# ============================================================
# 五、元组解包 — 元组的最强用法
# ============================================================
t = (10, 20, 30)
a, b, c = t          # 一次性取出所有元素
print(a, b, c)       # → 10 20 30

# 你之前已经用过！交换变量本质就是解包：
x, y = 10, 20
x, y = y, x          # 右边 (y, x) 就是一个元组，解包给左边
print(x, y)          # → 20 10

# 解包时元素个数必须匹配，否则报错：
# a, b = (1, 2, 3)   ← 报错！3 个值给 2 个变量


# ============================================================
# 六、元组 vs 列表 对比
# ============================================================
#                列表 list        元组 tuple
# 写法            [1, 2, 3]       (1, 2, 3)
# 可变性          可变 ✅          不可变 ❌
# 常用方法        append/pop/sort  几乎没有（只有 count/index）
# 性能            稍慢             稍快
# 用途            频繁增删改        固定不变的数据
#
# 能用元组就不用列表——"不可变"意味着更安全、更省内存，
# 还能用作字典的键（后面学）。

