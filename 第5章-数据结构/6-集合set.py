# ============================================================
# 集合 set — 无序、不重复
# ============================================================
# 集合用花括号 {} 创建，但里面没有"键值对"只有元素。
# 两个核心特性：
#   1. 元素不重复（自动去重）
#   2. 无序（没有下标，不能索引/切片）

# ============================================================
# 一、创建集合
# ============================================================
s = {1, 2, 3, 3, 2, 1}      # 有重复！
print(s)                    # → {1, 2, 3}（自动去重）

s2 = set([1, 2, 2, 3])      # 从列表转集合（去重神器）
print(s2)                   # → {1, 2, 3}

s3 = set("hello")           # 从字符串转集合
print(s3)                   # → {'h', 'e', 'l', 'o'}（去重且无序）

empty = set()               # ⚠️ 空集合必须用 set()！
# empty = {}                # ← 这是空字典，不是空集合！


# ============================================================
# 二、集合没有下标！
# ============================================================
s = {1, 2, 3}
# print(s[0])   ← 报错！TypeError: 'set' object is not subscriptable
# 集合是无序的，不能按位置取元素

# 只能判断"在不在"：
print(2 in s)      # → True
print(10 in s)     # → False

# 只能遍历：
for x in s:
    print(x, end=" ")   # → 顺序不固定（可能 1 2 3，也可能别的）
print()


# ============================================================
# 三、添加和删除
# ============================================================
s = {1, 2, 3}
s.add(4)              # 添加一个元素
print(s)              # → {1, 2, 3, 4}

s.add(2)              # 重复添加没效果
print(s)              # → {1, 2, 3, 4}（没变化）

s.remove(3)           # 删除指定元素
print(s)              # → {1, 2, 4}
# s.remove(99)        # ← 不存在会报 KeyError
s.discard(99)         # 删除，但不存在也不报错（更安全）

s.pop()               # 随机删一个（集合无序，删哪个不确定）
print(s)


# ============================================================
# 四、集合运算 — 集合的招牌功能！
# ============================================================
A = {1, 2, 3, 4, 5}
B = {4, 5, 6, 7}

print(A | B)        # 并集 → {1, 2, 3, 4, 5, 6, 7}
print(A & B)        # 交集 → {4, 5}
print(A - B)        # 差集（A 有 B 没有）→ {1, 2, 3}
print(B - A)        # → {6, 7}
print(A ^ B)        # 对称差（只在一个集合里）→ {1, 2, 3, 6, 7}

# 运算符版本：| & - ^
# 方法版本：union/intersection/difference/symmetric_difference

# 子集判断
print({1, 2} <= A)     # → True（{1,2} 是 A 的子集）
print(A >= B)          # → False（A 不是 B 的超集）


# ============================================================
# 五、集合的应用场景
# ============================================================

# ① 列表去重（最常用！）
lst = [1, 2, 2, 3, 3, 3, 4]
unique = list(set(lst))     # 集合去重 → 再转回列表
print(unique)               # → [1, 2, 3, 4]（顺序不保证）

# ② 快速判断元素是否存在（比列表快）
# ③ 数学集合运算（交集并集等）
# ④ 找两个列表的共同元素
a = [1, 2, 3, 4]
b = [3, 4, 5, 6]
print(set(a) & set(b))      # → {3, 4}（共同元素）


