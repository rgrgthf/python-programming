# ============================================================
# 字典 dict — 键值对存储
# ============================================================
# 字典用花括号 {} 创建，存的是"键:值"对（key: value）。
# 就像一本电话簿：按"名字"（键）查"号码"（值）。
# 你之前在统计字符次数时已经偷偷用过了！

# ============================================================
# 一、创建字典
# ============================================================
d = {"name": "小明", "age": 18, "city": "北京"}
print(d)   # → {'name': '小明', 'age': 18, 'city': '北京'}

empty = {}                 # 空字典
print(empty)               # → {}

# 用 dict() 创建
d2 = dict(name="小红", age=20)
print(d2)                  # → {'name': '小红', 'age': 20}


# ============================================================
# 二、键的特性（重点）
# ============================================================
# 1. 键必须【不可变】类型：字符串、数字、元组都可以
# 2. 键必须【唯一】：重复的键，后面的覆盖前面的
# 3. 值可以是任意类型（包括列表、字典）

d = {"a": 1, "a": 2}       # 键重复了
print(d)                   # → {'a': 2}（后面的覆盖前面的）

# 键不能用列表（列表可变）：
# d = {[1, 2]: "x"}        ← 报错！TypeError: unhashable type: 'list'


# ============================================================
# 三、访问 — 用键取值
# ============================================================
d = {"name": "小明", "age": 18}

print(d["name"])   # → 小明
print(d["age"])    # → 18
# print(d["height"])  ← 键不存在会报 KeyError！

# 用 get() 方法：键不存在时不报错，返回 None 或默认值
print(d.get("height"))        # → None
print(d.get("height", 0))     # → 0（指定默认值）
print(d.get("name", "无名"))   # → 小明（键存在就用真实值）


# ============================================================
# 四、增、改、删
# ============================================================
d = {"name": "小明"}

d["age"] = 18          # 键不存在 → 添加
print(d)               # → {'name': '小明', 'age': 18}

d["age"] = 19          # 键已存在 → 修改
print(d)               # → {'name': '小明', 'age': 19}

d.pop("age")           # 删除指定键，返回被删的值
print(d)               # → {'name': '小明'}

# d["xxx"] 不存在时：赋值是添加；读取是报错


# ============================================================
# 五、判断键是否存在 — in
# ============================================================
d = {"name": "小明", "age": 18}
print("name" in d)     # → True（判断的是键，不是值！）
print("小明" in d)     # → False
print("小明" in d.values())  # → True（判断值要这样）


# ============================================================
# 六、遍历字典
# ============================================================
d = {"name": "小明", "age": 18, "city": "北京"}

# ① 遍历键（默认）
for k in d:
    print(k, end=" ")       # → name age city
print()

# ② 遍历键值对（推荐）
for k, v in d.items():
    print(k, "=", v)        # name = 小明 / age = 18 / city = 北京

# ③ 只遍历键 / 只遍历值
print(list(d.keys()))       # → ['name', 'age', 'city']
print(list(d.values()))     # → ['小明', 18, '北京']


# ============================================================
# 七、实战：统计字符出现次数（正式版！）
# ============================================================
s = "hello python, hello world"
counts = {}                    # 空字典存结果
for ch in s:
    if ch.isalpha():           # 只统计字母
        if ch in counts:       # 这个键出现过吗？
            counts[ch] += 1    # 出现过 → 次数 +1
        else:
            counts[ch] = 1     # 第一次见 → 记为 1
print(counts)
# → {'h': 2, 'e': 2, 'l': 3, 'o': 4, 'p': 1, 'y': 1, 't': 1, 'n': 1, 'w': 1, 'r': 1, 'd': 1}
# 这就是"查字典"的经典套路：先 in 判断，再 +1
