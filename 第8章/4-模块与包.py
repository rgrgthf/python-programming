# ============================================================
# 一、什么是模块？
# ============================================================
# 模块 = 一个 .py 文件。任何 Python 文件都能被 import。
# 包 = 一个包含 __init__.py 的文件夹（一堆模块的集合）。

# 导入方式：
import math            # 导入整个模块
import random as rnd   # 起别名
from math import sqrt  # 只导入其中的函数
from os import path    # 导入子模块

# 三种用法的区别：
import math            # math.sqrt(9)        ← 要写前缀
from math import sqrt  # sqrt(9)             ← 直接用（只导入一个）
import math as m       # m.sqrt(9)           ← 短前缀


# ============================================================
# 二、import 的执行过程
# ============================================================
# import 一个模块时，Python 会：
#   1. 找到这个 .py 文件
#   2. 【从上到下执行】这个文件里的所有代码！
#   3. 把里面的函数/变量挂到模块名下
#
# 所以模块文件里不该有"立刻执行"的代码（除了定义）
# 否则 import 时会被执行。这就引出下一节：


# ============================================================
# 三、if __name__ == "__main__" — 必学！
# ============================================================
# __name__ 特殊变量：
#   直接运行这个文件时 → __name__ == "__main__"
#   被别人 import 时   → __name__ == 模块名

# 作用：写在模块文件里的测试代码，只在"直接运行"时执行，
#      被 import 时不会执行。

# 举例（假设这个文件叫 mytools.py）：
def add(a, b):
    return a + b

def sub(a, b):
    return a - b

if __name__ == "__main__":
    # 这里的代码只有"直接运行 mytools.py"时才执行
    print("测试：", add(3, 5))       # → 测试： 8
    print("测试：", sub(10, 4))      # → 测试： 6
# 如果别的文件 import mytools，只导入 add/sub 函数，
# 不会打印"测试：..."——因为 __name__ 不是 "__main__"


