# ============================================================
# 附录 A — VS Code 使用指南（高效写代码）
# ============================================================
# 这是你每天要用的编辑器，掌握这些操作效率翻倍。

# ============================================================
# 一、高频快捷键（必背）
# ============================================================
# Ctrl+S         保存（现在开了自动保存，改完1秒自动存）
# Ctrl+Z / Ctrl+Y 撤销 / 重做
# Ctrl+Shift+P   命令面板（万能入口）
# Ctrl+/         注释 / 取消注释
# Tab / Shift+Tab  缩进 / 取消缩进
# Ctrl+F         当前文件查找
# Ctrl+Shift+F   全文件夹查找
# Ctrl+Shift+E   文件资源管理器
# Ctrl+`         打开/关闭终端
# F5             调试（打断点用）
# Alt+↑ / Alt+↓  移动当前行
# Shift+Alt+↓    复制当前行到下一行
# Ctrl+D         选中下一个相同词（批量改）
# Ctrl+Shift+K   删除整行

# ============================================================
# 二、选择解释器（你踩过坑的地方！）
# ============================================================
# 右下角状态栏显示当前 Python 解释器
# 点击它 → 选择：
#   Python 3.14（系统）→ 学基础用
#   sci（conda）       → 数据分析/RDKit 用
#   .venv             → 项目隔离用
# 选错了代码会报 ModuleNotFoundError！

# ============================================================
# 三、运行 Python 代码的几种方式
# ============================================================
# ① 右上角 ▶（Run Python File）：运行整个文件
# ② 选中代码 → 右键 → "在Python终端中运行所选内容"（只跑选中部分）
# ③ 终端手动：python 文件名.py
# ④ 交互式：终端输入 python 进入 REPL，逐行测试
#
# ⚠️ 记住：运行的是"磁盘上的文件"，改完要等自动保存或 Ctrl+S

# ============================================================
# 四、代码格式化（专业习惯）
# ============================================================
# 你的环境有 ruff（代码检查/格式化工具）
# 终端里：ruff format 文件名.py   （自动格式化）
#         ruff check 文件名.py    （检查问题）
# 或在 VS Code 设置里开启"保存时自动格式化"

# ============================================================
# 五、代码片段（Snippets）与 IntelliSense
# ============================================================
# 输入 def 按 Tab → 自动补全函数模板
# 输入 for 按 Tab → for 循环模板
# 输入时自动提示（IntelliSense）：函数名、参数、文档
# 这些是 VS Code + Pylance 插件提供的智能补全

# ============================================================
# 六、多光标（进阶利器）
# ============================================================
# Alt+点击  → 添加多个光标
# Ctrl+Alt+↑/↓ → 上下添加光标
# 场景：一次改多行相同结构
#   按住 Alt 点每行的开头 → 同时输入

# ============================================================
# 七、调试（F5）— 比 print 更强
# ============================================================
# 1. 在代码行号左边点击 → 加红点（断点）
# 2. 按 F5 开始调试
# 3. 程序停在断点处，左侧面板看变量值
# 4. F10 单步执行（一行一行走）
# 5. F11 进入函数内部
# 6. 调试面板可以监视特定变量
#
# 用调试器可以不用狂加 print 就能看清每一步的值

# ============================================================
# 八、常用 VS Code 设置建议
# ============================================================
# 已开启：files.autoSave = afterDelay（自动保存）
# 建议开启：
#   editor.wordWrap = on            （长行自动换行）
#   python.analysis.typeCheckingMode = "basic"  （基础类型检查）
#
# 打开设置：Ctrl+, （逗号）

# ============================================================
# 六、易错点汇总
# ============================================================
# 1. 常用快捷键：Ctrl+Shift+P 命令面板、Ctrl+, 设置、F5 调试
# 2. 设置入口：用户设置（全局）/ 工作区设置（.vscode）
# 3. 装扩展：左侧扩展图标搜名字；装完可能要重载窗口
# 4. 选了错误的 Python 解释器会导致库找不到：
#    右下角选解释器，或用 Ctrl+Shift+P "Select Interpreter"
# 5. .vscode/settings.json 里的配置只对这个项目生效
# 6. 学会看输出面板（Ctrl+`）排查运行问题

