# ============================================================
# 六、科研使用建议
# ============================================================
# 推荐工作流：
#   探索阶段：Jupyter 里快速试（读数据、画图、试分析）
#   定型阶段：把验证过的代码整理成 .py 脚本
#   交付阶段：脚本 + 结果图 + 说明（作品集）
#
# 项目结构示例：
#   project/
#   ├── explore.ipynb      # 探索分析
#   ├── process.py         # 正式处理脚本
#   ├── results/           # 输出
#   └── data/              # 原始数据
