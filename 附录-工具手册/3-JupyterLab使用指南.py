# 关闭：终端 Ctrl+C 两次

# ============================================================
# 二、Notebook 基本操作
# ============================================================
# 单元格两种类型：
#   Code（代码）：可运行 Python
#   Markdown（文本）：写说明、公式、标题
#
# 快捷键：
#   Shift+Enter   运行当前单元格
#   Ctrl+Enter    运行不移动光标
#   B / A         下方/上方新建单元格
#   D D           删除单元格（连按两次D）
#   M             当前格变 Markdown
#   Y             当前格变 Code
#   Ctrl+S        保存

# ============================================================
# 三、为什么用 Jupyter？
# ============================================================
# 优点：
#   1. 边写边看结果（数据探索效率高）
#   2. 代码+图表+说明混排（汇报/教学友好）
#   3. 变量跨单元格保留（不用重跑前面代码）
#   4. 图表直接内嵌显示
#
# 缺点：
#   1. 状态容易乱（变量改了可能忘了）
#   2. 不适合大型工程（难以调试/版本控制）
#   3. 正式脚本还是要 .py

# ============================================================
# 四、在 Notebook 里用 pandas/matplotlib
# ============================================================
# import pandas as pd
