# ============================================================
# 附录 D — 找回隐藏文件指南
# ============================================================
# 为什么有些文件夹在 VS Code 里"看不见"？
# 因为 .vscode/settings.json 的 files.exclude 把它们藏起来了
# （为了让界面清爽）。文件一直都在磁盘上，只是不显示。
# 这篇教你四种方法找回它们。

# ============================================================
# 一、工作区里被隐藏了哪些东西？
# ============================================================
# settings.json 的 files.exclude 配置：
#   .git/                     Git 内部数据（不用看）
#   .vscode/                  编辑器配置（不用看）
#   .venv/                    虚拟环境（不用看）
#   识图代理/                  识图工具（需要时去文件管理器）
#   DeepSeek对话记录/          历史对话存档
#   学习记录表/                学习进度记录
#   附录-工具手册/备份恢复/     备份恢复脚本（很少用）

# ============================================================
# 二、方法1：VS Code 里临时显示（最方便）
# ============================================================
# 1. 按 Ctrl+Shift+P 打开命令面板
# 2. 输入 "exclude"，选择：Files: Toggle Exclude Files
# 3. 切换后，被隐藏的文件夹会暂时全部显示出来（灰色）
# 4. 看完再执行一次，就恢复隐藏
#
# 说明：这只是"显示开关"，不会真的删任何文件

# ============================================================
# 三、方法2：Windows 文件管理器（永远可见）
# ============================================================
# files.exclude 只影响 VS Code 的显示，
# 在 Windows 文件管理器里这些文件夹一直存在，例如：
#   C:\Users\22239\Python药学学习体系\附录-工具手册\备份恢复\
#   C:\Users\22239\Python药学学习体系\学习记录表\
#   C:\Users\22239\Python药学学习体系\识图代理\
#
# 直接在文件管理器地址栏粘贴上面路径就能进去

# ============================================================
# 四、方法3：终端命令查看
# ============================================================
# PowerShell 里执行：
#   cd C:\Users\22239\Python药学学习体系
#   Get-ChildItem -Force
#     ↑ -Force 参数会显示所有隐藏项
#   Get-ChildItem 附录-工具手册\备份恢复
#     ↑ 查看备份恢复文件夹里的文件

# ============================================================
# 五、方法4：永久取消隐藏（不推荐，界面会变乱）
# ============================================================
# 打开 .vscode/settings.json，
# 在 files.exclude 里删掉对应那一行，保存就恢复显示。
# 例子：想永远显示"备份恢复"文件夹，删掉这行即可：
#   "附录-工具手册/备份恢复": true

# ============================================================
# 六、怎么运行"备份恢复"脚本（万一用到）
# ============================================================
# 场景：某天 VS Code 的聊天记录又"消失"了
#   1. 完全关闭 VS Code（脚本第一步会检查，必须关！）
#   2. 打开文件管理器，进入：
#      C:\Users\22239\Python药学学习体系\附录-工具手册\备份恢复\
#   3. 双击 运行恢复聊天记录.bat
#   4. 等它跑完（出现"聊天记录恢复完成"），重新打开 VS Code
#
# 原理：脚本把旧路径(93ff142e...)的聊天数据复制到新路径(81cd8a39...)
# 备份：恢复前会自动备份当前数据到 backup-before-restore（双保险）

# ============================================================
# 七、files.exclude 和 .gitignore 的区别（别搞混）
# ============================================================
# files.exclude（settings.json）：
#   - 只影响 VS Code 界面显示
#   - 文件仍在磁盘上，git 提交不受影响
#
# .gitignore：
#   - 告诉 git"这些文件不要提交到 GitHub"
#   - 例如 .venv/、DeepSeek对话记录/、考研/、专业课/ 不上 GitHub
#   - 但它不影响 VS Code 显示
#
# 两者相互独立：一个管"看不看得见"，一个管"传不传到云端"

# ============================================================
# 八、一句话总结
# ============================================================
# 找隐藏文件：
#   临时显示 → Ctrl+Shift+P → Toggle Exclude Files
#   永久查看 → Windows 文件管理器 / 终端 -Force
#   永久取消 → 改 settings.json
# 记住：隐藏 ≠ 删除，所有文件都安全待在磁盘上！
