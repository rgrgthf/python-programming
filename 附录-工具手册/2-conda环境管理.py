# ============================================================
# 附录 B — conda 环境管理指南
# ============================================================
# conda 是管理 Python 环境和包的工具（你的 sci 环境就是 conda 建的）。
# 掌握这几个命令，环境管理不再混乱。

# ============================================================
# 一、基本概念
# ============================================================
# 环境 = 独立的 Python 安装空间（互不干扰的"小房间"）
# 你的电脑有三个环境：
#   系统 Python 3.14（默认，学基础）
#   sci（conda，数据分析/RDKit）
#   .venv（项目隔离）
#
# conda 主要管 sci 这个环境

# ============================================================
# 二、激活环境（最重要！）
# ============================================================
# Windows PowerShell 里：
#   conda activate sci
# 激活后终端提示符前面会出现 (sci)
# 之后 python/pip 都用 sci 环境里的
#
# 回到默认：
#   conda deactivate

# ⚠️ 如果提示 conda 不是命令，需要先初始化：
#   在 Anaconda Prompt 或：
#   C:\Users\22239\miniconda3\Scripts\conda.exe init powershell
#   然后重启终端

# ============================================================
# 三、查看环境与包
# ============================================================
# 列出所有环境：
#   conda env list
#   → base / sci
#
# 当前环境装了哪些包：
#   conda list
#
# 某个包装了没：
#   conda list rdkit

# ============================================================
# 四、安装 / 卸载包
# ============================================================
# 安装（推荐用 conda，会解决依赖）：
#   conda install pandas -c conda-forge
#
# 用 pip 装 conda 里没有的：
#   pip install 包名
# ⚠️ 先 conda activate sci，再 pip install（装到 sci 里）
#
# 卸载：
#   conda remove 包名
#   pip uninstall 包名
#
# 更新包：
#   conda update 包名
#   pip install --upgrade 包名

# ============================================================
# 五、创建新环境（进阶）
# ============================================================
# 创建（指定Python版本）：
#   conda create -n 环境名 python=3.12
#
# 删除环境：
#   conda env remove -n 环境名
#
# 复制环境：
#   conda create -n 新名 --clone 旧名

# ============================================================
# 六、环境导出与还原（换电脑必备！）
# ============================================================
# 导出环境配置（记录装了哪些包）：
#   conda env export > environment.yml
#
# 用配置重建环境（新电脑）：
#   conda env create -f environment.yml
#
# 这样换电脑/备份环境就一条命令搞定

# ============================================================
# 七、国内镜像（你已配好清华源）
# ============================================================
# 你的 .condarc 已配置清华镜像，国内下载快
# 如果装包很慢，检查：
#   conda config --show channels
# 恢复默认源：
#   conda config --remove-key channels

# ============================================================
# 八、常见问题排查
# ============================================================
# 问题1：import 报 ModuleNotFoundError
#   检查：环境对不对（右下角解释器 / conda activate）
#
# 问题2：包装了但 import 不到
#   可能装到了别的环境。确认：conda list 包名
#
# 问题3：conda 装包很慢/超时
#   检查镜像配置；或改用 pip install
#
# 问题4：环境搞乱了
#   重建：conda env remove -n sci → conda create -n sci python=3.12
#   再按之前命令装包（记录在 environment.yml 最省事）

# ============================================================
# 六、易错点汇总
# ============================================================
# 1. conda 环境隔离：不同项目用不同环境，避免包冲突
# 2. 常用：conda create -n 环境名 / conda activate /
#    conda deactivate / conda list
# 3. RDKit 这类库 pip 装不上的，用 conda 装更稳
#    （conda install -c conda-forge rdkit）
# 4. 导出环境：conda env export > environment.yml
#    （记录依赖，换机器一键重建）
# 5. 激活环境后，pip 装包是装进【当前环境】
# 6. 别在 base 环境乱装包，隔离更安全

