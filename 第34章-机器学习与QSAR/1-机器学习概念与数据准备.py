# ============================================================
# 六、易错点汇总
# ============================================================
# 1. 监督学习要【特征 X】和【标签 y】：
#    X 是描述符矩阵，y 是活性/性质值
# 2. 数据必须拆分成【训练集/测试集】，
#    用测试集评估才有说服力（test_size=0.2）
# 3. 分类（活性/非活性）vs 回归（IC50 数值）模型不同，
#    评估指标也不同（准确率 vs R²）
# 4. 【过拟合】：模型在训练集好、测试集差——
#    是 QSAR 最大的坑
# 5. 特征和标签要一一对应，别错位
# 6. 数据量小（几十条）别硬上复杂模型

