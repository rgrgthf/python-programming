# ============================================================
# scipy 科研统计 — 论文显著性分析
# ============================================================
# scipy.stats 是科学计算统计的核心库。
# 论文/报告里最常用的三件事：
#   1. 描述统计（均值±标准差）
#   2. 显著性检验（t检验 / ANOVA / 卡方）
#   3. 相关性分析（pearson/spearman）
# 使用前：from scipy import stats

import numpy as np
from scipy import stats

# ============================================================
# 一、描述统计（快速掌握数据）
# ============================================================
data = np.array([12.3, 13.1, 11.8, 12.9, 13.5, 12.7, 13.2, 12.4])
print("均值：", data.mean())          # → 12.7375
print("标准差：", data.std())         # → 0.543（总体标准差）
print("标准误：", stats.sem(data))    # → 0.192（标准误=std/sqrt(n)）
print(stats.describe(data))          # 一次性描述统计

# 论文格式："均值 ± 标准差"：
print(f"{data.mean():.2f} ± {data.std():.2f}")   # → 12.74 ± 0.54

# ============================================================
# 二、正态性检验（选检验方法前必做）
# ============================================================
# 数据是否正态，决定了用参数检验还是非参数检验
# Shapiro-Wilk 检验：p > 0.05 说明数据正态
group1 = np.array([12.3, 13.1, 11.8, 12.9, 13.5, 12.7])
w, p = stats.shapiro(group1)
print(f"Shapiro: W={w:.3f}, p={p:.3f}")
# p > 0.05 → 数据符合正态分布 → 可以用 t 检验/ANOVA
# p <= 0.05 → 不符合正态 → 用非参数检验（Mann-Whitney / Kruskal）

# ============================================================
# 三、独立样本 t 检验（两组比较）
# ============================================================
# 场景：对照组 vs 给药组，比较有没有显著差异
control = np.array([95, 93, 97, 94, 96, 95, 92, 96])
treated = np.array([50, 45, 47, 52, 48, 49, 46, 51])

t_stat, p_value = stats.ttest_ind(control, treated)
print(f"t = {t_stat:.3f}, p = {p_value:.4f}")
# p < 0.05 → 差异显著（两组存活率有统计学差异）

# 解读：
#   p < 0.05   → 差异显著（论文标 *）
#   p < 0.01   → 差异极显著（论文标 **）
#   p >= 0.05  → 差异不显著（不能下结论有差异）

# ============================================================
# 四、配对 t 检验（同一批样本前后对比）
# ============================================================
# 场景：同一批动物，给药前 vs 给药后的指标
before = np.array([80, 82, 79, 81, 83, 78, 82, 80])
after  = np.array([60, 62, 58, 61, 63, 59, 62, 60])

t_stat, p_value = stats.ttest_rel(before, after)
print(f"配对t检验: t = {t_stat:.3f}, p = {p_value:.4f}")
# 配对 vs 独立：配对是"同一批人前后测"，独立是"两组不同的人"

# ============================================================
# 五、如何选检验？（重点！难点在选，不在写代码）
# ============================================================
# 比较几组？ 数据正态吗？
#
#   两组比较：
#     独立样本 → t 检验 ttest_ind
#     配对样本 → 配对 t 检验 ttest_rel
#     不正态   → Mann-Whitney U (独立) / Wilcoxon (配对)
#
#   三组及以上：
#     正态     → 单因素方差分析 ANOVA（第3节讲）
#     不正态   → Kruskal-Wallis 检验
#
# 一句话流程：
#   先 Shapiro 查正态 → 再决定用参数检验还是非参数检验

# ============================================================
# 五、易错点汇总
# ============================================================
# 1. t 检验返回的是 (统计量, p值) 元组，要解包：
#    t_stat, p = ttest_ind(a, b)
# 2. p < 0.05 才有统计意义；p 大说明【不能拒绝原假设】，
#    不代表"两组相同"
# 3. 先做正态性检验（shapiro），数据不正态要用非参数检验
#    （如 Mann-Whitney U，scipy.stats.mannwhitneyu）
# 4. 独立样本 ttest_ind vs 配对样本 ttest_rel 别选错：
#    同一个体前后测 → 配对；两个独立组 → 独立
# 5. ttest_ind 默认假设方差相等；方差不齐时加 equal_var=False
#    （Welch 检验）
# 6. 样本量太小（n<30）时 t 检验结果要谨慎解读

