# ============================================================
# os 模块 — 操作文件和目录
# ============================================================
# os 模块提供操作系统的功能：看路径、建文件夹、删文件等。
# 先导入：import os

import os

# ============================================================
# 一、路径相关
# ============================================================
print(os.getcwd())          # 当前工作目录
# → C:\Users\22239\python程序库

# 拼接路径（跨平台推荐！自动处理 / 和 \）
p = os.path.join("第7章", "test.txt")
print(p)                    # → 第7章\test.txt（Windows）或 第7章/test.txt（Linux）

# 判断文件/目录是否存在
print(os.path.exists("test.txt"))        # → False（当前目录没有）
print(os.path.exists("第7章"))           # → True

# 判断是文件还是目录
print(os.path.isfile("第7章"))           # → False
print(os.path.isdir("第7章"))            # → True

# 拆分路径
path = os.path.abspath("第7章")          # 转绝对路径
print(path)
print(os.path.basename(path))            # → 第7章（最后一段）
print(os.path.dirname(path))             # → C:\Users\22239\python程序库（上级目录）


# ============================================================
# 二、目录操作
# ============================================================
# 创建目录
if not os.path.exists("new_dir"):
    os.mkdir("new_dir")      # 创建单个目录（已存在会报错）

# os.makedirs("a/b/c")      # 创建多级目录

# 列出目录内容
print(os.listdir("第7章"))   # → 该目录下的所有文件名（列表）

# 删除
# os.remove("文件")         # 删除文件
# os.rmdir("空目录")        # 删除空目录


# ============================================================
# 三、重命名
# ============================================================
# os.rename("旧名", "新名")
# os.rename("old.txt", "new.txt")


# ============================================================
# 四、实战：遍历一个文件夹的所有文件
# ============================================================
# 列出第7章所有 .py 文件
files = os.listdir("第7章")
for f in files:
    if f.endswith(".py"):
        print(f)            # → 只打印 .py 文件
# os.path.splitext(f)[1] 可以取扩展名：".py"


# ============================================================
# 五、pathlib（更现代的写法，了解）
# ============================================================
# Python 3.4+ 推荐用 pathlib 替代 os.path
from pathlib import Path
p = Path("第7章") / "test.txt"     # 直接用 / 拼接！
print(p)                            # → 第7章\test.txt
print(p.exists())                   # 判断存在
# 了解即可，os 模块的用法先掌握
