# 六、调试实战：找出逻辑错误
# ============================================================
# 这个函数想计算平均值，但可能有 bug
def calc_mean(values):
    total = 0
    count = 0
    for v in values:
        if v > 0:          # 只想统计正数？
            total += v
            count += 1
    return total / count   # 如果 count=0 会 ZeroDivisionError！

# 用调试思路修正：
def calc_mean_fixed(values):
    positive = [v for v in values if v > 0]
    if not positive:               # 空列表处理
        return 0.0
    return sum(positive) / len(positive)

print(calc_mean_fixed([1, 2, 3, -5]))   # → 2.0
print(calc_mean_fixed([-1, -2]))        # → 0.0（不崩溃）

