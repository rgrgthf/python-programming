# ============================================================
# 五、常见 bug 类型与排查思路
# ============================================================
# 1. NameError: 变量名拼错 / 还没定义
# 2. TypeError: 类型不对（如对 int 用 len()）
# 3. IndexError: 索引越界（列表超范围）
# 4. KeyError: 字典键不存在
# 5. AttributeError: 对象没有这个属性
# 6. ValueError: 值不合法（如 int("abc")）
# 7. ZeroDivisionError: 除以0
# 8. 逻辑错误（不报错但结果不对）：用断点或打印中间值

# 排查套路：
#   1. 复现：能稳定复现吗？
#   2. 缩小：注释掉一半代码，看还报不报
#   3. 定位：断点停在关键位置看变量
#   4. 修复：改一行测一次

