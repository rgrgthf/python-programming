# 实战1：print 输出到文件
# ============================================================
# with 语句：上下文管理器，代码块结束后自动关闭文件，比 open/close 更安全
with open("练习输出/test1.txt", "w", encoding="utf-8") as f:
    print("人生苦短，我用Python！", file=f)
# 此处无需 f.close()，with 已自动处理