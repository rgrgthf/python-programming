# ============================================================
# input() 函数
# ============================================================
# 作用：接收用户的键盘输入，括号中可写提示文字
# 重点：无论用户输入什么，返回值永远是 字符串（str）类型！

# ① 基本用法
# input("请输入您的姓名: ")  # 仅输入，不保存
name = input("请输入您的姓名: ")
print("您好，" + name + "！",sep="")

# ② 类型转换 — 输入数字做运算
age = int(input("请输入您的年龄: "))     # int() 将字符串转为整数
print("您今年", age, "岁了！",sep="")
print("明年您", age + 1, "岁！",sep="")         # 转成 int 后才能做数学运算

# 注意：如果用户输入的不是纯数字（如 "18岁"），int() 会报 ValueError

# ③ 其他常用转换
# float(input(...))   → 转为浮点数（小数）
# eval(input(...))    → 自动识别类型（如输入 3.14 得到 float，输入 [1,2] 得到 list）

