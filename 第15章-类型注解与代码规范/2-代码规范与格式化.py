# ============================================================
# 一、PEP 8 核心规范（最常用几条）
# ============================================================
# 1. 缩进：4 个空格（不要 Tab）
# 2. 行宽：≤ 79 字符（长行要换行）
# 3. 变量/函数：小写 + 下划线  snake_case
#    my_name, total_amount, get_value
# 4. 类名：大驼峰  PascalCase
#    DrugInfo, DataProcessor
# 5. 常量：全大写 + 下划线
#    MAX_DOSE, PI
# 6. 运算符两边留空格
#    x = 1 + 2  （不是 x=1+2）
# 7. 逗号后留空格
#    f(a, b, c)
# 8. 函数/类之间空两行
# 9. import 放文件顶部，顺序：标准库 → 第三方 → 自己的

# ============================================================
# 二、命名艺术（老师的心法）
# ============================================================
# 不好的命名：
#   a = 5
#   x = get_data()
#   lst = [1, 2, 3]
#
# 好的命名（看到名字就懂意图）：
#   concentration = 5.0
#   sample_data = get_sample_data()
#   drug_list = ["阿司匹林", "布洛芬"]

# 命名原则：
#   1. 明确意图：process_data 比 do_stuff 好
#   2. 不说类型：drug_list 的 list 可省，直接 drugs
#   3. 动词开头：函数用动词（calc_/get_/find_/convert_）
#   4. 布尔变量用 is/has：is_valid, has_error
#   5. 避免缩写（除非通用）：conc 可，dtm 不行

