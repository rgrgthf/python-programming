# ① 文档字符串（函数说明，放"""里）——必写！
def calc_ic50(doses, inhibitions):
    """
    计算半数抑制浓度 IC50。
    参数:
        doses: list[float] 药物浓度列表
        inhibitions: list[float] 对应抑制率(0~100)
    返回:
        float IC50 值
    """
    # 简化示例
    return doses[inhibitions.index(max(inhibitions))]

