def normalize_absorbance(raw, blank=0.0):
    """基线校正：减去空白吸光度。

    Args:
        raw: 原始吸光度列表
        blank: 空白对照吸光度，默认0

    Returns:
        校正后的吸光度列表

    Raises:
        ValueError: raw 中有负数时
    """
    if any(r < 0 for r in raw):
        raise ValueError("吸光度不能为负")
    return [r - blank for r in raw]

print(normalize_absorbance([0.5, 0.8], 0.05))   # → [0.45, 0.75]

