# 4. 成就感：自己做的工具被别人用，是最大的激励

# ============================================================
# 二、怎么选题？（好项目三要素）
# ============================================================
# ① 真实需求：解决你实际遇到的问题（实验课/社团/老师课题）
# ② 难度适中：跳一跳够得着（太简单没成长，太难会放弃）
# ③ 能展示：结果直观（有图有结论，面试官3分钟看懂）
#
# 好题目示例（按你的阶段）：
#   - 标准曲线批量处理工具（简单，先练手）
#   - 实验数据 Excel 自动汇总工具（简单+实用）
#   - 化合物类药性筛选工具（RDKit，中等）
#   - 药物信息查询网站（Flask，中等）
#   - QSAR 活性预测模型（机器学习，进阶）
#   - 分子相似性检索系统（RDKit+Web，综合）

# ============================================================
# 三、项目规划模板（开始前想清楚）
# ============================================================
# 写一份项目说明（README），一开始就写：
"""
# 项目名称：XXX

## 1. 目标
一句话说清：这个工具/项目是干什么的，给谁用。

## 2. 功能列表
- [ ] 功能1：读取数据
- [ ] 功能2：清洗
- [ ] 功能3：分析
- [ ] 功能4：出图
- [ ] 功能5：生成报告

## 3. 技术栈
Python 3.12, pandas, numpy, matplotlib, openpyxl

## 4. 输入/输出
输入：Excel 实验记录
输出：汇总报告.xlsx + 图表.png

## 5. 里程碑
- [ ] 第一周：数据读取和清洗
- [ ] 第二周：分析和绘图
- [ ] 第三周：报告生成和测试
- [ ] 第四周：打磨和文档
"""

# ============================================================
# 四、项目文件夹规范（专业工程结构）
# ============================================================
# project/
# ├── README.md          # 项目说明（最重要！）
# ├── main.py            # 主程序（入口）
# ├── src/               # 模块代码
# │   ├── data_loader.py
# │   ├── analysis.py
# │   └── plot.py
# ├── tests/             # 测试（第24章）
# │   └── test_analysis.py
# ├── data/              # 数据（原始+处理）
# ├── results/           # 输出（图、报告）
# └── requirements.txt   # 依赖清单（pip freeze > requirements.txt）

# ============================================================
# 五、开发流程（迭代式）
# ============================================================
# 1. 最小可用版（MVP）：先做出能跑通主流程的版本
# 2. 迭代改进：每个功能单独实现、单独测试
# 3. 遇到不会的：查文档 → 写小demo → 再集成
# 4. 收尾：写README、清代码、加注释、跑测试
#
# 关键心态：
#   - 先跑通，再优化（别一开始就追求完美）
#   - 分解任务（大任务拆成小步骤）
#   - 每天一点点（比一次憋大的强）

# ============================================================
# 六、选择你的第一个项目（行动清单）
# ============================================================
# 建议第一个项目：实验数据 Excel 自动汇总工具
# 理由：实用（你马上用得上）+ 技术栈已全会（简单）
# 步骤：
#   1. 收集 3~5 个真实的实验 Excel 文件
#   2. 写出批量读取+汇总+统计（第23章的实战升级）
#   3. 加参数（第25章 argparse）
#   4. 加测试（第24章）
#   5. 打包成 exe（第25章 PyInstaller）
#   6. 写 README + 放作品集
#
# 做完一个，你就知道完整流程了，
# 之后做更复杂的项目（QSAR/药物发现）驾轻就熟。

# ============================================================
# 七、总结
# ============================================================
# 选题：真实需求 + 难度适中 + 能展示
# 规划：先写README（目标/功能/技术栈/里程碑）
# 结构：src + tests + data + results + README
# 流程：MVP → 迭代 → 收尾（文档+测试）
