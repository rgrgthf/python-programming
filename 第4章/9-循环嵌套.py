# ============================================================
# 循环嵌套 — 循环里面套循环
# ============================================================
# 外层每执行一轮，内层从头到尾完整执行一遍。
# 就像钟表：时针走一格，分针转一整圈。

# ============================================================
# 一、基本示例
# ============================================================
for i in range(1, 4):       # 外层 3 轮
    for j in range(1, 3):   # 内层 2 轮
        print(f"i={i}, j={j}")
# 输出：
# i=1, j=1
# i=1, j=2
# i=2, j=1
# i=2, j=2
# i=3, j=1
# i=3, j=2
# 总共执行 3 × 2 = 6 次


# ============================================================
# 二、九九乘法表
# ============================================================
for i in range(1, 10):              # 外层：行
    for j in range(1, i + 1):       # 内层：每行列数 = 行号
        print(f"{j}×{i}={i*j:2d}", end="  ")
    print()  # 换行
# 输出：
# 1×1= 1
# 1×2= 2  2×2= 4
# 1×3= 3  2×3= 6  3×3= 9
# ...


# ============================================================
# 三、打印图形
# ============================================================

# ① 直角三角形
n = 5
for i in range(1, n + 1):
    print("*" * i)
# 输出：
# *
# **
# ***
# ****
# *****

# ② 等腰三角形（带空格）
for i in range(1, n + 1):
    spaces = " " * (n - i)
    stars = "*" * (2 * i - 1)
    print(spaces + stars)
# 输出：
#     *
#    ***
#   *****
#  *******
# *********

# ③ 空心正方形
size = 5
for i in range(size):
    for j in range(size):
        if i == 0 or i == size - 1 or j == 0 or j == size - 1:
            print("* ", end="")
        else:
            print("  ", end="")
    print()


# ============================================================
# 四、循环嵌套中的 break 和 continue
# ============================================================
# break 只跳出它所在的那一层循环，不影响外层！
for i in range(1, 4):
    for j in range(1, 10):
        if j > 3:
            break                 # 只跳出内层 j 循环
        print(f"{i}-{j}", end=" ")
    print()  # ← break 后走到这里，外层继续下一轮
# 输出：
# 1-1 1-2 1-3
# 2-1 2-2 2-3
# 3-1 3-2 3-3


