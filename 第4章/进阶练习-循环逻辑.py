# 6. 用辗转相除法求两个正整数的最大公约数。
#    例：12 和 18 的最大公约数是 6
# 提示：a, b = b, a % b，直到 b 为 0，此时 a 就是答案
# 你的代码：
a = int(input("请输入第一个正整数："))
b = int(input("请输入第二个正整数："))
