# ============================================================
# 单分支结构 — if
# ============================================================
# 语法：if 条件:（条件后面必须有冒号）
#         ⬇ 缩进 4 格
#          条件成立时执行的代码
# 条件可以是任何能得出 True / False 的表达式

# ============================================================
# 一、基本示例
# ============================================================
age = int(input("请输入你的年龄："))
if age >= 18:
    print("你已成年，可以进入网吧")  # 条件成立才执行
print("程序结束")  # 无论条件是否成立，这行都会执行

# 对比 C++：Python 不需要括号包裹条件，不需要花括号，用冒号 + 缩进代替
# C++:  if (age >= 18) { cout << "..."; }


# ============================================================
# 二、条件可以写什么？
# ============================================================

# ① 比较运算符
x = 10
if x > 5:
    print("x 大于 5")

# ② 逻辑运算符
score = 85
if score >= 60 and score < 80:
    print("中等水平")

# ③ 直接用值（非零/非空 → True）
name = "小明"
if name:             # 非空字符串 → True
    print("名字不为空")

if 0:                # 0 → False，不执行
    print("这行不会被打印")

# ④ in / not in（成员判断）
s = "Hello World"
if "World" in s:
    print("找到了 World")

# ⑤ is / is not（身份判断，比 == 更严格）
a = None
if a is None:
    print("a 是 None")


# ============================================================
# 三、缩进是 Python 的灵魂
# ============================================================
# if 下面的代码块通过缩进（4 个空格）来界定，不像 C++ 用 {}。

if True:
    print("我在 if 里面")      # ← 有缩进，属于 if
    print("我也在 if 里面")    # ← 有缩进，也属于 if
print("我不在 if 里面")        # ← 无缩进，不属于 if

# 错误示范：缩进不一致会报 IndentationError
# if True:
#     print("4 个空格")
#   print("2 个空格")   ← 缩进不一致，报错！


# ============================================================
# 四、实战：判断闰年
# ============================================================
# 闰年规则：能被 4 整除但不能被 100 整除，或者能被 400 整除
year = int(input("请输入年份："))
if (year % 4 == 0 and year % 100 != 0) or (year % 400 == 0):
    print(year, "是闰年")
print("判断完毕")
# 注意：如果不想让非闰年也输出"判断完毕"，可以把 print 也缩进到 if 里面


# ============================================================
# 五、常见坑
# ============================================================

# ① 忘记冒号 → SyntaxError
# if x > 5           ← 少了冒号，报错！
#     print("x")

# ② 不该缩进的缩进了 → 逻辑错误（最难排查！）
password = "123456"
if password == "123456":
    print("登录成功")
    print("欢迎进入系统")  # ← 也在 if 里，只有密码对才输出
# 如果你本意是无论登录成功与否都说"欢迎"，这行就不该缩进

# ③ 条件里写 = 而不是 ==
# if x = 5:          ← 赋值语句，报错！
# if x == 5:         ← 正确，比较运算
# 示例：判断一个数是否为正数
num = int(input("请输入一个整数："))
if num > 0:
    print(num, "是一个正数。")
