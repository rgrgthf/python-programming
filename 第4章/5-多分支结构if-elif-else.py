# ============================================================
# 多分支结构 — if … elif … else
# ============================================================
# 语法：if 条件1:
#           条件1成立 → 执行
#       elif 条件2:
#           条件1不成立、条件2成立 → 执行
#       elif 条件3:
#           前面都不成立、条件3成立 → 执行
#       else:
#           以上全不成立 → 执行（可选）
# 从上到下依次判断，命中一条就跳出，后面全跳过。

# ============================================================
# 一、基本示例
# ============================================================
score = int(input("请输入成绩（0-100）："))

if score >= 90:
    grade = "A"
elif score >= 80:
    grade = "B"
elif score >= 70:
    grade = "C"
elif score >= 60:
    grade = "D"
else:
    grade = "F"

print("等级：", grade)


# ============================================================
# 二、执行逻辑图解
# ============================================================
# score = 75 时：
#
#   if score >= 90   → False → 跳过，往下走
#   elif score >= 80 → False → 跳过，往下走
#   elif score >= 70 → True  → 执行 grade="C"，跳出！后面全跳过
#   elif score >= 60 → （不会执行）
#   else:            → （不会执行）
#
# 这就是"命中即止"原则：从上到下，第一个 True 执行后立刻跳出。


# ============================================================
# 三、关键规则
# ============================================================

# ① 顺序至关重要 — 条件范围大的放前面还是后面？
# 错误写法（永远不会输出 B 和 C）：
score = 85
if score >= 60:
    print("及格")        # 85 ≥ 60，命中！后面全跳过
elif score >= 80:
    print("良好")        # 永远不会执行！
elif score >= 90:
    print("优秀")        # 永远不会执行！
# 教训：大范围条件会被优先命中，应把最严格/最窄的条件放前面

# ② 可以用多个 elif，也可以省略 else
x = 5
if x > 0:
    print("正数")
elif x < 0:
    print("负数")
# x = 0 时什么都不输出，因为没有 else 兜底


