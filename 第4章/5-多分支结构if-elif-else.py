# 四、实战示例
# ============================================================

# ① BMI 体重指数
height = float(input("身高（m）："))
weight = float(input("体重（kg）："))
bmi = weight / (height ** 2)
print("BMI：", round(bmi, 1))

if bmi < 18.5:
    print("偏瘦")
elif bmi < 24:
    print("正常")
elif bmi < 28:
    print("偏胖")
else:
    print("肥胖")

# ② 简易计算器
a = float(input("第一个数："))
op = input("运算符（+ - * /）：")
b = float(input("第二个数："))

if op == "+":
    print(a + b)
elif op == "-":
    print(a - b)
elif op == "*":
    print(a * b)
elif op == "/":
    if b != 0:
        print(a / b)
    else:
        print("错误：除数不能为 0")
else:
    print("错误：不支持的运算符")


# ============================================================
# 五、嵌套 if（分支里面套分支）
# ============================================================
# 多分支 + 嵌套配合使用，威力巨大。
year = int(input("请输入年份："))

if year % 4 == 0:
    if year % 100 == 0:
        if year % 400 == 0:
            print("闰年")
        else:
            print("平年")
    else:
        print("闰年")
else:
    print("平年")

# 等价的扁平写法（用 and / or 避免嵌套）：
if (year % 4 == 0 and year % 100 != 0) or (year % 400 == 0):
    print("闰年")
else:
    print("平年")
# 嵌套 vs 扁平：嵌套直观但层次深，扁平简洁但条件长，根据情况选择


# ============================================================
# 六、match-case（Python 3.10+，类似 C++ 的 switch）
# ============================================================
# 当大量 elif 都在判断同一个变量是否等于某个值时，match-case 更清晰。
status_code = int(input("输入状态码："))

match status_code:
    case 200:
        print("成功")
    case 404:
        print("未找到")
    case 500:
        print("服务器错误")
    case _:                     # _ 是通配符，相当于 else
        print("未知状态码")

