# 5.【简答】eval("1+2") 和 eval("abc") 分别会发生什么？为什么？
# 你的答案：
"""
eval("1+2")结果为3，eval("abc")结果为abc
eval()函数的作用是去掉引号并执行引号内容，1+2执行结果为3，abc则不做任何处理
"""
# ✏️ 订正：eval("abc") 会报 NameError！
#   eval 会把引号内容当 Python 代码执行，"abc" 会被当成变量名 abc 去解析，
#   而 abc 未定义 → NameError: name 'abc' is not defined。
#   只有 eval("'abc'")（带引号的字符串）才会返回字符串 'abc'。

