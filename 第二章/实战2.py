# 实战2：综合运用 input 和 print
# ============================================================

# 获取用户输入
name = input("请输入您的姓名：")
age = int(input("请输入您的年龄："))                # int() 转整数
motto = input("请输入您的座右铭：")

# 格式化输出
print("----------自我介绍----------")
print("姓名：", name, sep="")    # sep="" 去除默认空格，实现紧贴效果
print("年龄：", age, sep="")
print("座右铭：", motto, sep="")