# ============================================================
# print() 函数
# ============================================================
# 完整格式：print(*objects, sep=' ', end='\n', file=sys.stdout, flush=False)
# objects — 要输出的内容，可多个
# sep     — 多个内容之间的分隔符，默认空格
# end     — 输出末尾的结束符，默认换行 \n
# file    — 输出目标（默认屏幕），可改为文件对象
# flush   — 是否立即刷新缓冲区，默认 False

# ============================================================
# 一、基本输出
# ============================================================
a = 100
b = 50
print("Hello, World!")
print(a)
print(b)
print(a + b)
print("The sum of a and b is:", a + b)  # 多个内容用逗号分隔

# ============================================================
# 二、sep 参数 — 自定义分隔符
# ============================================================
print(1, 2, 3, sep="-")       # → 1-2-3
print("A", "B", "C", sep="")  # → ABC（无分隔符）

# ============================================================
# 三、end 参数 — 自定义结束符
# ============================================================
print("第一行", end=" → ")
print("还是第一行")            # → 第一行 → 还是第一行（不换行）
print("这才是第二行")          # 默认 end='\n'，正常换行

# ============================================================
# 四、字符与编码：chr() 和 ord()
# ============================================================
# ord()：字符 → 码点（整数）
# chr()：码点（整数） → 字符

# 常用 ASCII 码点速查：
# 'A'=65  'a'=97  '0'=48  空格=32
# 'C'=67  '['=91   '8'=56

print(chr(97))   # → a
print(chr(98))   # → b
print(chr(67))   # → C
print(chr(56))   # → 8
print(chr(91))   # → [

print(ord('C'))  # → 67

# Unicode 码点（中文等非 ASCII 字符）
print(ord("何"))  # → 20309
print(ord("梓"))  # → 26771
print(ord("坚"))  # → 22362

# 用 chr() 反向还原中文
print(chr(20309) + chr(26771) + chr(22362))  # → 何梓坚
# 加空格再拼接
print(chr(20309) + chr(26771) + chr(22362) + chr(32) + chr(20320) + chr(22909))
# → 何梓坚 你好

# 控制字符（不可见）
print(ord(" "))  # → 32，空格是可打印字符
print(chr(1))    # SOH（Start of Heading），控制字符，终端通常不可见

# ============================================================
# 五、输出到文件
# ============================================================
# 使用 file 参数将内容写入文件而非屏幕
fp = open("test.txt", "w")           # w=写入模式，文件不存在则创建，存在则覆盖
print("Hello, World!", file=fp)      # 内容写入文件
fp.close()                           # 一定要关闭文件！

# 推荐用 with 语句（自动关闭，更安全）：
with open("test1.txt", "w", encoding="utf-8") as f:
    print("人生苦短，我用Python！", file=f)
# 缩进块结束后文件自动关闭，无需 f.close()
