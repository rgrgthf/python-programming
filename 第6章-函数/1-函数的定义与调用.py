# ============================================================
# 函数 — 把代码打包，随用随调
# ============================================================
# 函数 = 一段有名字的、可以重复使用的代码块。
# 你已经用过很多内置函数了：print()、input()、len()、max()...
# 这一章学习【自己定义】函数。

# ============================================================
# 一、为什么需要函数？
# ============================================================
# ① 避免重复代码：同一段逻辑写 N 遍，不如定义一次调用 N 次
# ② 方便修改：改一处，所有调用点都生效
# ③ 逻辑清晰：把大问题拆成小函数，每个函数干一件事

# 例子：没有函数时，算三次圆的面积要写三遍公式
r1, r2, r3 = 2, 3, 4
# print(3.14 * r1 * r1)
# print(3.14 * r2 * r2)
# print(3.14 * r3 * r3)
# 有了函数，一行调用搞定（见下面）


# ============================================================
# 二、定义和调用
# ============================================================
# 语法：def 函数名(参数):
#           函数体
# 调用：函数名(实参)

def area(r):                 # 定义：名字叫 area，需要 1 个参数 r
    return 3.14 * r * r      # return：把结果返回给调用者

print(area(2))   # → 12.56（调用，传 2）
print(area(3))   # → 28.26
print(area(4))   # → 50.24
# 写一次公式，调三次——这就是函数的意义


# ============================================================
# 三、函数的基本结构
# ============================================================
def greet(name):          # def + 函数名 + (参数) + 冒号
    """打印欢迎语"""       # 可选：文档字符串，说明函数作用
    print("你好，", name, "！", sep="")

greet("小明")   # → 你好，小明！
greet("小红")   # → 你好，小红！

# 定义函数时：name 叫【形参】（占位符）
# 调用函数时："小明" 叫【实参】（实际传入的值）


# ============================================================
# 四、函数的执行流程
# ============================================================
def demo():
    print("第 1 行")
    print("第 2 行")

print("调用前")
demo()               # 调用时，跳到函数里执行，执行完回到这里
print("调用后")
# 输出顺序：调用前 → 第1行 → 第2行 → 调用后


