# ============================================================
# 一、return 的作用
# ============================================================
# return 做两件事：
#   1. 结束函数执行（后面的代码不再运行）
#   2. 把值"交还"给调用者

def square(x):
    return x * x       # 返回值
    print("这句不会执行！")  # return 后面的代码永远不跑

result = square(5)     # 用变量接住返回值
print(result)          # → 25
print(square(3) + 1)   # → 10（返回值可以直接参与运算）


# ============================================================
# 二、没有 return 的函数返回 None
# ============================================================
def say_hello():
    print("你好")       # 只有 print，没有 return

x = say_hello()        # 输出：你好
print(x)               # → None（没有 return 就返回 None）

# None 是 Python 的特殊值，表示"什么都没有"
# 这就是 print(lst.sort()) 打印 None 的原因——sort() 没有 return！


# ============================================================
# 三、return 提前退出（条件判断）
# ============================================================
def check_age(age):
    if age < 0 or age > 150:
        return "非法年龄"    # 提前返回，函数结束
    if age >= 18:
        return "成年"
    return "未成年"

print(check_age(20))   # → 成年
print(check_age(10))   # → 未成年
print(check_age(999))  # → 非法年龄（提前退出）


# ============================================================
# 四、返回多个值 — 其实返回的是元组！
# ============================================================
def get_min_max(lst):
    return min(lst), max(lst)   # 返回一个元组

result = get_min_max([3, 1, 4, 1, 5])
print(result)           # → (1, 5)

mn, mx = get_min_max([3, 1, 4, 1, 5])  # 解包接住
print(mn, mx)           # → 1 5
# 底层：return a, b 相当于 return (a, b)


