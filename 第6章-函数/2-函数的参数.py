# ============================================================
# 函数的参数 — 传入数据的各种方式
# ============================================================

# ============================================================
# 一、位置参数（最常用）
# ============================================================
# 按顺序传参，第一个给第一个形参，第二个给第二个
def add(a, b):
    return a + b

print(add(3, 5))    # → 8（3 给 a，5 给 b）
# add(3)            ← 报错！少传一个参数


# ============================================================
# 二、关键字参数 — 按名字传，顺序可以乱
# ============================================================
def describe(name, age, city):
    print(f"{name}，{age}岁，住在{city}")

describe("小明", 18, "北京")          # 位置参数
describe(city="上海", age=20, name="小红")  # 关键字参数（顺序无关）
# → 小红，20岁，住在上海

# 混用：位置参数必须在前面，关键字参数在后面
describe("小刚", city="广州", age=22)   # ✅
# describe(city="广州", "小刚", 22)     # ❌ 关键字参数不能在位置参数前面


# ============================================================
# 三、默认值参数 — 不传就用默认值
# ============================================================
def greet(name, greeting="你好"):
    print(greeting, name)

greet("小明")              # → 你好 小明（用默认值）
greet("小红", "早上好")     # → 早上好 小红（覆盖默认值）

# 有默认值的参数要放在没有默认值参数的后面
# def f(a=1, b):   ❌ 语法错误！b 没有默认值却在 a 后面


# ============================================================
# 四、可变参数 *args — 传任意多个位置参数
# ============================================================
# *args 会把所有多余的位置参数收集成一个元组
def sum_all(*nums):
    total = 0
    for n in nums:
        total += n
    return total

print(sum_all(1, 2))          # → 3
print(sum_all(1, 2, 3, 4, 5)) # → 15
print(sum_all())              # → 0（可以一个都不传）


# ============================================================
# 五、关键字可变参数 **kwargs — 传任意多个关键字参数
# ============================================================
# **kwargs 会把所有多余的关键字参数收集成一个字典
def show_info(**info):
    for k, v in info.items():
        print(k, "=", v)

show_info(name="小明", age=18)
# → name = 小明
# → age = 18


# ============================================================
# 六、参数传递的核心：可变 vs 不可变
# ============================================================
# 不可变类型（数字/字符串/元组）：函数里改，外面不变（传的是"值"）
def change_num(x):
    x = 100          # 改的是副本
n = 5
change_num(n)
print(n)             # → 5（没变！）

# 可变类型（列表/字典/集合）：函数里改，外面也变（传的是"引用"）
def add_item(lst):
    lst.append(99)   # 直接改的是同一个列表
mylist = [1, 2]
add_item(mylist)
print(mylist)        # → [1, 2, 99]（变了！）

# 想让函数不修改外部列表，传副本：add_item(mylist[:])


# ============================================================
# 七、实战：综合运用
# ============================================================
def make_profile(name, age, city="未知", *hobbies):
    """生成一个个人信息字典"""
    profile = {"name": name, "age": age, "city": city}
    if hobbies:
        profile["hobbies"] = hobbies
    return profile

p = make_profile("小明", 18, "北京", "篮球", "编程")
print(p)
# → {'name': '小明', 'age': 18, 'city': '北京', 'hobbies': ('篮球', '编程')}
