# ============================================================
# lambda 匿名函数 — 一行定义的小函数
# ============================================================
# 语法：lambda 参数: 返回值
# 相当于一个"没有名字的迷你函数"，适合只用一次的小逻辑。

# ============================================================
# 一、基本用法
# ============================================================
# 普通函数写法
def add1(x, y):
    return x + y

# lambda 写法（一行搞定）
add2 = lambda x, y: x + y

print(add1(3, 5))   # → 8
print(add2(3, 5))   # → 8
# lambda x, y: x + y
#   ↑参数      ↑返回值（不用写 return）


# ============================================================
# 二、lambda 的招牌用法：配合 sorted() 的 key 参数
# ============================================================
# 按字符串长度排序
words = ["apple", "hi", "banana", "a"]
print(sorted(words, key=len))       # → ['a', 'hi', 'apple', 'banana']

# 等价写法（key 传一个函数）
print(sorted(words, key=lambda w: len(w)))  # 同上

# 按字典的值排序
scores = {"语文": 90, "数学": 85, "英语": 95}
print(sorted(scores, key=lambda k: scores[k]))
# → ['数学', '语文', '英语']（按分数从低到高的科目名）

# 按元组第二个元素排序
students = [("小明", 18), ("小红", 20), ("小刚", 16)]
print(sorted(students, key=lambda s: s[1]))
# → [('小刚', 16), ('小明', 18), ('小红', 20)]


# ============================================================
# 三、配合 max/min 用
# ============================================================
# 找分数最高的科目
scores = {"语文": 90, "数学": 85, "英语": 95}
print(max(scores, key=lambda k: scores[k]))   # → 英语
# 这就是之前 max(count, key=count.get) 的原理！


# ============================================================
# 四、lambda 的局限
# ============================================================
# 只能写一行表达式，不能有 if-else 语句块、不能有循环
# 逻辑复杂时，用普通 def 函数，别硬塞 lambda

# lambda 适合：逻辑简单、只用一次
# def 适合：逻辑复杂、要复用、要文档
