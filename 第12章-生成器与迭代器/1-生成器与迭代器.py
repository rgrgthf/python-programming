# ============================================================
# Python 进阶 ② — 生成器与迭代器
# ============================================================
# 迭代器：能"一个一个取元素"的对象（for 循环就是用它）
# 生成器：一种"惰性"的迭代器——用到才生成，省内存！
# 处理大数据（几十万行实验数据）时是救命技能。

# ============================================================
# 一、可迭代对象 vs 迭代器
# ============================================================
# 可迭代对象（iterable）：能 for 循环的（列表、字符串、字典、文件...）
# 迭代器（iterator）：能"一个一个取"的对象

lst = [1, 2, 3]
it = iter(lst)           # 把列表变成迭代器
print(next(it))          # → 1（取下一个）
print(next(it))          # → 2
print(next(it))          # → 3
# print(next(it))        # → StopIteration（取完了会报这个）

# for 循环的本质就是：反复 next() 直到 StopIteration
for x in [1, 2, 3]:
    print(x, end=" ")
print()

# ============================================================
# 二、生成器函数（yield）
# ============================================================
# 普通函数用 return 返回一次就结束
# 生成器函数用 yield：每 yield 一次，暂停保存状态，下次从这继续

def count_down(n):
    while n > 0:
        yield n          # 每次到这里就"交出一个值"并暂停
        n -= 1

g = count_down(3)
print(next(g))    # → 3
print(next(g))    # → 2
print(next(g))    # → 1

# 也可以直接 for
for x in count_down(3):
    print(x, end=" ")    # → 3 2 1
print()

# ============================================================
# 三、为什么要用生成器？— 省内存！
# ============================================================
# 场景：生成 1000 万个数的序列
import sys

# 方法1：列表（全存内存）
lst = [i * 2 for i in range(10_000_000)]
print("列表内存：", sys.getsizeof(lst) / 1024 / 1024, "MB")   # ~80MB

# 方法2：生成器（边算边给，不存）
gen = (i * 2 for i in range(10_000_000))   # 生成器表达式（圆括号！）
print("生成器内存：", sys.getsizeof(gen), "字节")   # 只有几百字节！

# 用 for 消费生成器（不占内存）
# for x in gen:
#     if x > 100:
#         break

# 关键区别：
#   列表推导式 [x for x in ...] → 一次性算出所有，存内存
#   生成器表达式 (x for x in ...) → 用到一个算一个

# ============================================================
# 四、生成器 vs 列表推导式
# ============================================================
# 列表推导式（[]）
squares_list = [x ** 2 for x in range(10)]
print(squares_list)   # → [0, 1, 4, 9, ...]

# 生成器表达式（()）
squares_gen = (x ** 2 for x in range(10))
print(squares_gen)    # → <generator object ...>
print(list(squares_gen))   # 转成列表才能看到全部

# 选择：
#   数据量小、要重复用 → 列表
#   数据量大、只用一次 → 生成器

# ============================================================
# 五、文件逐行读取（生成器的经典应用）
# ============================================================
# 大文件（几GB）不能一次读完，for line in f 就是惰性逐行读
# 这就是生成器的原理：文件对象本身就是惰性迭代器

# 模拟：读取超长文件（教学用少量数据）
with open("large.txt", "w") as f:
    for i in range(1000):
        f.write(f"第{i}行数据\n")

# 逐行处理，内存恒定
count = 0
with open("large.txt") as f:
    for line in f:          # 一次只读一行进内存！
        count += 1
print("总行数：", count)

# ============================================================
# 六、生成器实战：批量处理实验数据
# ============================================================
# 场景：读取上百万行实验数据，只保留满足条件的
def filter_large_data(filename, threshold):
    """生成器：逐行读取，只产出数值大于 threshold 的行"""
    with open(filename) as f:
        for line in f:
            value = float(line.strip())
            if value > threshold:
                yield value

# 生成测试数据
import random
with open("data_big.txt", "w") as f:
    for _ in range(10000):
        f.write(f"{random.random() * 100:.2f}\n")

# 用生成器过滤（内存几乎不涨）
big_values = filter_large_data("data_big.txt", 90)
over_90 = sum(1 for _ in big_values)   # 统计>90的个数
print("大于90的个数：", over_90)

