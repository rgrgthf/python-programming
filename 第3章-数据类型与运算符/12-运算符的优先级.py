# ============================================================
# 各组优先级单独演示
# ============================================================

# --- ① ** 最高 ---
print(-3 ** 2)   # → -9    （先算 3²=9，再取负）
print((-3) ** 2) # → 9     （括号改变了顺序）

# --- ② ~ 和一元 - 同级，从右向左 ---
print(~12)   # → -13    （~n = -n-1）
print(~-5)   # → 4      （先 -5=-5，再 ~(-5)=4）
print(-~5)   # → 6      （先 ~5=-6，再 -(-6)=6）

# --- ③ * / // % 优先于 ④ + - ---
print(2 + 3 * 4)    # → 14    （3*4=12，2+12=14）
print((2 + 3) * 4)  # → 20    （括号优先）

# --- ④ + - 优先于 ⑤ 移位 ---
print(3 + 1 << 1)   # → 8     （先 3+1=4，再 4<<1=8）

# --- ⑤ 移位 优先于 ⑥⑦⑧ 位运算 ---
print(1 << 2 & 4)   # → 4     （先 1<<2=4，再 4&4=4）

# --- ⑥ & 优先于 ⑦ ^ ---
print(3 & 1 ^ 2)    # → 3     （先 3&1=1，再 1^2=3）

# --- ⑦ ^ 优先于 ⑧ | ---
print(1 ^ 2 | 4)    # → 7     （先 1^2=3，再 3|4=7）

# --- ⑧ 位运算 优先于 ⑨ 比较 ---
print(3 | 4 == 7)   # → True  （先 3|4=7，再 7==7）

# --- ⑨ 比较 优先于 ⑩⑪⑫ 逻辑 ---
print(5 > 3 and 2 < 1)      # → False （先比较，再 and）
print(not 5 > 3)            # → False （先 5>3=True，再 not）

# --- ⑪ and 优先于 ⑫ or ---
print(False and False or True)   # → True  （先 and，再 or）
print(False and (False or True)) # → False （括号改变顺序）
print()

# ============================================================
# 补充：比较运算符链（Python 特有）
# ============================================================
# 注意：a < b < c 等价于 a < b and b < c
print(3 < 5 < 7)    # → True    （3<5 and 5<7）
print(10 > 5 != 6)  # → True    （10>5 and 5!=6）

# ============================================================
# 补充：短路求值（and / or）
# ============================================================
# and：左边为 False 时右边不执行
# or：左边为 True 时右边不执行
a = 3 > 2   # True
print(a or 10 / 0)  # → True    （a已经是True，不执行10/0，不会报错）
print(not a and 10 / 0)  # → False （not a 是 False，不执行10/0）

