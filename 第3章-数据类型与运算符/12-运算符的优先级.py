# ============================================================
# 运算符的优先级（从高到低）
# ============================================================
# ① **       幂运算（最高）
# ② ~ + -    按位取反、一元正负号
# ③ * / // % 乘、除、整除、取余
# ④ + -      加、减
# ⑤ << >>    左移、右移
# ⑥ &        按位与
# ⑦ ^        按位异或
# ⑧ |        按位或
# ⑨ == != > < >= <= is in  比较运算
# ⑩ not      逻辑非
# ⑪ and      逻辑与
# ⑫ or       逻辑或（最低）

# ============================================================
# 一条龙示例：一个表达式走完 12 级优先级
# ============================================================
# 下面每一步都标出了"当前谁在驱动运算"

result = ~-2 ** 3 + 4 * 5 // 6 % 7 - 8 << 1 >> 2 & 3 ^ 4 | 5 == 6 and not 7 > 8 or 9 < 10

# ① ** 幂运算
#    2 ** 3 → 8
# →  ~-8 + 4*5//6%7 - 8<<1>>2 & 3 ^ 4 | 5==6 and not 7>8 or 9<10

# ② ~ 和一元 -（从右向左）
#    一元 -：-8 = -8
#    ~：~(-8) → 7    （公式 ~n = -n-1）
# →  7 + 4*5//6%7 - 8<<1>>2 & 3 ^ 4 | 5==6 and not 7>8 or 9<10

# ③ * // %（从左向右）
#    4*5 → 20
#    20//6 → 3
#    3%7 → 3
# →  7 + 3 - 8<<1>>2 & 3 ^ 4 | 5==6 and not 7>8 or 9<10

# ④ + -（二元加减，从左向右）
#    7+3 → 10
#    10-8 → 2
# →  2<<1>>2 & 3 ^ 4 | 5==6 and not 7>8 or 9<10

# ⑤ << >>（从左向右）
#    2<<1 → 4    （10 左移1位 → 100）
#    4>>2 → 1    （100 右移2位 → 1）
# →  1 & 3 ^ 4 | 5==6 and not 7>8 or 9<10

# ⑥ &  1&3 → 1    （01 & 11 = 01）
# →  1 ^ 4 | 5==6 and not 7>8 or 9<10

# ⑦ ^  1^4 → 5    （001 ^ 100 = 101）
# →  5 | 5==6 and not 7>8 or 9<10

# ⑧ |  5|5 → 5
# →  5==6 and not 7>8 or 9<10

# ⑨ == > <
#    5==6 → False
#    7>8  → False
#    9<10 → True
# →  False and not False or True

# ⑩ not  not False → True
# →  False and True or True

# ⑪ and  False and True → False
# →  False or True

# ⑫ or   False or True → True ✅

print(result)  # → True
print()

