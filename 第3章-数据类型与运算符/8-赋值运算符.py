#赋值运算符有以下几种：
# = 简单的赋值 如x=y 将y赋值给x
# += 加法赋值 如x+=y 将y加到x上，然后将结果x+y赋值给x
# -= 减法赋值 如x-=y 将y减到x上，然后将结果x-y赋值给x
# *= 乘法赋值 如x*=y 将y乘到x上，然后将结果x*y赋值给x
# /= 除法赋值 如x/=y 将y除到x上，然后将结果x/y赋值给x
# **= 幂运算赋值 如x**=y 将y的幂次方到x上，然后将结果x**y赋值给x
# %= 取余赋值 如x%=y 将y取余到x上，然后将结果x%y赋值给x
# //= 整除赋值 如x//=y 将y整除到x上，然后将结果x//y赋值给x
#示例
x = 20
y = 10
x = x + y  # 此时x已被赋值为30，将覆盖原来的值20
print(x)  # 输出30
x += y  # 将x+y的值（30+10=40）赋值给x，此时x的值为40
print(x)  # 输出40
x -= y  # 将x-y的值40-10=30赋值给x，此时x的值为30
print(x)  # 输出30
x *= y  # 将x*y的值30*10=300赋值给x，此时x的值为300
print(x)  # 输出300
x /= y  # 将x/y的值300/10=30.0赋值给x，此时x的值为30.0
print(x, type(x))  # 输出30.0 float
#注意：Python 3 中 / 除法无论能否整除，结果一定是 float（300/10→30.0 而非 30）
#这和复数 .real/.imag 总是返回 float 的道理类似——运算结果"可能"带小数，Python 默认走浮点
#如果希望得到整数商，用 //（地板除），如 300//10 → 30（int）
x = int(x)  # 将30.0转换为整数30，此时x的值为30
print(x, type(x))  # 输出30 int
x **= y  # 将x**y的值30**10=59049000000赋值给x，此时x的值为5904900000
print(x)
x //= y  # 将x//y的值5904900000//10=590490000赋值给x，此时x的值为590490000
print(x)  # 输出590490000
x %= y  # 将x%y的值590490000%10=0赋值给x，此时x的值为0
print(x)  # 输出0

#python支持链式赋值
a = b = c = 100
print(a, b, c)
#python还支持系列解包赋值
a, b = 10, 20  # 相当于a=10，b=20
print(a, b)
#如何交换两个变量的值呢？
a, b = b, a
print(a, b)  # 输出 20 10

