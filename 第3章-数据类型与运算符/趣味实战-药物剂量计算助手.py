print("=" * 36)
print("💊  药物剂量计算助手  v1.0")
print("=" * 36)

# ---- 1. 输入数据（input 返回字符串 → 用 float() 转数字）----
weight = float(input("🐭 请输入体重 (kg): "))
dose_per_kg = float(input("💉 每公斤剂量 (mg/kg): "))

# ---- 2. 计算（乘法运算符）----
total = weight * dose_per_kg

# ---- 3. 判断剂量是否合理（if 判断）----
print("-" * 36)
if total > 500:
    print(f"⚠️ 总剂量 {total:.1f} mg 偏大，请核对剂量！")
elif total <= 0:
    print("❌ 输入有误，体重和剂量必须为正数")
else:
    print("✅ 剂量在合理范围")

print(f"🐭 体重: {weight} kg")
print(f"💉 剂量: {dose_per_kg} mg/kg")
print(f"💊 单次总剂量: {total:.1f} mg")
print("=" * 36)
print("🎉 恭喜！你已经用 Python 做出一个医药小工具！")
