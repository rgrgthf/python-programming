# ============================================================
# 数值类型（Numeric Types）
# ============================================================
# Python 支持 4 种数值类型：int、float、bool、complex

# ============================================================
# 一、整数 int — 没有大小限制（只受内存限制）
# ============================================================
a = 100              # 十进制
b = -50              # 负整数
c = 0                # 零

# 不同进制表示
bin_num = 0b1010     # 二进制 → 10
oct_num = 0o77       # 八进制 → 63
hex_num = 0xFF       # 十六进制 → 255

print(bin_num, oct_num, hex_num)  # → 10 63 255

# 大数字可以用下划线分隔，方便阅读（Python 3.6+）
big = 1_000_000_000  # 十亿，等价于 1000000000
print(big)
# ============================================================
# 二、浮点数 float — 即小数（双精度，约 15~17 位有效数字）
# ============================================================
x = 3.14
y = -0.5
z = 1.5e3            # 科学计数法 → 1500.0
print(z)

# 注意：浮点数有精度问题！
print(0.1 + 0.2)     # → 0.30000000000000004（不是精确的 0.3）
#如果只想保留两位小数，可以使用 round() 函数：
print(round(0.1 + 0.2, 2))  # → 0.3 2表示保留两位小数

# ============================================================
# 三、布尔类型 bool — True 和 False（本质是 int 的子类）
# ============================================================
t = True
f = False
print(t, type(t))    # → True <class 'bool'>
# bool 可以参与数学运算（True=1，False=0）
print(True + 1)      # → 2
print(False + 1)     # → 1
#可以用print（）的内置函数bool()来判断一个数值的真假
print(bool("")) #空字符串的布尔值是False
print(bool(0))       # → False
print(bool("你好"))  # → True（非空字符串为 True）


# 以下值被视为 False：
# None, 0, 0.0, ""（空字符串）, []（空列表）, {}（空字典）, ()（空元组）
print(bool(0))       # → False
print(bool("你好"))  # → True（非空字符串为 True）
print(bool([]))      # 空列表为 False
print(bool({}))     # 空字典为 False
print(bool(()))      # 空元组为 False
print(bool(None))    # None 为 False


# ============================================================
# 四、复数 complex — 数学中的复数（实部 + 虚部 j）j=√-1，就是数学中的 i
# ============================================================
c1 = 3 + 4j
c2 = complex(1, 2)   # → 1+2j
print(c1.real)       # → 3.0（实部）.real 属性返回复数的实部
print(c1.imag)       # → 4.0（虚部）.imag 属性返回复数的虚部

# ============================================================
# 五、类型转换
# ============================================================
#int() 将数据类型转为整数
#float() 将数据类型转为浮点数
#bool() 将数据类型转为布尔值
#str() 将数据类型转为字符串
#chr() 将整数转为对应unicode码的字符
#ord() 将字符转为对应unicode码的整数
#hex() 将整数转为十六进制字符串，以0x开头
#oct() 将整数转为八进制字符串，以0o开头
#bin() 将整数转为二进制字符串，以0b开头
print(int(3.9))       # → 3（截断，不是四舍五入）
print(float(10))      # → 10.0
print(bool(100))      # → True
print(int(True))      # → 1
print(bool(False))     # → False
print(str(True))      # → "True"

print(chr(97))       # → 'a'
print(ord('a'))       # → 97

print(hex(255))      # → '0xff'
print(oct(64))       # → '0o100'
print(bin(8))        # → '0b1000'
#转换的结果是字符串，需要转换成相应的数据类型才能使用

# 字符串转数字
print(int("123"))     # → 123
print(float("3.14"))  # → 3.14
#将字符串转成int或float时报错的情况
print(int("3.14"))   # 报错：ValueError: invalid literal for int() with base 10: '3.14'
print(float("abc"))    # 报错：ValueError: coul

