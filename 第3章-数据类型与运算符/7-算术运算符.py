#算术运算符有以下几种：
# + - * /  加减乘除
print(5 + 3, 5 - 3, 5 * 3, 5 / 3)  # → 8 2 15 1.6666666666666667
# //       整除（向下取整）  7 // 2 → 3
# %        取余              7 % 2  → 1
# **       幂运算            2 ** 3  → 8
print(7 // 2, 7 % 2, 2 ** 3)  # → 3 1 8
#算术运算符的优先级从高到低是
# 1. **（幂运算）
# 2. *、/、//、%
# 3. +、-

