# ============================================================
# 变量与常量
# ============================================================
# 语法：变量名 = 值
# "=" 是赋值运算符，不是数学上的等号
# Python 不需要声明类型，类型由值决定（动态类型）

# ============================================================
# 一、变量的定义和使用
# ============================================================
user_name = "小明"     # 字符串 str（推荐 snake_case 命名）
user_age = 18            # 整数 int

# type() 查看变量类型
print(type(user_name))   # → <class 'str'>
print(type(user_age))    # → <class 'int'>

print(user_name, "的年龄是", user_age, sep="")

# ============================================================
# 二、动态类型 — 变量类型可以随时改变
# ============================================================
user_name = 100          # 同一变量重新赋值为整数
print(type(user_name))   # → <class 'int'>（类型已改变）

# ============================================================
# 三、多个变量指向同一值
# ============================================================
no = number = 100        # 链式赋值，两个变量指向同一个整数对象
print(no, number, sep=" ")

# id() 查看内存地址，相同值可能复用同一地址（小整数池）
print(id(no), id(number), sep=" ")  # 两个地址相同，说明是同一对象

# ============================================================
# 四、多变量同时赋值（解包 / unpacking）
# ============================================================
x, y, z = 1, 2, 3
print(x, y, z)           # → 1 2 3

# 交换两个变量的值（无需中间变量！）
a, b = 10, 20
a, b = b, a
print(a, b)              # → 20 10

# ============================================================
# 五、常量
# ============================================================
# Python 没有真正的常量机制，约定用 UPPER_CASE（全大写）表示"不要修改"
PI = 3.1415926
MAX_CONNECTIONS = 100
# 技术上仍可修改，但这是开发者之间的约定，不应违背

