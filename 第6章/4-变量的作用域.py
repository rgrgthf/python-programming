# ============================================================
# 变量的作用域 — 变量能"活"在哪里
# ============================================================
# 作用域（scope）= 变量的"活动范围"。
# Python 中主要分：局部变量 和 全局变量。

# ============================================================
# 一、局部变量 — 函数里定义的
# ============================================================
def my_func():
    x = 10           # 局部变量：只在函数内部有效
    print(x)         # 函数内部能用

my_func()            # → 10
# print(x)           ← 报错！NameError，外面访问不到局部变量


# ============================================================
# 二、全局变量 — 模块顶层定义的
# ============================================================
y = 100              # 全局变量：整个文件都能访问

def show():
    print(y)         # 函数内部能【读取】全局变量

show()               # → 100
print(y)             # → 100（外面也能用）


# ============================================================
# 三、⚠️ 读取 vs 修改 —— 最重要的区别
# ============================================================
count = 0

def read_it():
    print(count)     # 只读：没问题，能读到全局的 0

def write_it():
    count = 5        # 赋值：Python 认为你创建了一个【新的局部变量】！
    # 并不会修改全局 count！

read_it()            # → 0
write_it()
print(count)         # → 0（全局变量没被改！函数里的 count=5 是局部的）

# 想修改全局变量，必须声明 global：
def really_write():
    global count     # 声明：我要改的是全局变量
    count = 5

really_write()
print(count)         # → 5（这次真的改了）


# ============================================================
# 四、global 的使用场景
# ============================================================
# 尽量少用 global！更好的做法是"参数传入，返回值传出"
total = 0

# 不好的做法（用 global）
def add_bad(n):
    global total
    total += n

# 好的做法（传参 + 返回值）
def add_good(total, n):
    return total + n

# 函数应该是"黑盒"：输入参数 → 输出结果，不偷偷改外面的变量


# ============================================================
# 五、作用域查找顺序 LEGB
# ============================================================
# Python 找变量按这个顺序：
#   L Local    局部 → 函数内部
#   E Enclosing 外层函数（嵌套函数时）
#   G Global   全局 → 模块顶层
#   B Builtin  内置 → 如 print、len

x = "全局"           # G

def outer():
    x = "外层"       # E
    def inner():
        x = "内层"   # L
        print(x)
    inner()

outer()              # → 内层（先找最近的）
# 记住：找变量从内往外找，第一个找到的说了算


# ============================================================
# 六、总结一句话
# ============================================================
# 函数内能读全局，但想改全局必须 global。
# 最佳实践：函数参数传入 + return 返回，尽量别碰全局变量。
