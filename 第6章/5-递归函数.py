# 默认递归深度约 1000 层，超过会报 RecursionError
# fib(1000) 用这个写法会非常慢甚至卡死（重复计算太多）

# 实战建议：递归适合"层级清晰"的问题（如文件夹遍历），
# 数值计算类（阶乘、斐波那契）用循环更稳。
