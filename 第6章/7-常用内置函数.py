# ============================================================
# 常用内置函数 — 编程高频工具
# ============================================================
# 这些函数不用 import，直接用。按用途分类。

# ============================================================
# 一、数值类
# ============================================================
print(abs(-5))          # → 5（绝对值）
print(round(3.14159, 2))# → 3.14（四舍五入保留 2 位）
print(pow(2, 10))       # → 1024（幂运算，等价于 2**10）
print(max(3, 7, 2))     # → 7（最大值）
print(min([5, 1, 9]))   # → 1（最小值，也能传列表）
print(sum([1, 2, 3]))   # → 6（求和，只适用于数字）

# 也可以带 key：
print(max("hello", key=len))    # → hello


# ============================================================
# 二、类型转换类
# ============================================================
print(int("42"))        # → 42
print(float("3.14"))    # → 3.14
print(str(123))         # → '123'
print(bool(0))          # → False
print(list("abc"))      # → ['a', 'b', 'c']
print(tuple([1, 2]))    # → (1, 2)
print(set("aabb"))      # → {'a', 'b'}


# ============================================================
# 三、序列操作类
# ============================================================
# sorted()：排序，返回新列表（不改变原数据）
lst = [3, 1, 2]
print(sorted(lst))      # → [1, 2, 3]
print(lst)              # → [3, 1, 2]（原列表没变！和 sort() 不同）
print(sorted(lst, reverse=True))   # → [3, 2, 1]

# reversed()：反转（返回迭代器，需转 list）
print(list(reversed([1, 2, 3])))   # → [3, 2, 1]

# enumerate()：同时拿到下标和元素
for i, ch in enumerate("abc"):
    print(i, ch)        # 0 a / 1 b / 2 c

# zip()：把多个序列按位置配对
names = ["小明", "小红"]
ages = [18, 20]
for n, a in zip(names, ages):
    print(n, a)         # 小明 18 / 小红 20
print(dict(zip(names, ages)))   # → {'小明': 18, '小红': 20}


# ============================================================
# 四、判断类
# ============================================================
print(all([True, True, False]))   # → False（全部为真才 True）
print(any([False, True, False]))  # → True（有一个为真就 True）
print(all([1, 2, 3]))             # → True（非零即真）
print(any([0, "", 3]))            # → True

# isinstance()：判断类型
print(isinstance(5, int))        # → True
print(isinstance("hi", str))     # → True
print(isinstance([1], list))     # → True


# ============================================================
# 五、实战：综合运用
# ============================================================
# 找出列表中出现次数最多的元素
nums = [1, 2, 2, 3, 3, 3, 4, 4, 4, 4]
print(max(set(nums), key=nums.count))   # → 4

# 一句话理解 max(set, key=nums.count)：
# 对去重后的每个数，用"它在原列表的出现次数"作为比较标准，
# 取出次数最大的那个数
