# 五、循环变量命名约定
# ============================================================
# 临时变量用单字母（i, j, k）
# 有意义时用描述性名称
for student in ["张三", "李四", "王五"]:
    print(student)

# 不关心循环变量的值时，用 _ 占位
for _ in range(3):
    print("重要的事情说三遍")

