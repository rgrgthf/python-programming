# 四、for-else — 循环正常结束才执行 else
# ============================================================
# 如果 for 循环没有被 break 打断，结束后会执行 else。
# 经典场景：查找 → 找到了 break，找不到走 else。

# ① 判断质数（素数）
num = 29
for i in range(2, int(num ** 0.5) + 1):
    if num % i == 0:
        print(num, "不是质数")
        break
else:
    print(num, "是质数")  # 没找到因子 → 是质数

# ② 找第一个能被 7 整除的数（用 break）
for i in range(1, 100):
    if i % 7 == 0:
        print("找到了：", i)  # → 7
        break
else:
    print("没找到")  # ← break 了，这行不执行

# ③ 找第一个能被 7 整除的数（不用 break，对比）
for i in range(1, 6):       # 1~5，都没有 7 的倍数
    if i % 7 == 0:
        break
else:
    print("1~5 中没有 7 的倍数")  # ← 循环自然结束，else 执行！
