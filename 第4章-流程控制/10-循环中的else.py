# if is_prime:
#     print("是质数")
# else:
#     print("不是质数")
# for-else 省掉了标志变量 is_prime，更简洁


# ============================================================
# 四、while-else 同理
# ============================================================
attempts = 0
while attempts < 3:
    pwd = input("密码：")
    if pwd == "123456":
        print("登录成功")
        break
    attempts += 1
else:
    print("3 次机会用完，账号已锁定")
# 密码对了 → break 跳出，else 不执行
# 3 次都错  → 循环自然结束，else 执行 → 锁定


