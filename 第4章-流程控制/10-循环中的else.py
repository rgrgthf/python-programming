# ============================================================
# 循环中的 else — Python 特有语法
# ============================================================
# for-else 和 while-else：当循环"自然结束"（非 break 退出）时，执行 else。
# 注意：这个 else 和 if-else("否则") 没关系，理解为 then（"之后"）更准确。

# ============================================================
# 一、for-else 基本用法
# ============================================================
for i in range(3):
    print(i)
else:
    print("循环正常结束")  # 循环跑完了，没被 break → 执行 else

# 输出：
# 0
# 1
# 2
# 循环正常结束


# ============================================================
# 二、break 会"跳过" else
# ============================================================
for i in range(5):
    if i == 3:
        print("找到了，退出")
        break
else:
    print("没找到")  # ← break 了，这行不执行！

# 输出：找到了，退出
# （没有"没找到"）


# ============================================================
# 三、经典场景：判断质数
# ============================================================
# 这就是 for-else 最漂亮的用法！
num = int(input("请输入一个大于 1 的整数："))

for i in range(2, int(num ** 0.5) + 1):
    if num % i == 0:
        print(num, "不是质数，能被", i, "整除")
        break  # 找到因子 → 不是质数
else:
    print(num, "是质数")  # break 从未触发 → 是质数

# ---- 为什么只试到 √num 就够了？----
# 质数定义：大于 1 的自然数，且只有 1 和它本身两个因数（1 不是质数）
# 数学原理：如果 num 是合数，一定能拆成 num = a × b，
#   而 a 和 b 中至少有一个 ≤ √num（否则两个都大于 √num，乘积就超过 num）
#   例：36 = 2×18 = 3×12 = 4×9 = 6×6，较小的因子最大就是 6 = √36
#   所以只要从 2 试到 √num 都没找到因子 → 必是质数，试到 num 是浪费时间
# 效率对比：
#   朴素写法 range(2, num)         → num=1000000 要试 999998 次
#   开根写法 range(2, int(num**0.5)+1) → 只要试 999 次，快 1000 倍
# 为什么 +1：int() 会截断小数，num=25 时 √25=5.0，int=5，
#   若写 range(2, 5) 会漏掉 5（25=5×5），误判为质数，+1 保证包含平方根本身

# 传统写法（不用 for-else）：
