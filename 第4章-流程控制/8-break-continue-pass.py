# 五、实战综合：登录系统（三次机会）
# ============================================================
password = "123456"
max_attempts = 3

for attempt in range(1, max_attempts + 1):
    pwd = input(f"请输入密码（第 {attempt}/{max_attempts} 次）：")
    if pwd == password:
        print("登录成功！")
        break  # 成功 → 退出循环
    else:
        remaining = max_attempts - attempt
        if remaining > 0:
            print(f"密码错误，还剩 {remaining} 次机会")
        else:
            print("三次机会已用完，账号已锁定")
# 注意：登录成功后 break 跳出，不会走到"账号锁定"

