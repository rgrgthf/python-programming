# ============================================================
# 循环控制 — break / continue / pass
# ============================================================
# break    → 立即退出整个循环（循环彻底结束）
# continue → 跳过本轮剩余代码，直接进入下一轮判断
# pass     → 什么都不做，只是占位符（和循环无关，常放在空代码块里）

# ============================================================
# 一、break — 强制退出
# ============================================================

# 找到第一个能被 7 和 3 同时整除的数
for i in range(1, 1000):
    if i % 7 == 0 and i % 3 == 0:
        print("找到了：", i)  # → 21
        break  # 找到就退出，后面的不找了


# ============================================================
# 二、continue — 跳过本轮
# ============================================================

# 打印 1~10 中的所有奇数（跳过偶数）
for i in range(1, 11):
    if i % 2 == 0:
        continue  # 偶数 → 跳过 print，直接进入下一轮
    print(i, end=" ")  # → 1 3 5 7 9
print()


# ============================================================
# 三、break vs continue 对比
# ============================================================
for i in range(1, 6):
    if i == 3:
        break        # i=3 时直接跳出，循环结束
    print(i, end=" ")
print()
# → 1 2

for i in range(1, 6):
    if i == 3:
        continue     # i=3 时跳过本轮，继续 i=4
    print(i, end=" ")
print()
# → 1 2 4 5


# ============================================================
# 四、pass — 占位符
# ============================================================
# pass 不干任何事，只用于"语法上需要写点什么但我还没想好怎么写"的地方

# ① 空函数（稍后实现）
def my_function():
    pass  # 占位，函数体不能为空

# ② 空类
class MyClass:
    pass

# ③ 空 if（极少用，但合法）
if True:
    pass  # 先占着，后面再写逻辑

# ④ 和 continue 的区别
for i in range(3):
    if i == 1:
        pass        # pass 什么都不做，下面 print 照常执行
    print(i, end=" ")
print()
# → 0 1 2

for i in range(3):
    if i == 1:
        continue    # continue 跳过 print
    print(i, end=" ")
print()
# → 0 2


