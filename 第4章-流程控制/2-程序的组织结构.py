# 程序的组织结构有三种，分别是顺序结构、选择/分支结构和循环结构

# ============================================================
# 一、顺序结构
# ============================================================
# 按程序语句的自然顺序，从上到下，依次执行每条语句。
# 这是最基本的结构，之前的例子几乎都是顺序结构。
#
# 示例：输入两个数，计算并输出和与差
a = int(input("请输入第一个数："))
b = int(input("请输入第二个数："))
print("和：", a + b)
print("差：", a - b)
# 执行顺序：输入a → 输入b → 输出和 → 输出差，一条接一条，没有跳转

# ============================================================
# 二、选择/分支结构
# ============================================================
# 根据条件判断，决定执行哪一段代码。Python 使用 if / elif / else。
#
# 示例：判断成绩等级
score = int(input("请输入成绩（0-100）："))
if score >= 90:
    print("优秀")
elif score >= 70:
    print("良好")
elif score >= 60:
    print("及格")
else:
    print("不及格")
# 只有一条分支会被执行，其余跳过


# ============================================================
# 三、循环结构
# ============================================================
# 让一段代码重复执行多次。Python 主要有 for 循环和 while 循环。
#
# 示例：求 1 + 2 + 3 + ... + 100 的和

# ① for 循环 — 已知循环次数时使用
total = 0
for i in range(1, 101):    # i 从 1 到 100
    total += i
print("1+2+...+100 =", total)  # → 5050

# ② while 循环 — 当条件满足时反复执行
total = 0
i = 1
while i <= 100:
    total += i
    i += 1
print("1+2+...+100 =", total)  # → 5050

# ============================================================
# 总结
# ============================================================
# 三种结构可以互相嵌套组合：
#   循环里可以有分支（遍历成绩，判断每个是否及格）
#   分支里可以有循环（输入密码，错误则重复输入）
#   顺序结构是最外层框架，任何程序都离不开它

