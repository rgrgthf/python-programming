# ============================================================
# 双分支结构 — if … else
# ============================================================
# 语法：if 条件:
#           条件成立时执行的代码
#       else:
#           条件不成立时执行的代码
# 两条路必走其一，不会都不执行，也不会都执行。

# ============================================================
# 一、基本示例
# ============================================================
age = int(input("请输入你的年龄："))
if age >= 18:
    print("已成年")
else:
    print("未成年")
print("程序结束")  # 无论走哪条分支，这行都会执行

# 对比 C++：Python 用冒号 + 缩进代替花括号
# C++:  if (age >= 18) { cout << "已成年"; }
#       else { cout << "未成年"; }


# ============================================================
# 二、if 和 if-else 的区别
# ============================================================
# if 单分支：       条件成立 → 执行，不成立 → 跳过
# if-else 双分支：  条件成立 → 走 if，不成立 → 走 else，必走一条

# 单分支 — 不成立就什么都不做
score = 95
if score >= 90:
    print("优秀")  # 95 → 输出"优秀"；85 → 什么都不输出

# 双分支 — 不成立就走 else
if score >= 90:
    print("优秀")
else:
    print("不是优秀")  # 95 → "优秀"；85 → "不是优秀"


