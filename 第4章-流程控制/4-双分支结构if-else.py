# 三、实战示例
# ============================================================

# ① 判断奇偶
num = int(input("请输入一个整数："))
if num % 2 == 0:
    print(num, "是偶数")
else:
    print(num, "是奇数")

# ② 登录验证
password = input("请输入密码：")
if password == "123456":
    print("登录成功！")
else:
    print("密码错误，登录失败")

# ③ 判断三角形能否构成
a = float(input("输入边长 a："))
b = float(input("输入边长 b："))
c = float(input("输入边长 c："))
if a + b > c and a + c > b and b + c > a:
    print("能构成三角形")
else:
    print("不能构成三角形")
# 三角形条件：任意两边之和大于第三边


# ============================================================
# 四、简化写法：条件表达式（三元运算）
# ============================================================
# 如果 if 和 else 里都只是简单赋值，可以一行搞定。
# 语法：变量 = 值1 if 条件 else 值2

age = 20
status = "成年" if age >= 18 else "未成年"
print(status)  # → 成年

# 等价于：
# if age >= 18:
#     status = "成年"
# else:
#     status = "未成年"

# 对比 C++ 的三目运算符：
# C++:  status = age >= 18 ? "成年" : "未成年";
# Python 把 ? 换成了 if，把 : 换成了 else，语序更接近自然语言


# ============================================================
# 五、常见坑
# ============================================================

# ① else 后面直接跟冒号，不能写条件
# if x > 0:
#     print("正数")
# else x < 0:          ← 错误！else 后面不能写条件
#     print("负数")
# 正确做法：多条件判断应使用 elif（参见下一节）

# ② 缩进不一致
# if True:
#     print("OK")
#   else:               ← 缩进和 if 不对齐，报 IndentationError
#     print("NO")
# 正确：else 必须和对应的 if 左对齐

# ③ else 和 if 之间不要插入不属于 if 的代码
# if x > 0:
#     print("正数")
# print("干扰行")       ← 这行不在 if 里，打断了 if-else 结构
# else:                 ← 报错！Python 不知道这个 else 跟哪个 if 配对
#     print("非正数")

