#比较运算符也叫对比运算符，用于比较两个值的大小关系。
# 运算的结果是布尔类型，只有True和False两种。
# Python中常用的比较运算符有以下几种：
# == 等于运算符，检查两个值是否相等，返回True或False
# != 不等于运算符，检查两个值是否不相等，返回True或False
# > 大于运算符，检查左边的值是否大于右边的值，返回True或False
# < 小于运算符，检查左边的值是否小于右边的值，返回True或False
# >= 大于等于运算符，检查左边的值是否大于等于右边的值，返回True或False
# <= 小于等于运算符，检查左边的值是否小于等于右边的值，返回True或False
#示例
print("98大于90吗？",98>90)
print("98小于90吗？",98<90)
print("98大于等于90吗？",98>=90)
print("98小于等于90吗？",98<=90)
print("98等于90吗？",98==90)
print("98不等于90吗？",98!=90)