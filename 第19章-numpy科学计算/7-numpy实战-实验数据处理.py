# ============================================================
# numpy 深入 ⑥ — 实战：实验数据批量处理
# ============================================================
# 综合运用：模拟一个真实的"酶标仪读板数据"处理场景，
# 把前面所有 numpy 知识串起来。

import numpy as np

# ============================================================
# 一、模拟原始数据
# ============================================================
# 酶标仪 96 孔板（8行×12列）的读数，先取 6×4 简化
np.random.seed(42)   # 固定随机种子，结果可复现

# 真实值：第1行对照，第2行给药低，第3行给药高
true_value = np.array([
    [1.0, 1.0, 1.0, 1.0],
    [0.7, 0.7, 0.7, 0.7],
    [0.4, 0.4, 0.4, 0.4],
])
# 加测量噪声（正态分布随机误差）
noise = np.random.normal(0, 0.05, true_value.shape)
raw = true_value + noise
print("原始读数：")
print(raw.round(3))
# [[1.02 0.96 0.99 1.01]
#  [0.72 0.66 0.70 0.68]
#  [0.38 0.41 0.43 0.39]]

# ============================================================
# 二、数据清洗：处理异常值
# ============================================================
# 假设出现一个异常读数（>2 或 <0）
raw[1, 2] = 2.5      # 手动制造一个异常值
print("异常值位置：", np.where(raw > 2))
# → (array([1]), array([2]))

# 方法：把超过 [0, 1.5] 的值替换为组内中位数
clean = raw.copy()
outlier_mask = (clean < 0) | (clean > 1.5)
clean[outlier_mask] = np.nan     # 先标为 NaN
print("标记异常后：")
print(clean)
# 用 nanmedian（忽略NaN的中位数）填充
row_medians = np.nanmedian(clean, axis=1)   # 每行中位数
print("每行中位数：", row_medians.round(3))

# 填充：把 NaN 替换成对应行的中位数
for i in range(clean.shape[0]):
    mask = np.isnan(clean[i])
    clean[i][mask] = row_medians[i]
print("清洗后：")
print(clean.round(3))

# ============================================================
# 三、组内统计
# ============================================================
means = clean.mean(axis=1)     # 每行均值（每组）
stds = clean.std(axis=1)       # 每行标准差
print("\n各组均值±标准差：")
for i, (m, s) in enumerate(zip(means, stds)):
    print(f"组{i}: {m:.3f} ± {s:.3f}")

# ============================================================
# 四、计算抑制率（相对对照组）
# ============================================================
control_mean = means[0]                        # 对照组均值
inhibition = (1 - means / control_mean) * 100  # 抑制率%
print("\n抑制率(%)：", inhibition.round(1))
# → 组0: 0%（对照本身），组1: ~30%，组2: ~60%

# ============================================================
# 五、批量生成浓度梯度（药理常用）
# ============================================================
# 用 logspace 生成 0.1 到 100 的 8 个浓度（对数梯度）
concs = np.logspace(-1, 2, 8)
print("\n浓度梯度(μM)：", concs.round(2))
# → [0.1  0.27 0.74 2.15 5.99 16.68 46.42 100.  ]

# ============================================================
# 六、结果整理与保存
# ============================================================
# 把结果合并成一个二维数组
result = np.column_stack([means, stds, inhibition])
print("\n汇总表（均值/标准差/抑制率%）：")
print(result.round(3))

# 保存到文件（numpy 自带）
np.save("result_array.npy", result)          # 二进制格式（快）
loaded = np.load("result_array.npy")         # 读回
print("读回验证：", loaded.round(3))

# 保存为 CSV（可被 Excel/pandas 打开）
np.savetxt("result.csv", result, delimiter=",",
           header="mean,std,inhibition(%)", comments="")
print("已保存 result.csv")

