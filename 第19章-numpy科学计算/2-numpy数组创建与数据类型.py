# ============================================================
# 七、易错点汇总
# ============================================================
# 1. np.arange(n) 是 [0,1,...,n-1]，【不含】n（和 range 一致）
# 2. np.linspace(0, 1, 5) 生成 5 个【含两端】的等距点；
#    arange 是步长控制，linspace 是数量控制——别搞混
# 3. dtype 是 numpy 的灵魂：int/float/uint 混用会出意外，
#    必要时用 .astype() 显式转换
# 4. np.zeros/np.ones 的括号里传的是【形状】(2,3)，不是两个参数
# 5. np.random 生成数组常用：
#    randn(标准正态) / uniform(均匀) / randint(整数)
# 6. 数据量不同用不同的创建方式：arange/linspace/zeros/ones

