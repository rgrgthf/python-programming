# ============================================================
# numpy 深入 ① — 数组的创建与数据类型
# ============================================================
# numpy 的核心对象是 ndarray（N 维数组）。
# 学习目标：掌握所有创建方式 + 理解 dtype（数据类型）+ 属性。

import numpy as np

# ============================================================
# 一、从 Python 列表创建
# ============================================================
a = np.array([1, 2, 3])            # 一维
b = np.array([[1, 2], [3, 4]])     # 二维（列表的列表）
c = np.array([1, 2, 3], dtype=float)  # 指定元素类型

# 注意：元素类型不一致时，numpy 会【自动统一】
d = np.array([1, 2.5, 3])          # int + float → 全部变 float
print(d, d.dtype)                  # → [1.  2.5 3. ] float64

# 空数组（不初始化值，用已有内存，可能含垃圾值）
e = np.empty(3)
print(e)                           # → 随机内存值（一般别用）

# ============================================================
# 二、快速生成数组（重点！）
# ============================================================
# arange：类似 range，但返回数组
print(np.arange(10))           # → [0 1 2 ... 9]
print(np.arange(2, 10, 2))     # → [2 4 6 8]（起点、终点、步长）

# linspace：在区间内均匀取 n 个点（含端点）
print(np.linspace(0, 1, 5))    # → [0. 0.25 0.5 0.75 1.]
print(np.linspace(0, 10, 3))   # → [0. 5. 10.]

# logspace：对数间隔（浓度梯度常用！）
print(np.logspace(0, 2, 3))    # → [1. 10. 100.]（10^0, 10^1, 10^2）
# 药理做剂量梯度常用：np.logspace(-1, 2, 8) 生成 0.1~100 的 8 个浓度

# zeros / ones / full
print(np.zeros(3))             # → [0. 0. 0.]
print(np.zeros((2, 3)))        # → 2行3列全0
print(np.ones((2, 2)))         # → 全1
print(np.full(3, 7))           # → [7 7 7]（全指定值）

# eye / identity：单位矩阵
print(np.eye(3))               # → 对角线为1
# [[1. 0. 0.]
#  [0. 1. 0.]
#  [0. 0. 1.]]

# ============================================================
# 三、随机数生成（np.random）
# ============================================================
# 均匀分布
print(np.random.rand(3))           # → 3个 [0,1) 均匀随机数
print(np.random.rand(2, 3))        # → 2x3
print(np.random.uniform(0, 10, 5)) # → 5个 [0,10) 均匀随机数

# 整数随机
print(np.random.randint(0, 100, 5))        # → 5个 0~99 随机整数
print(np.random.randint(0, 10, size=(2, 3)))# → 2x3 的随机整数

# 正态分布（科研最常用！模拟测量误差）
print(np.random.normal(0, 1, 5))   # → 均值0标准差1的5个值
print(np.random.normal(10, 2, 5))  # → 均值10标准差2

# 设置随机种子（让结果可复现！论文必备）
np.random.seed(42)
print(np.random.rand(3))           # → 每次运行都一样
# 科研中为了别人能复现你的结果，生成随机数据前固定 seed

# 随机打乱 / 随机选择
arr = np.arange(10)
np.random.shuffle(arr)             # 原地打乱
print(np.random.choice([10, 20, 30], size=3))  # 有放回随机选
print(np.random.choice([10, 20, 30], size=3, replace=False))  # 不放回

# ============================================================
# 四、数组属性
# ============================================================
a = np.array([[1, 2, 3], [4, 5, 6]])
print(a.ndim)      # → 2（维度数）
print(a.shape)     # → (2, 3)（形状：2行3列）
print(a.size)      # → 6（元素总数）
print(a.dtype)     # → int64（元素类型）
print(a.itemsize)  # → 8（每个元素占字节数）
print(a.nbytes)    # → 48（总字节数 = size × itemsize）

# ============================================================
# 五、dtype 数据类型（重要）
# ============================================================
# 常见 dtype：
#   int8/int16/int32/int64   整数（位数越多范围越大）
#   float16/float32/float64  浮点数（64 是默认，双精度）
#   bool                     布尔
#   object                   对象（一般别用，慢）
#   str / unicode            字符串

# 为什么关注 dtype？
#   1. 内存：int64(8字节) vs int8(1字节)，大数据时差距巨大
#   2. 精度：float32 精度低，科学计算一般用 float64
#   3. 运算速度：同 dtype 运算快

# 转换 dtype
a = np.array([1, 2, 3])
b = a.astype(float)     # → [1. 2. 3.]（不改变原数组）
c = a.astype(np.int8)
print(b.dtype, c.dtype)

# ⚠️ astype 截断问题：
print(np.array([3.9, 3.1]).astype(int))   # → [3 3]（直接截断，不是四舍五入！）
print(np.array([3.9, 3.1]).round().astype(int))  # → [4 3]（先四舍五入）

# ============================================================
# 六、数组转 Python 列表
# ============================================================
a = np.array([1, 2, 3])
print(a.tolist())        # → [1, 2, 3]（普通列表）
print(list(a))           # → 也能转

