# ============================================================
# numpy 深入 ④ — 数组变形、拼接与拆分
# ============================================================
# 处理数据时经常要改变数组形状：展平、转置、拼接、拆分。

import numpy as np

# ============================================================
# 一、reshape — 改变形状
# ============================================================
a = np.arange(12)              # [0 1 2 ... 11]
print(a.reshape(3, 4))         # → 3行4列
print(a.reshape(2, 6))         # → 2行6列
print(a.reshape(2, 3, 2))      # → 三维

# ⚠️ reshape 要求元素总数不变：12 = 3×4 = 2×6 = 2×3×2
# 用 -1 自动推断：
print(a.reshape(3, -1))        # → 3行，列数自动算（4）
print(a.reshape(-1, 4))        # → 行数自动算（3）
# -1 = "帮我算这个维度"

# 1D ←→ 2D
b = np.arange(6).reshape(2, 3)
print(b.reshape(-1))           # → [0 1 2 3 4 5]（展平成1维）
print(b.flatten())             # → 同上（flatten 返回副本）
print(b.ravel())               # → 同上（ravel 返回视图）

# 顺序注意：reshape 默认按"行优先"（C顺序）填充
print(np.arange(6).reshape(2, 3))
# → [[0 1 2]
#    [3 4 5]]

# ============================================================
# 二、转置 transpose / T
# ============================================================
m = np.array([[1, 2, 3],
              [4, 5, 6]])
print(m.T)       # → 转置（行变列）
# [[1 4]
#  [2 5]
#  [3 6]]
print(m.transpose())    # 等价

# 场景：数据是"列=样本"存的时候，转置成"行=样本"
# 例如 Excel 里横着存的样品，读进来转置一下

# ============================================================
# 三、拼接 concatenate
# ============================================================
a = np.array([[1, 2], [3, 4]])
b = np.array([[5, 6], [7, 8]])

# 上下拼（行方向，axis=0）
print(np.concatenate([a, b], axis=0))
# [[1 2]
#  [3 4]
#  [5 6]
#  [7 8]]

# 左右拼（列方向，axis=1）
print(np.concatenate([a, b], axis=1))
# [[1 2 5 6]
#  [3 4 7 8]]

# ⚠️ 拼接要求：沿 axis 之外的其他维度形状一致
# 上下拼：列数要相同；左右拼：行数要相同

# 一维拼接
print(np.concatenate([np.array([1, 2]), np.array([3, 4])]))
# → [1 2 3 4]

# ============================================================
# 四、追加 append / 插入 insert / 删除 delete
# ============================================================
a = np.array([1, 2, 3])
print(np.append(a, 4))              # → [1 2 3 4]（返回新数组）
print(np.append(a, [4, 5]))         # → [1 2 3 4 5]
print(np.insert(a, 1, 99))          # → [1 99 2 3]（在下标1前插入）
print(np.delete(a, 1))              # → [1 3]（删除下标1）

# ⚠️ numpy 的 append 每次都创建新数组，循环里用会非常慢！
# 大数据场景：先建 list，最后统一转 np.array

# ============================================================
# 五、stack — 堆叠成更高维
# ============================================================
a = np.array([1, 2, 3])
b = np.array([4, 5, 6])
print(np.vstack([a, b]))     # 垂直堆叠（成两行）
# [[1 2 3]
#  [4 5 6]]
print(np.hstack([a, b]))     # 水平堆叠
# → [1 2 3 4 5 6]

# ============================================================
# 六、拆分 split
# ============================================================
a = np.arange(10)
print(np.split(a, 2))        # → 分成2份：[0..4] [5..9]
print(np.split(a, [3, 7]))   # → 按下标切：[:3] [3:7] [7:]

# ============================================================
# 七、复制：copy vs view（重要！）
# ============================================================
a = np.arange(6)
b = a.reshape(2, 3)      # 视图（共享数据）
b[0, 0] = 999
print(a)                 # → [999 1 2 3 4 5]（a 也被改了！）

c = a.copy()             # 真正的副本
c[0] = -1
print(a)                 # → a 没变（copy 安全）

# 经验：
#   reshape / T / 切片 → 视图（改一个另一个也变）
#   copy() / flatten() / 布尔索引结果 → 副本（独立）
# 不确定时用 .copy() 最安全

# ============================================================
# 八、实战：把实验数据整理成想要的形状
# ============================================================
# 场景：仪器导出 3 批数据，每批 5 个读数，分别存在3个数组里
batch1 = np.array([1.1, 1.2, 1.3, 1.4, 1.5])
batch2 = np.array([2.1, 2.2, 2.3, 2.4, 2.5])
batch3 = np.array([3.1, 3.2, 3.3, 3.4, 3.5])

# 拼成 3行×5列（每行一批）
all_data = np.vstack([batch1, batch2, batch3])
print(all_data.shape)    # → (3, 5)

# 转置成 5行×3列（每列一批，方便按批统计）
by_batch = all_data.T
print(by_batch.mean(axis=0))    # 每批的均值

# 展平成一维（后面做总体统计）
flat = all_data.flatten()
print(flat.mean(), flat.std())  # 总体均值标准差

# ============================================================
# 八、易错点汇总
# ============================================================
# 1. reshape 要求元素总数【不变】：
#    (6,) → (2,3) 可以；(6,) → (2,4) 报错
# 2. reshape 默认返回【视图】（若可能），改它会影响原数组；
#    要独立用 .copy()
# 3. -1 是自动推断：arr.reshape(-1, 1) = 自动算行数
#    （给列固定为 1）——机器学习里常用
# 4. np.concatenate 默认按第 0 轴（行）拼；
#    axis=1 按列拼
# 5. np.vstack 纵向、np.hstack 横向，
#    np.stack 沿新轴堆叠
# 6. flatten() 返回副本，ravel() 返回视图（尽量用 flatten）

