# ============================================================
# numpy 深入 ③ — 运算与广播（Broadcasting）
# ============================================================
# 广播是 numpy 最强大也最易混的特性：
# 不同形状的数组也能运算，numpy 自动"扩展"较小的数组。

import numpy as np

# ============================================================
# 一、数组与标量的运算（最简单）
# ============================================================
a = np.array([1, 2, 3, 4])
print(a + 10)     # → [11 12 13 14]
print(a * 2)      # → [ 2  4  6  8]
print(a ** 2)     # → [ 1  4  9 16]
print(1 / a)      # → [1. 0.5 0.33...]
print(a / 0)      # → [inf inf ...]（不报错，得 inf，注意！）

# ============================================================
# 二、数组与数组的运算（形状相同）
# ============================================================
a = np.array([1, 2, 3])
b = np.array([10, 20, 30])
print(a + b)     # → [11 22 33]（对应位置相加）
print(a * b)     # → [10 40 90]（对应位置相乘，不是矩阵乘法！）
print(a > b)     # → [False False False]（逐元素比较）

# ⚠️ numpy 的 * 是逐元素乘，不是数学矩阵乘法
# 矩阵乘法用 @ 或 np.dot：
A = np.array([[1, 2], [3, 4]])
B = np.array([[5, 6], [7, 8]])
print(A @ B)     # 矩阵乘法
# [[19 22]
#  [43 50]]
print(A * B)     # 逐元素乘（完全不同）
# [[ 5 12]
#  [21 32]]

# ============================================================
# 三、广播（Broadcasting）— 核心中的核心
# ============================================================
# 不同形状的数组运算时，numpy 把小的"广播"成大的

# 例子1：一维数组 + 标量
# [1 2 3] + 10  → 10 被广播成 [10 10 10]

# 例子2：二维数组 + 一维数组（每行都加）
m = np.array([[1, 2, 3],
              [4, 5, 6]])
v = np.array([10, 20, 30])
print(m + v)
# → [[11 22 33]
#    [14 25 36]]   ← 每一行都加上 v！

# 例子3：二维数组 + 列向量
v_col = np.array([[10], [100]])     # 2行1列
print(m + v_col)
# → [[11 12 13]     ← 第0行加10
#    [104 105 106]] ← 第1行加100

# 这就是"每行标准化"的底层：data - data.mean(axis=0)
data = np.array([[1, 2, 3],
                 [4, 5, 6]])
means = data.mean(axis=0)     # → [2.5 3.5 4.5]（每列均值）
print(data - means)           # 每列减去该列均值（广播！）

# ============================================================
# 四、广播规则（理解这个就通了）
# ============================================================
# 从右往左对比两个数组的形状：
#   1. 维度相同 → 直接用
#   2. 维度不同 → 小的补 1
#   3. 某维是 1 → 广播成另一边的长度
#   4. 都不匹配且不为1 → 报错 ValueError

# 例子：
#   (2,3) 和 (3,)   → 兼容（(3,)补成(1,3)，再广播成(2,3)）
#   (2,3) 和 (2,1)  → 兼容（(2,1)广播成(2,3)）
#   (2,3) 和 (4,)   → 不兼容！报错（3 vs 4 不匹配）

# 常见报错：operands could not be broadcast together with shapes...

# ============================================================
# 五、通用函数 ufunc（逐元素运算）
# ============================================================
a = np.array([1, 4, 9, 16])
print(np.sqrt(a))      # 平方根 → [1. 2. 3. 4.]
print(np.log(a))       # 自然对数
print(np.log10(a))     # 常用对数
print(np.exp(a))       # e^x
print(np.abs(np.array([-1, 2, -3])))   # 绝对值

# 三角函数
angles = np.array([0, np.pi / 2, np.pi])
print(np.sin(angles))  # → [0. 1. 1.2e-16]

# 取整
b = np.array([3.7, 3.2, -3.7])
print(np.floor(b))     # 向下取整 → [ 3.  3. -4.]
print(np.ceil(b))      # 向上取整 → [ 4.  4. -3.]
print(np.round(b))     # 四舍五入 → [ 4.  3. -4.]

# ============================================================
# 六、聚合运算（axis 方向）
# ============================================================
m = np.array([[1, 2, 3],
              [4, 5, 6]])

print(m.sum())            # → 21（全部）
print(m.sum(axis=0))      # → [5 7 9]（沿行方向：每列的和）
print(m.sum(axis=1))      # → [6 15]（沿列方向：每行的和）
print(m.mean())           # → 3.5
print(m.max())            # → 6
print(m.min())            # → 1
print(m.std())            # → 1.7078（标准差）

# axis 记忆法：
#   axis=0 → 沿"第0维"（行）移动 → 结果按列算
#   axis=1 → 沿"第1维"（列）移动 → 结果按行算
#   简单记：axis=0 是"竖着算"，axis=1 是"横着算"

# ============================================================
# 七、cumsum / cumprod（累计）
# ============================================================
a = np.array([1, 2, 3, 4])
print(np.cumsum(a))    # 累计和 → [1 3 6 10]
print(np.cumprod(a))   # 累计积 → [1 2 6 24]
# 场景：药物累积释放量曲线

# ============================================================
# 八、比较与逻辑运算
# ============================================================
a = np.array([1, 5, 3, 8])
print(np.any(a > 5))    # → True（有没有大于5的）
print(np.all(a > 0))    # → True（是否全部大于0）
print(np.where(a > 3))  # → (array([1, 3]),)（下标）

# ============================================================
# 八、易错点汇总
# ============================================================
# 1. 广播规则：两个数组从【尾部维度】对齐，
#    兼容条件是"维度相同或有一个是 1"；
#    形状完全对不上（如 (3,) + (4,)）会 ValueError
# 2. 逐元素运算是 +-*/；【矩阵乘法】是 @ 或 np.dot
# 3. np.where(条件, 是, 否)：满足条件取第一个，否则取第二个
# 4. 向量化：能用数组运算就别写 for 循环（快几十倍）
# 5. 除法注意除零：numpy 会给出 inf 或警告，
#    数据里有 0 先处理
# 6. 比较运算返回布尔数组，可作索引

