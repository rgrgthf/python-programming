# ============================================================
# 文件的打开与关闭 — 开始读写文件
# ============================================================
# 之前你用过 print(file=fp) 输出到文件，现在系统学一下。
# 核心函数：open() 打开文件 → 操作 → close() 关闭文件

# ============================================================
# 一、open() 基本语法
# ============================================================
# open(文件路径, 模式, encoding=编码)
# 模式决定"你想怎么用这个文件"

# 常见模式：
#   "r"  只读（默认）     文件必须存在，否则报错
#   "w"  只写             不存在则创建，存在则【清空重写】！
#   "a"  追加             不存在则创建，存在则接着末尾写
#   "r+" 读写             可读可写，不创建新文件
#   "w+" 读写             可读可写，会清空
#   "a+" 读写             可读可追加
#   "b"  二进制模式        (如 "rb" 读图片，"wb" 写图片)

# ============================================================
# 二、打开和关闭
# ============================================================
# 基本流程：
f = open("练习输出/test.txt", "w")     # 以写模式打开（不存在会创建）
f.write("你好，Python！")      # 写入内容
f.close()                     # ⚠️ 用完必须关闭！

# 不关闭的后果：
#   1. 数据可能没真正写入磁盘（还在缓冲区）
#   2. 文件被占用，其他程序打不开
#   3. 多次打开不关会耗尽资源


# ============================================================
# 三、读取模式
# ============================================================
# 先写点内容供读取
f = open("练习输出/test.txt", "w", encoding="utf-8")
f.write("第一行\n第二行\n第三行\n")
f.close()

f = open("练习输出/test.txt", "r", encoding="utf-8")
content = f.read()          # 读全部
print(content)
f.close()


# ============================================================
# 四、追加模式 a
# ============================================================
f = open("练习输出/test.txt", "a", encoding="utf-8")
f.write("追加的一行\n")      # 接在末尾，不清空原有内容
f.close()

f = open("练习输出/test.txt", "r", encoding="utf-8")
print(f.read())             # 原内容 + 追加的一行
f.close()


# ============================================================
# 五、编码 encoding
# ============================================================
# 中文文件必须指定 encoding="utf-8"，否则可能乱码或报错
# 写文件：open("x.txt", "w", encoding="utf-8")
# 读文件：open("x.txt", "r", encoding="utf-8")
# 不指定时，Windows 默认用 GBK，和 UTF-8 文件不兼容会报 UnicodeDecodeError


# ============================================================
# 六、路径
