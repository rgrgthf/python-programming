# ============================================================
# with 语句 — 自动管理文件
# ============================================================
# 手动 close() 容易忘，with 语句自动关闭，是推荐写法。

# ============================================================
# 一、基本写法
# ============================================================
# 传统写法
f = open("练习输出/test.txt", "w", encoding="utf-8")
f.write("你好")
f.close()                    # 手动关闭

# with 写法（推荐）
with open("练习输出/test.txt", "w", encoding="utf-8") as f:
    f.write("你好")
# 缩进块结束，文件自动关闭，无需 close()


# ============================================================
# 二、with 为什么安全？
# ============================================================
# 就算中间报错，with 也会保证文件被关闭（异常也会走关闭）
with open("练习输出/test.txt", "w", encoding="utf-8") as f:
    f.write("1\n")
    # raise Exception("出错")    # 假设这里出错
    f.write("2\n")
# 即使出错，文件也已自动关闭，不会占用资源


# ============================================================
# 三、读文件用 with
# ============================================================
with open("练习输出/test.txt", "r", encoding="utf-8") as f:
    content = f.read()
    print(content)
# 读取结束自动关闭


# ============================================================
# 四、同时开多个文件
# ============================================================
# 读一个文件，写入另一个（复制文件）
with open("练习输出/test.txt", "r", encoding="utf-8") as src, \
     open("练习输出/copy.txt", "w", encoding="utf-8") as dst:
    for line in src:           # 逐行读
        dst.write(line)        # 逐行写
# 两个文件都自动关闭
# \ 是续行符：一行太长时换行继续写


# ============================================================
# 五、什么时候必须用 with？
# ============================================================
# 几乎所有文件操作都应该用 with：
# ✅ 简单、安全、不用记 close()
# ✅ 避免"忘记关闭"导致的数据丢失/文件占用
# ❌ 只有需要长期保持文件打开（很少见）才手动 open/close
#
# 记住：以后写文件操作，默认用 with！

