# ============================================================
# 文件的读取 — 各种读法
# ============================================================
# 先造一个测试文件
f = open("练习输出/test.txt", "w", encoding="utf-8")
f.write("第一行\n第二行\n第三行\n第四行\n")
f.close()

# ============================================================
# 一、read() — 一次读全部
# ============================================================
f = open("练习输出/test.txt", "r", encoding="utf-8")
content = f.read()          # 读整个文件，返回一个字符串
print(content)
f.close()
# 输出：
# 第一行
# 第二行
# 第三行
# 第四行


# ============================================================
# 二、read(n) — 读指定字符数
# ============================================================
f = open("练习输出/test.txt", "r", encoding="utf-8")
print(f.read(3))    # 读前 3 个字符 → "第一行"
print(f.read(2))    # 接着读 2 个字符 → "\n第"（位置是连续的！）
f.close()
# 注意：read(n) 是从【当前位置】继续读，不是每次从头


# ============================================================
# 三、readline() — 读一行
# ============================================================
f = open("练习输出/test.txt", "r", encoding="utf-8")
print(f.readline())    # → 第一行（含换行符 \n）
print(f.readline())    # → 第二行
f.close()
# 每次调用读一行，指针向后移动


# ============================================================
# 四、readlines() — 读所有行成列表
# ============================================================
f = open("练习输出/test.txt", "r", encoding="utf-8")
lines = f.readlines()       # 每行一个元素（带 \n）
print(lines)                # → ['第一行\n', '第二行\n', '第三行\n', '第四行\n']
f.close()

# 去掉每行末尾的换行符
clean = [line.strip() for line in lines]
print(clean)                # → ['第一行', '第二行', '第三行', '第四行']


# ============================================================
# 五、最推荐：for 循环直接遍历
# ============================================================
# 大文件（几 GB）不能 read() 全读进内存，用 for 逐行读最安全
f = open("练习输出/test.txt", "r", encoding="utf-8")
for line in f:              # 一行一行读，省内存
    print(line.strip())     # strip() 去掉换行符
f.close()
# 输出：
# 第一行
# 第二行
# 第三行
# 第四行


# ============================================================
# 六、读取注意点
# ============================================================
# 1. 用 "r" 读不存在的文件会报 FileNotFoundError
# 2. 中文文件必须指定 encoding="utf-8"
# 3. 读完后文件指针在末尾，再 read() 返回空字符串
# 4. 每行都带 \n，常用 strip() 清理

