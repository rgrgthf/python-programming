# 六、什么时候用异常处理？
# ============================================================
# ✅ 用户输入可能不合法时
# ✅ 读取可能不存在的文件/网络请求时
# ✅ 任何"外部因素"可能导致错误的地方
# ❌ 不要用 try/except 掩盖逻辑错误——bug 要改，不是吞掉

