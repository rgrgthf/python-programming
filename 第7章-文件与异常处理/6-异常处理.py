# ============================================================
# 异常处理 — 让程序出错时优雅处理
# ============================================================
# 程序运行中可能出错（用户输入错误、文件不存在、除数为0...）
# 异常处理 = 提前预判错误，给用户友好提示，而不是直接崩溃。

# ============================================================
# 一、try / except 基本用法
# ============================================================
try:
    num = int(input("请输入一个整数："))
    print("结果是：", 10 / num)
except ZeroDivisionError:          # 捕获特定的异常类型
    print("错误：除数不能为 0！")
except ValueError:                 # 可以多个 except
    print("错误：输入的不是整数！")
# 输入 0 → 错误：除数不能为 0！
# 输入 abc → 错误：输入的不是整数！
# 输入 5 → 结果是：2.0


# ============================================================
# 二、常用异常类型
# ============================================================
# ValueError          值错误（int("abc")）
# TypeError           类型错误（"a" + 1）
# ZeroDivisionError   除零错误（10 / 0）
# FileNotFoundError   文件不存在
# IndexError          下标越界（lst[10]）
# KeyError            键不存在（d["x"]）
# NameError           变量未定义
# IndentationError    缩进错误


# ============================================================
# 三、except Exception — 兜底捕获
# ============================================================
# 不知道具体什么错，可以用 Exception 捕获所有错误（不推荐滥用）
try:
    result = 10 / int(input("数字："))
except Exception as e:      # e 是错误对象，能打印详细信息
    print("出错了：", e)    # → 出错了：division by zero
# 更规范：尽量捕获具体的异常类型


# ============================================================
# 四、else 和 finally
# ============================================================
# else：try 没出错时执行
# finally：无论是否出错都会执行（通常用于清理）
try:
    f = open("练习输出/test.txt", "r", encoding="utf-8")
except FileNotFoundError:
    print("文件不存在")
else:
    print("文件读取成功")
    print(f.read())
finally:
    print("无论如何都会执行")
# finally 常用场景：确保文件关闭、释放资源


# ============================================================
# 五、实战：文件操作 + 异常处理
# ============================================================
def read_file_safe(filename):
    """安全读取文件，文件不存在时给友好提示"""
    try:
        with open(filename, "r", encoding="utf-8") as f:
            return f.read()
    except FileNotFoundError:
        return f"错误：找不到文件 {filename}"
    except UnicodeDecodeError:
        return "错误：编码不匹配，尝试指定 encoding"

print(read_file_safe("test.txt"))       # 正常读取
print(read_file_safe("不存在.txt"))      # → 错误：找不到文件 不存在.txt


