# ============================================================
# 序列总结 — 四大容器的对比与选择
# ============================================================
# 到这一章为止，你学过了：字符串、列表、元组、字典、集合
# 这一节把它们放在一起对比，建立整体框架。

# ============================================================
# 一、哪些是"序列"？
# ============================================================
# 序列 = 有序、可以用下标访问、可以切片
#   字符串 str     ✅ 有序（但不可变）
#   列表 list      ✅ 有序（可变）
#   元组 tuple     ✅ 有序（不可变）
#   字典 dict      ❌ 无序（没有下标）
#   集合 set       ❌ 无序（没有下标）

# 验证：字典和集合没有下标
# d = {"a": 1}; print(d[0])   ← 报错
# s = {1, 2};   print(s[0])   ← 报错


# ============================================================
# 二、可变性对比
# ============================================================
# 可变（能增删改）      不可变（创建后不能动）
#   列表 list             字符串 str
#   字典 dict             元组 tuple
#   集合 set
#
# 为什么重要？
# 1. 不可变类型才能当字典的键（列表/字典/集合都不能当键）
# 2. 不可变类型可以做集合的元素


# ============================================================
# 三、四大容器速查表
# ============================================================
#               列表 list      元组 tuple      字典 dict        集合 set
# 写法          [1,2,3]        (1,2,3)         {"a":1}          {1,2,3}
# 有序？        是              是              否              否
# 可变？        是              否              是              是
# 元素唯一？    否              否              键唯一          是
# 按下标访问？  是 lst[0]       是 t[0]         否（按键）       否
# 典型用途      动态数据        固定数据        键值查找        去重/集合运算


# ============================================================
# 四、怎么选？（决策流程）
# ============================================================
# 需要按"位置/编号"存储 → 列表（要改）或 元组（固定）
# 需要按"键/名字"查找   → 字典
# 需要去重或集合运算    → 集合
# 只是一段文本           → 字符串

# 场景举例：
#  学生名单（会增删）       → 列表
#  常量配置（不变）         → 元组
#  学号→姓名（按学号查）    → 字典
#  统计有哪些不同字母       → 集合


# ============================================================
# 五、通用操作（序列共有）
# ============================================================
# 以下操作对 字符串/列表/元组 都有效：
print(len("abc"))          # → 3
print(len([1, 2, 3]))      # → 3
print(len((1, 2)))         # → 2

print("a" in "abc")        # → True
print(1 in [1, 2])         # → True
print(1 in (1, 2))         # → True

# 字典的 in 判断的是键
d = {"a": 1}
print("a" in d)            # → True
print(1 in d)              # → False（1 是值不是键）


# ============================================================
# 六、类型转换（互转）
# ============================================================
s = "hello"
print(list(s))             # 字符串→列表 → ['h','e','l','l','o']
print(tuple(s))            # 字符串→元组 → ('h','e','l','l','o')
print(set(s))              # 字符串→集合 → {'h','e','l','o'}（去重）

lst = [1, 2, 2, 3]
print(tuple(lst))          # 列表→元组 → (1, 2, 2, 3)
print(set(lst))            # 列表→集合 → {1, 2, 3}（去重）
print(list(lst))           # 列表→列表（拷贝一份新的）

t = (1, 2, 3)
print(list(t))             # 元组→列表 → [1, 2, 3]


# ============================================================
# 七、本章重点总结
# ============================================================
# 1. 列表是最常用的容器：append/insert/pop/remove/sort
# 2. 元组 = 不可变列表，安全且能解包
# 3. 字典 = 键值查找，比列表快，遍历用 items()
# 4. 集合 = 去重 + 集合运算（| & - ^）
# 5. 判断可变不可变，决定了它能不能当字典的键
