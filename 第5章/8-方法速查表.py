# ============================================================
# 方法速查表 — 各种类型可用的函数一览
# ============================================================
# 这是第五章的"字典级"参考：每种类型能调用哪些方法。
# 使用时：先看类型 → 再找方法 → 不懂的翻回对应笔记或问我。
# 格式：方法名(参数) —— 作用

# ============================================================
# 一、字符串 str（不可变）
# ============================================================
# s.upper()         全部转大写        "abc".upper() → 'ABC'
# s.lower()         全部转小写        "ABC".lower() → 'abc'
# s.strip()         去掉两端空白      "  hi  ".strip() → 'hi'
# s.split(sep)      按分隔符切开成列表 "1,2".split(",") → ['1','2']
# s.join(列表)      用 s 拼接列表元素  "-".join(['a','b']) → 'a-b'
# s.replace(a,b)    把 a 替换成 b      "aba".replace("a","x") → 'xbx'
# s.find(sub)       找子串下标，找不到 -1
# s.count(sub)      子串出现次数
# s.startswith(x)   是否以 x 开头
# s.endswith(x)     是否以 x 结尾
# s.isalpha()       是否全是字母
# s.isdigit()       是否全是数字
# len(s)            长度
# s[i] / s[a:b]     索引 / 切片
# s + t / s * n     拼接 / 重复
# x in s            成员判断

# ============================================================
# 二、列表 list（可变、有序）
# ============================================================
# lst.append(x)          末尾加一个元素
# lst.extend(列表)       把另一个列表的元素逐个加进来
# lst.insert(i, x)       在下标 i 处插入 x
# lst.remove(x)          删除第一个等于 x 的元素（按值）
# lst.pop(i)             删除并返回下标 i 的元素（默认最后一个）
# lst.clear()            清空
# lst.index(x)           返回 x 第一次出现的下标
# lst.count(x)           x 出现几次
# lst.sort()             升序排序（reverse=True 降序）
# lst.reverse()          反转顺序
# lst[i] = x             修改元素
# del lst[i]             按下标删除
# lst[a:b]               切片（结果还是列表）
# len(lst) / x in lst    长度 / 成员判断
# sum(lst)               求和（数字列表）
# list(range(n))         快速生成 0~n-1

# ============================================================
# 三、元组 tuple（不可变、有序）
# ============================================================
# t.count(x)         x 出现几次
# t.index(x)         x 第一次出现的下标
# len(t) / t[i] / 切片 / x in t    都能用
# 没有 append/pop/sort 等修改方法！（不可变）
# a, b, c = t        解包（元组最强用法）

# ============================================================
# 四、字典 dict（可变、无序、按键查）
# ============================================================
# d[key]             取值（键不存在报 KeyError）
# d.get(key, 默认)    安全取值（不存在返回默认，不报错）
# d[key] = value     添加 / 修改
# d.pop(key, 默认)    删除键并返回值（可带默认防报错）
# d.popitem()         删除最后一个键值对
# d.clear()           清空
# d.keys()            所有键
# d.values()          所有值
# d.items()           所有键值对
# d.update(另一字典)   合并更新
# d.setdefault(k, v)  键不存在才设置
# key in d            判断键是否存在
# len(d)              键值对个数
# 遍历：for k, v in d.items()

# ============================================================
# 五、集合 set（可变、无序、去重）
# ============================================================
# s.add(x)            添加元素
# s.remove(x)         删除元素（不存在报 KeyError）
# s.discard(x)        删除元素（不存在也不报错）
# s.pop()             随机删除一个
# s.clear()           清空
# A | B               并集
# A & B               交集
# A - B               差集
# A ^ B               对称差
# A <= B              子集判断
# x in s              成员判断
# len(s)              元素个数
# set(列表)           列表去重

# ============================================================
# 六、通用内置函数（对多种类型都有效）
# ============================================================
# len(x)       长度/元素个数         适用：全部
# type(x)      类型                  适用：全部
# list(x)      转成列表              适用：str/tuple/set/range
# tuple(x)     转成元组              适用：str/list/set
# set(x)       转成集合（去重）      适用：str/list/tuple
# str(x)       转成字符串            适用：全部
# sorted(x)    排序（返回新列表）    适用：list/tuple/set/str
# reversed(x)  反转（返回迭代器）    适用：list/tuple/str
# max(x) / min(x)  最大 / 最小       适用：list/tuple/str/set
# sum(x)       求和                  适用：数字 list/tuple/set
# enumerate(x) 同时拿下标和元素      适用：list/tuple/str
# zip(a, b)    把两个序列配对        适用：list/tuple

# ============================================================
