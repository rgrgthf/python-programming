# 程序的描述方式有三种
# 分别是自然语言、伪代码和流程图。
# 统一示例：输入圆的半径，计算圆的周长和面积并输出
# 公式：周长 = 2 × π × r，面积 = π × r²

# ============================================================
# 一、自然语言
# ============================================================
# 用日常语言描述程序做了什么，适合给非程序员看，缺点是可能不够精确。
#
# 示例：
#   1. 提示用户输入圆的半径
#   2. 获取用户输入，转换成数值
#   3. 用公式"周长 = 2 × 3.14 × 半径"计算周长
#   4. 用公式"面积 = 3.14 × 半径 × 半径"计算面积
#   5. 输出计算结果

# ============================================================
# 二、伪代码
# ============================================================
# 介于自然语言和代码之间，有代码的结构但不拘泥于语法，方便理清思路。
#
# 示例：
#   输入 r
#   PI = 3.14
#   周长 = 2 * PI * r
#   面积 = PI * r * r
#   输出 周长, 面积

# ============================================================
# 三、流程图
# ============================================================
# 用图形符号描述程序执行流程，直观清晰，适合复杂逻辑。
#
#    ┌──────────────┐
#    │    开始       │
#    └──────┬───────┘
#           ▼
#    ┌──────────────┐
#    │ 输入半径 r    │
#    └──────┬───────┘
#           ▼
#    ┌──────────────┐
#    │ 周长=2*PI*r  │
#    │ 面积=PI*r*r  │
#    └──────┬───────┘
#           ▼
#    ┌──────────────┐
#    │ 输出周长和面积 │
#    └──────┬───────┘
#           ▼
#    ┌──────────────┐
#    │    结束       │
#    └──────────────┘
#
# 符号说明：
#   ┌─┐（圆角矩形）= 开始/结束
#   └─┘（矩形）    = 处理步骤
#   ⬜（平行四边形） = 输入/输出（图中用矩形简化）

# ============================================================
# 四、真正的 Python 代码（对照参考）
# ============================================================
r = float(input("请输入圆的半径："))
PI = 3.14
perimeter = 2 * PI * r
area = PI * r * r
print("周长：", perimeter)
print("面积：", area)