# 五、常见坑
# ============================================================

# ① 忘记更新循环变量 → 死循环！
# i = 1
# while i <= 5:
#     print(i)
#     # 忘了 i += 1！i 永远是 1，条件永远 True — 死循环！

# ② while 的条件里不能写赋值（和 if 一样）
# while x = 5:       ← 错误！= 是赋值
# while x == 5:      ← 正确，== 是比较