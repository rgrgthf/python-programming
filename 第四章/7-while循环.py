# ============================================================
# while 循环 — 条件成立就继续
# ============================================================
# 语法：while 条件:
#           循环体
# 每次执行前先判断条件，条件为 True 就执行一轮，为 False 就退出。
# 和 for 不同：while 不依赖序列，靠条件驱动，循环次数可以不事先确定。

# ============================================================
# 一、基本示例
# ============================================================
i = 1
while i <= 5:
    print(i, end=" ")
    i += 1  # ← 千万别忘！否则死循环
print()
# → 1 2 3 4 5

# 对比 C++：
# C++:  while (i <= 5) { cout << i; i++; }
# Python：不需要括号包裹条件，用冒号 + 缩进


# ============================================================
# 二、while 的经典应用场景
# ============================================================

# ① 不知道循环次数 — 用户输入控制退出
answer = ""
while answer != "quit":
    answer = input("请输入内容（输入 quit 退出）：")
    print("你输入了：", answer)

# ② 循环次数不确定 — 猜数字游戏
import random
target = random.randint(1, 100)
guess = 0
count = 0
while guess != target:
    guess = int(input("猜一个 1~100 的数："))
    count += 1
    if guess > target:
        print("大了")
    elif guess < target:
        print("小了")
print("猜对了！你用了", count, "次")

# ③ 处理输入直到合法
age = -1
while age < 0 or age > 150:
    age = int(input("请输入年龄（0-150）："))
print("你的年龄是：", age)


# ============================================================
# 三、for vs while 选择指南
# ============================================================
# 知道循环次数（或遍历序列） → for
# 不知道循环次数，靠条件控制   → while
#
# for i in range(10):       # 明确循环 10 次
# while user_input != "q":  # 不知道用户什么时候输 q


# ============================================================
# 四、无限循环
# ============================================================
# while True 是"一直循环直到内部用 break 退出"
while True:
    cmd = input("输入命令（help/quit）：")
    if cmd == "quit":
        print("再见！")
        break  # break 强行跳出循环
    elif cmd == "help":
        print("这是帮助信息")
    else:
        print("未知命令")


