# ============================================================
# 四、while-else 同理
# ============================================================
attempts = 0
while attempts < 3:
    pwd = input("密码：")
    if pwd == "123456":
        print("登录成功")
        break
    attempts += 1
else:
    print("3 次机会用完，账号已锁定")
# 密码对了 → break 跳出，else 不执行
# 3 次都错  → 循环自然结束，else 执行 → 锁定


# ============================================================
# 五、总结：else 什么时候执行？
# ============================================================
#           break 退出   自然结束（条件变 False）
# for-else     ❌ 不执行       ✅ 执行
# while-else   ❌ 不执行       ✅ 执行

# 一句话：把 else 读作"循环跑完了没被打断"，就好理解了。