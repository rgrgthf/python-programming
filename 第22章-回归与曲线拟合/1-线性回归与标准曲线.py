# ============================================================
# 线性回归与标准曲线 — 药物分析核心技能
# ============================================================
# 标准曲线：用已知浓度的标准品测出信号（吸光度），
# 拟合出"信号 = k × 浓度 + b"的直线，再用未知样品的信号反推浓度。
# 这是药物分析实验最常用、论文里必出现的图。

import numpy as np
import matplotlib.pyplot as plt
from scipy import stats

plt.rcParams["font.sans-serif"] = ["SimHei"]
plt.rcParams["axes.unicode_minus"] = False

# ============================================================
# 一、准备标准品数据
# ============================================================
# 标准浓度和对应的吸光度（你的实验数据）
conc = np.array([0.0, 0.1, 0.2, 0.4, 0.8, 1.6])    # 浓度 mg/mL
abs_ = np.array([0.001, 0.082, 0.158, 0.331, 0.654, 1.302])  # 吸光度

# ============================================================
# 二、线性回归（最小二乘法）
# ============================================================
slope, intercept, r_value, p_value, std_err = stats.linregress(conc, abs_)
# slope     = 斜率 k
# intercept = 截距 b
# r_value   = 相关系数 r（r² 是决定系数，越接近1越好）

print(f"回归方程：y = {slope:.4f}x + {intercept:.4f}")
print(f"R² = {r_value ** 2:.4f}")
print(f"p = {p_value:.4f}")
# R² > 0.99 是标准曲线的基本要求（药物分析要求）

# ============================================================
# 三、画标准曲线图（论文标准格式）
# ============================================================
# 生成拟合直线（两个端点就够画直线）
line_x = np.array([0, conc.max()])
line_y = slope * line_x + intercept

plt.scatter(conc, abs_, color="blue", label="标准品")
plt.plot(line_x, line_y, "r--", label=f"y = {slope:.3f}x + {intercept:.3f}")
plt.xlabel("浓度 (mg/mL)")
plt.ylabel("吸光度 (A)")
plt.title("标准曲线")
plt.grid(True, linestyle="--", alpha=0.5)
plt.legend()

# 在图上标注 R²（论文习惯）
plt.text(0.05, abs_.max() * 0.8, f"R² = {r_value**2:.4f}", fontsize=12)

plt.savefig("标准曲线.png", dpi=300)
plt.show()

# ============================================================
# 四、用标准曲线算未知样品浓度
# ============================================================
# 测得未知样品的吸光度：
unknown_abs = 0.412

# 从 y = kx + b 反解 x = (y - b) / k
unknown_conc = (unknown_abs - intercept) / slope
print(f"未知样品浓度 = {unknown_conc:.3f} mg/mL")

# ============================================================
# 五、批量计算多个未知样品
# ============================================================
unknowns = np.array([0.210, 0.412, 0.650, 0.880])
concs = (unknowns - intercept) / slope
print("多个未知样品浓度：", np.round(concs, 3))

# ============================================================
# 六、计算加样回收率（药分实验常用）
# ============================================================
# 已知理论浓度，测出实际浓度，回收率 = 实际/理论 × 100%
theory = np.array([0.5, 1.0, 1.5])        # 理论浓度
measured = np.array([0.49, 1.03, 1.47])   # 实测浓度
recovery = measured / theory * 100
print("回收率(%)：", np.round(recovery, 1))
print(f"平均回收率：{recovery.mean():.1f}% ± {recovery.std():.1f}%")
# 药物分析要求回收率通常在 95%~105% 之间

# ============================================================
# 七、标准曲线质量检查清单
# ============================================================
# 1. R² ≥ 0.99（线性关系好）
# 2. 截距接近 0（无系统误差）
# 3. 未知样品信号落在标准曲线范围内（外推不可靠！）
# 4. 至少 5~6 个浓度点，覆盖待测样品浓度范围
