# 网址：  r"https?://\S+"
# 浮点数：r"-?\d+\.\d+"
# 空白清理：r"\s+"
# 化学式？：r"[A-Z][a-z]?\d*"（元素+原子数，粗略版）

# ============================================================
# 六、r 原始字符串 — 必须写 r"..."
# ============================================================
# 正则里 \d 等反斜杠有特殊含义，用 r"..." 防止 Python 转义
print(r"\d+")    # 原始字符串，\d 保持原样
# 不加 r："\\d+" 才是对的（\d 会被 Python 当成转义字符吃掉）
# 所以【正则一律写 r"..."】，这是硬规则。

# ============================================================
# 七、易错点汇总
# ============================================================
# 1. 忘了写 r → \d 被转义，模式全错。写正则必带 r
# 2. search vs match：match 必须从头开始，别搞混
# 3. 贪婪匹配吃太多：HTML 标签、多字符场景用 .+? 懒惰
# 4. findall 有分组时返回元组，不是字符串
# 5. 忘加 re.I 导致大小写不匹配
# 6. 写复杂正则前先想清楚，一行正则解决不了就拆两步

