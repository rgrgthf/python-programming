# ============================================================
# 正则 = 用"模式"描述一类字符串，然后【搜索/提取/替换】。
# 用途：从实验数据、日志、文档中提取信息，清洗文本。
# Python 用 re 模块。学完你能：
#   · 用 re 在文本里查找/提取/替换
#   · 读懂元字符和量词，自己写模式
#   · 用分组精准提取想要的部分
#
# 记住：正则不是背下来的，是"查 + 用"用熟的。
# 重点知道"能做什么、大概怎么写"，用到再查具体符号。

import re

# ============================================================
# 一、核心函数全家福（re 模块最常用的 6 个）
# ============================================================
# ① re.search：全文查找，返回【第一个】匹配（找不到返回 None）
result = re.search(r"\d+", "浓度是 12.5 mg/mL")
print(result.group())       # → 12（第一个数字串）
# search 找不到时不报错，返回 None——用前先判断：
m = re.search(r"xyz", "abc")
print(m)                    # → None

# ② re.findall：找到【所有】匹配，返回列表（最常用！）
nums = re.findall(r"\d+", "批次1: 0.5, 批次2: 1.2, 批次3: 0.8")
print(nums)                 # → ['1', '0', '5', '2', '1', '2', '3', '0', '8']

# ③ re.sub：替换所有匹配
clean = re.sub(r"\d+", "X", "样品A-001 和 样品B-002")
print(clean)                # → 样品A-X 和 样品B-X

# ④ re.match：从【开头】开始匹配（和 search 的区别！）
print(re.match(r"\d+", "123abc"))   # → 有结果（开头就是数字）
print(re.match(r"\d+", "abc123"))   # → None（开头不是数字）
print(re.search(r"\d+", "abc123"))  # → 有结果（search 全文找）

# ⑤ re.fullmatch：要求【整个字符串】完全匹配（验证输入格式专用）
print(re.fullmatch(r"\d{3}", "123"))    # → 有结果
print(re.fullmatch(r"\d{3}", "1234"))   # → None（多了一位）

# ⑥ re.finditer：找所有匹配，返回迭代器（数据多时省内存）
for m in re.finditer(r"\d+", "a1 b22 c333"):
    print(m.group(), end=" ")     # → 1 22 333
print()

# ---------- 怎么选？----------
# 只要第一个匹配  → re.search
# 要全部匹配     → re.findall（最常用）
# 替换          → re.sub
# 严格验证整个串 → re.fullmatch（或 re.match）

# ============================================================
# 二、基本元字符（先混个脸熟，用多了自然记住）
# ============================================================
# \d  数字           \D  非数字
# \w  字母数字下划线   \W  非
# \s  空白(空格/换行)  \S  非空白
# .   任意字符（除换行）
# ^   开头           $   结尾
# \b  单词边界
#
# 量词：
# *   0次或多次        +   1次或多次
# ?   0次或1次
# {n} 恰好n次          {n,m} n到m次
#
# 字符类：
# [abc]  a/b/c任一      [a-z]  a到z
# [^abc] 非a/b/c

# 示例（理解量词和字符类）：
print(re.findall(r"\d{2}", "abc123def45"))     # → ['12', '45']（恰好2位）
print(re.findall(r"\d{2,3}", "abc123def45"))   # → ['123', '45']（2~3位，贪多）
print(re.findall(r"[a-z]+", "Hello World 123"))  # → ['ello', 'orld']
print(re.findall(r"[A-Z]", "Hello World"))        # → ['H', 'W']

# ---------- 贪婪 vs 懒惰（重要易错点）----------
# 默认是【贪婪】：尽量多匹配。加 ? 变【懒惰】：尽量少匹配。
text = "<a>1</a><b>2</b>"
print(re.findall(r"<.+>", text))     # → ['<a>1</a><b>2</b>']（贪婪，一口气到底）
print(re.findall(r"<.+?>", text))    # → ['<a>', '</a>', '<b>', '</b>']（懒惰，一个一个）
# 处理 HTML/标签时几乎都要用懒惰（.+?）

# ---------- 常用 flags（修饰符）----------
# re.I    忽略大小写
# re.S    . 也匹配换行（默认 . 不匹配换行）
# re.M    多行模式，^ $ 匹配每行开头结尾
print(re.search(r"hello", "HELLO", re.I))     # → 有结果（忽略大小写）

# ---------- re.compile（进阶：多次用同一模式）----------
# 同一模式用很多次时，先编译成对象，更快更清晰：
phone_re = re.compile(r"1[3-9]\d{9}")
print(phone_re.findall("电话 13812345678，另一 13900001111"))
# → ['13812345678', '13900001111']

# ============================================================
# 三、分组 ( ) — 精准提取关键部分
# ============================================================
# 用 ( ) 分组，group(1) 取第一组，group(0) 是整体
m = re.search(r"(\d+)\.(\d+)", "浓度 12.5 mg/mL")
print(m.group(0))    # → 12.5（整个匹配）
print(m.group(1))    # → 12（第一组：整数部分）
print(m.group(2))    # → 5（第二组：小数部分）

# 例子：解析"姓名-成绩"
m = re.search(r"(\w+)-(\d+)", "小明-95")
print(m.group(1), m.group(2))    # → 小明 95

# ---------- 命名分组（推荐：可读性更好）----------
# 用 (?P<名字>...) 给分组起名，用 group("名字") 取：
m = re.search(r"(?P<name>\w+)-(?P<score>\d+)", "小明-95")
print(m.group("name"), m.group("score"))   # → 小明 95

# findall 遇到分组时：返回的是【每组的内容】组成的元组
print(re.findall(r"(\w+)-(\d+)", "小明-95 小红-88"))
# → [('小明', '95'), ('小红', '88')]

# ============================================================
# 四、实战：从实验记录中提取数据
# ============================================================
# 假设仪器导出一堆文本记录：
records = [
    "Sample A1: 吸光度 0.523",
    "Sample B2: 吸光度 1.014",
    "Sample C3: 吸光度 0.098",
]

# 提取所有样品名和吸光度（用命名分组）
for line in records:
    m = re.search(r"(?P<sample>\w+): 吸光度 (?P<abs>\d+\.\d+)", line)
    if m:
        print(f"样品 {m.group('sample')}：吸光度 {m.group('abs')}")

