# 四、打包数据分析脚本（带 pandas 等库）
# ============================================================
# 打包含 pandas/numpy 的脚本：
#   pyinstaller --onefile 数据分析工具.py
# 注意：
#   - 打包会慢一些（库大）
#   - 生成的 exe 也较大（几十MB）
#   - 建议在 sci 环境打包（库全）
#
# 坑1：找不到数据文件
#   → 用 --add-data "data.xlsx;." 附加
#   → 代码里用相对路径要小心（见下）
#
# 坑2：运行时文件路径问题
#   打包后程序在临时目录解压运行，用 sys._MEIPASS 定位：
import sys, os

def resource_path(relative_path):
    """打包后也能找到资源文件"""
    base_path = getattr(sys, "_MEIPASS", os.path.abspath("."))
    return os.path.join(base_path, relative_path)

# 用法：path = resource_path("data/template.xlsx")

