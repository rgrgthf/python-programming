# ============================================================
# 五、易错点汇总
# ============================================================
# 1. PyInstaller 打包：pyinstaller -F 文件.py
#    -F 单文件，-w 无控制台窗口
# 2. 打包出的 exe 在 dist/ 目录
# 3. 含第三方库（pandas 等）的 exe 会很大、启动慢——正常
# 4. 打包前先确认代码【能直接运行】（没有路径写死/缺文件）
# 5. 中文路径/文件名打包有时会出问题，
#    用英文路径更稳
# 6. 打包后的 exe 给别人用：对方不用装 Python

