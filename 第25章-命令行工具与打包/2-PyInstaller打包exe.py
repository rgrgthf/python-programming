# ============================================================
# 六、常见问题
# ============================================================
# 问题1：exe 被杀毒软件误报
#   → Python 打包的 exe 常见误报，加白名单或签名
# 问题2：打包后运行闪退
#   → 终端直接运行 exe 看报错；多半是缺数据文件或路径问题
# 问题3：exe 太大
#   → 正常（含Python解释器+库），可接受
# 问题4：换电脑打不开
#   → Windows 系统不同位数问题少见，一般 OK
# 问题5：重新打包
#   → 先删 build/ 和 dist/ 再打包，避免残留

