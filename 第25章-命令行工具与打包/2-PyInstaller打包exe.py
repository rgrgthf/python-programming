# ============================================================
# 命令行工具与打包 ② — PyInstaller 打包 exe
# ============================================================
# 把 Python 脚本打包成 .exe：
#   实验室同事没有 Python 环境也能双击运行你的工具！
#   ⚠️ 需要安装：pip install pyinstaller

# ============================================================
# 一、为什么打包？
# ============================================================
# 1. 别人不用装 Python 就能用（药学实验室很实用！）
# 2. 分发工具简单（一个 exe 文件）
# 3. 保护源码（exe 不易被直接读取）
# 4. 作品集展示：给面试官演示"我做过可用的工具"

# ============================================================
# 二、打包命令（终端里执行）
# ============================================================
# 基本打包：
#   pyinstaller 你的脚本.py
#   → 生成 dist/你的脚本.exe
#
# 常用参数：
#   --onefile      打包成单个exe文件（推荐，方便分发）
#   --windowed     不显示黑色命令行窗口（有GUI时用）
#   --name 名字    指定exe名称
#   --icon 图标.ico 设置图标
#   --add-data    附加数据文件（如数据模板）
#
# 完整示例：
#   pyinstaller --onefile --name 剂量计算器 剂量计算器.py
#   → 生成 dist/剂量计算器.exe

# ============================================================
# 三、打包一个最小示例（跟着做）
# ============================================================
