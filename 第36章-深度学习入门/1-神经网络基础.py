# ============================================================
# 深度学习入门 ① — 神经网络基础
# ============================================================
# 深度学习的本质：用"多层神经网络"拟合复杂函数。
# 这一节讲清楚核心概念（不写代码，重在理解）：
# 神经元、激活函数、损失函数、反向传播、训练过程。

# ============================================================
# 一、从"一个神经元"讲起
# ============================================================
# 神经元 = 输入加权求和 + 激活函数
#
#        x1 ──w1──┐
#        x2 ──w2──┼──→ 求和 → 激活 → 输出
#        x3 ──w3──┘
#
# 输出 = 激活函数(w1*x1 + w2*x2 + w3*x3 + b)
# 权重 w 决定每个输入的重要性
# 偏置 b 调节整体偏移

# 用代码模拟一个神经元：
import numpy as np

def neuron(inputs, weights, bias, activation=lambda x: x):
    """单个神经元的计算"""
    z = np.dot(inputs, weights) + bias   # 加权求和
    return activation(z)

# 例子：根据(分子量, LogP)判断类药性（简化）
inputs = np.array([180.0, 1.5])          # 分子量, LogP
weights = np.array([-0.01, 0.5])         # 权重
bias = 1.0
output = neuron(inputs, weights, bias)
print(f"神经元输出: {output:.3f}")

# ============================================================
# 二、激活函数（给网络"非线性"能力）
# ============================================================
# 没有激活函数，多层=一层（线性叠加无意义）
# 激活函数引入非线性，才能拟合复杂模式

def sigmoid(x):
    """S型函数：输出0~1，适合二分类"""
    return 1 / (1 + np.exp(-x))

def relu(x):
    """修正线性单元：负值归0，最常用"""
    return max(0, x)

def tanh(x):
    """双曲正切：输出-1~1"""
    return np.tanh(x)

# 展示不同激活函数
for x in [-3, -1, 0, 1, 3]:
    print(f"x={x:>2}: sigmoid={sigmoid(x):.3f}  relu={relu(x):>3}  "
          f"tanh={tanh(x):.3f}")

# 怎么选？
#   隐藏层：默认 ReLU（快、效果好）
#   二分类输出：sigmoid（输出概率）
#   多分类输出：softmax
#   回归输出：不用激活（直接输出数值）

# ============================================================
# 三、神经网络的结构
# ============================================================
# 输入层 → 隐藏层(多层) → 输出层
#
#  输入(5个描述符)     隐藏层(128神经元)     输出(活性)
#     MW ─────────┐
#     LogP ───────┤   [ReLU] × 2层  ──→  [线性] ──→ 预测值
#     HBD ───────┤
#     ...
#
# "深度" = 隐藏层多
# 层数越多，能表示的函数越复杂（但也越容易过拟合）

# ============================================================
# 四、训练过程（核心思想）
# ============================================================
# 训练 = 不断调整权重 w，让预测越来越准
#
# 1. 前向传播：输入 → 层层计算 → 得到预测值
# 2. 计算损失：预测值 vs 真实值 差多少
#    - 回归用 MSE（均方误差）
#    - 分类用 交叉熵
# 3. 反向传播：从输出往回，计算每个权重该往哪调
#    （梯度下降：损失对每个w求导，朝减小损失的方向微调）
# 4. 更新权重：w = w - 学习率 × 梯度
# 5. 重复 1~4（一个 epoch = 跑完一遍全部数据）

# 学习率（learning rate）：
#   太大 → 震荡不收敛
#   太小 → 训练太慢
#   常用 0.001 ~ 0.01，或用自适应优化器（Adam）

# ============================================================
# 五、过拟合与正则化（深度学习的头号问题）
# ============================================================
# 网络参数多 → 很容易把训练数据"背下来" → 测试集表现差
# 解决方法：
#   1. Dropout：训练时随机"关掉"部分神经元（防依赖个别）
#   2. Early stopping：验证集不再变好就停止
#   3. 数据增强：制造更多数据
#   4. 减小模型/加正则项

# ============================================================
# 六、深度学习的硬件
# ============================================================
# 训练在 GPU 上（显卡）远比 CPU 快
# 小数据集（几百分子）：CPU 也够用
# 大数据集（几万分子）：需要 GPU 或用云
# 学习阶段：CPU 跑小例子完全够

# ============================================================
# 七、什么时候该用深度学习？
# ============================================================
# 传统机器学习（第34/35章）：
#   - 数据量不大（几百~几千）
#   - 特征明确（描述符算好的）
#   - 简单、快、可解释（特征重要性）
#   → 药学QSAR小数据，先学这个！
#
# 深度学习：
#   - 数据量大（几万+）
#   - 数据是原始形式（图片/序列/分子图）
#   - 性能天花板更高
#   → 分子图神经网络(GNN)、蛋白质结构预测、图像分析
#
# 建议：先掌握传统ML（能用），深度学习作为了解+进阶

# ============================================================
# 八、总结
# ============================================================
# 神经元：加权求和 + 激活
# 激活：ReLU(隐藏层) sigmoid(二分类) softmax(多分类)
# 训练：前向→损失→反向传播→更新权重（梯度下降）
# 过拟合：Dropout/EarlyStopping
# 选型：小数据用sklearn，大数据/原始数据用深度学习
