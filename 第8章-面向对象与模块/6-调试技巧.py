# ============================================================
# 一、读懂报错信息（最重要！）
# ============================================================
# Python 报错分三部分，从下往上读：
#
#   Traceback (most recent call last):
#     File "xxx.py", line 5, in <module>     ← ① 出错位置（文件+行号）
#       print(1/0)                            ← ② 出错那行代码
#   ZeroDivisionError: division by zero       ← ③ 错误类型和原因
#
# 口诀：先看最后一行（什么错），再看中间（哪里错）。


# ============================================================
# 二、print 调试法 — 最朴素的排查手段
# ============================================================
# 不知道哪里出错时，在关键位置打印变量看变化：
def calculate(x, y):
    print("进入函数，x =", x, "y =", y)   # ① 看输入
    result = x + y
    print("result =", result)             # ② 看中间结果
    return result * 2

print(calculate(3, 4))
# 输出：
# 进入函数，x = 3 y = 4
# result = 7
# 14
# 通过多打几个 print，就能定位问题出在哪一步

# 调试完记得删掉 print，或用注释包起来


# ============================================================
# 三、常见错误类型速查
# ============================================================
# SyntaxError        语法错误（拼写、缺冒号、缩进）
# NameError          变量未定义（拼错变量名）
# TypeError          类型错误（"a" + 1、字典用()调用）
# ValueError         值错误（int("abc")）
# IndexError         下标越界（lst[10]）
# KeyError           键不存在（d["x"]）
# ZeroDivisionError  除零
# FileNotFoundError  文件不存在
# AttributeError     对象没有这个属性/方法（str没有append）
# UnicodeDecodeError 编码不匹配（忘写 encoding="utf-8"）


# ============================================================
# 四、常见错误的具体例子
# ============================================================

# ① NameError：变量名拼写不一致
# count = 0
# print(cont)        ← cont 拼错了！NameError

# ② TypeError：把字符串当数字用
# age = input("年龄：")      # input 返回字符串！
# print(age + 1)             # "18" + 1 → TypeError
# 解决：age = int(input(...))

# ③ IndexError：越界
# lst = [1, 2, 3]
# print(lst[3])      ← 最大下标是 2！

# ④ KeyError：字典键不存在
# d = {"a": 1}
# print(d["b"])      ← 键不存在！用 d.get("b", 默认值)


# ============================================================
# 五、分步排查法（遇到 bug 的标准流程）
# ============================================================
# 1. 复制完整的报错信息（别只截一行）
# 2. 看最后一行：是什么类型的错？
# 3. 看文件+行号：是哪一行？
# 4. 检查那行代码：拼写？类型？缩进？变量名？
# 5. 还是不懂？在出错行前加 print 打印相关变量
# 6. 实在不行，把报错贴给 AI（我）看
#
# 千万别：不看报错就乱改代码（瞎试）


# ============================================================
# 六、用 assert 检查逻辑（进阶）
# ============================================================
# assert 条件, "提示语"：条件为 False 时报错
def square(x):
    return x * x

assert square(4) == 16, "平方算错了！"    # 通过，无输出
# assert square(4) == 15, "平方算错了！"   # 失败，报 AssertionError
# assert 适合测试函数逻辑对不对，快速定位


