# ============================================================
# 一、读懂报错信息（最重要！）
# ============================================================
# Python 报错叫 Traceback（回溯），从【下往上】读：
#
#   Traceback (most recent call last):
#     File "xxx.py", line 5, in <module>     ← ① 出错位置：文件+行号
#       print(1/0)                            ← ② 出错那行代码
#   ZeroDivisionError: division by zero       ← ③ 错误类型 + 原因
#
# 三部分的作用：
#   ① 告诉你去哪找（哪个文件第几行）
#   ② 把那行代码原样给你看（可能多个函数嵌套时，会列出调用链）
#   ③ 【最重要】错误类型 + 一句话原因
#
# 口诀：【先看最后一行】知道"什么错"，【再看行号】知道"哪里错"。
# 报错很长时，往往只看最后 3-5 行就够。

# ============================================================
# 二、print 调试法 — 最朴素的排查手段
# ============================================================
# 不知道哪里出错时，在关键位置打印变量看变化：
def calculate(x, y):
    print("进入函数，x =", x, "y =", y)   # ① 看输入
    result = x + y
    print("result =", result)             # ② 看中间结果
    return result * 2

print(calculate(3, 4))
# 输出：
# 进入函数，x = 3 y = 4
# result = 7
# 14
# 通过多打几个 print，就能定位问题出在哪一步
# 调试完记得删掉 print，或用注释包起来


# ============================================================
# 三、常见错误类型速查（原因 + 解决）
# ============================================================
# | 错误              | 原因                           | 解决 |
# | SyntaxError       | 语法错误：缺冒号/拼错/缩进     | 看行号检查语法 |
# | NameError         | 变量未定义：名字拼错/没定义    | 检查变量名 |
# | TypeError         | 类型不匹配："a"+1、字符串.append | 转类型 str()/int() |
# | ValueError        | 值不对：int("abc")            | 检查输入值 |
# | IndexError        | 下标越界：lst[10]              | 检查长度/循环范围 |
# | KeyError          | 字典键不存在：d["x"]          | 用 d.get(key, 默认) |
# | ZeroDivisionError | 除以 0                        | 加判断 x != 0 |
# | FileNotFoundError | 文件不存在/路径错              | 检查路径/先创建 |
# | AttributeError    | 对象没这个属性/方法：str.append | 换对的方法/确认类型 |
# | UnicodeDecodeError| 编码不匹配：忘写 encoding       | open() 加 encoding="utf-8" |
#
# 这十个错误，覆盖了你 90% 的报错。遇到先归类，再对症下药。

# ============================================================
# 四、常见错误的具体例子
# ============================================================

# ① NameError：变量名拼写不一致
# count = 0
# print(cont)        ← cont 拼错了！NameError: name 'cont' is not defined
# 解决：检查变量名拼写（IDE 里变量会变色的，盯着颜色看）

# ② TypeError：把字符串当数字用
# age = input("年龄：")      # input 返回字符串！
# print(age + 1)             # "18" + 1 → TypeError
# 解决：age = int(input(...))   # 先转成整数

# ③ IndexError：越界
# lst = [1, 2, 3]
# print(lst[3])      ← 最大下标是 2！（下标从 0 开始）
# 解决：下标范围是 0 ~ len(lst)-1

# ④ KeyError：字典键不存在
# d = {"a": 1}
# print(d["b"])      ← 键不存在！
# 解决：print(d.get("b", 0))   # get + 默认值，更安全

# ⑤ AttributeError：对象没这个属性/方法
# s = "hello"
# s.append("x")      ← 字符串没有 append！那是列表的方法
# 解决：先确认对象类型，再用对的方法

# ============================================================
# 五、分步排查法（遇到 bug 的标准流程）
# ============================================================
# 1. 复制完整的报错信息（别只截一行）
# 2. 看最后一行：是什么类型的错？
# 3. 看文件+行号：是哪一行？
# 4. 检查那行代码：拼写？类型？缩进？变量名？
# 5. 还是不懂？在出错行前加 print 打印相关变量
# 6. 实在不行，把报错贴给 AI（我）看
#
# 千万别：不看报错就乱改代码（瞎试）——那是浪费时间的最大来源。

# ============================================================
# 六、assert 检查逻辑（进阶）
# ============================================================
# assert 条件, "提示语"：条件为 False 时抛 AssertionError
# 适合"验证假设"：假设某个值应该是什么，不对就立刻报警

def square(x):
    return x * x

assert square(4) == 16, "平方算错了！"    # 通过，无输出
# assert square(4) == 15, "平方算错了！"   # 失败，报 AssertionError
# 用途：测试函数逻辑、防御式检查（数据必须满足条件才继续）

