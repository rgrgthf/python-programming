# ============================================================
# 一、模块、包、导入方式
# ============================================================
# · 【模块 module】= 一个 .py 文件。任何 .py 文件都能被 import。
# · 【包 package】= 一个包含 __init__.py 的【文件夹】，
#   是一堆相关模块的集合（比如 os 包里装着 path、listdir 等）。
#
# 为什么需要它们？——代码多了就要拆分：
#   一个项目几千行，全塞一个文件没法维护。
#   把"算剂量的"放 dose.py、"管库存的"放 stock.py，
#   用的时候 import 进来——这就是模块化。

# 导入的四种写法：
import math            # ① 导入整个模块 → math.sqrt(9)
import random as rnd   # ② 起别名 → rnd.randint(1,10)
from math import sqrt  # ③ 只导入其中一样 → sqrt(9)（不用前缀）
from math import pi, e #   一次导入多个

# 三种写法的取舍：
#   import math            → 要写前缀 math.sqrt，好处：名字不会冲突
#   from math import sqrt  → 直接用 sqrt，好处：简洁；坏处：可能重名
#   import math as m       → 短前缀 m.sqrt，兼顾两者，但牺牲可读性
#
# 经验：
#   · 用得多 → import 模块（带前缀，清晰）
#   · 用得少/只用一个 → from 模块 import 函数
#   · 别用 from math import * （星号导入）：把全部名字倒进来，
#     很容易覆盖你自己的变量，是新手常犯的坑


# ============================================================
# 二、import 到底做了什么？
# ============================================================
# import 一个模块时，Python 会：
#   1. 按 sys.path 的顺序【找】这个 .py 文件
#      （sys.path 包含：脚本所在目录、已装第三方库目录、标准库目录）
#   2. 【从上到下执行】这个文件里的【所有代码】！（重要！）
#   3. 把里面的函数/变量挂到模块名下，供你调用
#
# 结论：模块文件里不该有"一执行就有副作用"的代码，
#   比如 print、input、打开文件——否则别人一 import，
#   就莫名其妙打印一堆东西。这就引出下一节的关键技巧：

# ============================================================
# 三、if __name__ == "__main__" — 每个文件都该有
# ============================================================
# __name__ 是 Python 自动给的【特殊变量】：
#   · 直接运行这个文件时 → __name__ == "__main__"
#   · 被别人 import 时   → __name__ == "模块名"（不是 __main__）
#
# 所以把"测试代码"放进 if 里，就能做到：
#   直接运行 → 执行测试；被 import → 只导入函数，不执行测试。

def add(a, b):
    return a + b

def sub(a, b):
    return a - b

if __name__ == "__main__":
    # 这里的代码只有"直接运行本文件"时才执行
    print("测试：", add(3, 5))       # → 测试： 8
    print("测试：", sub(10, 4))      # → 测试： 6
# 如果别的文件 import 本文件，只导入 add/sub，不会打印测试
# 因为此时 __name__ 是模块名，不是 "__main__"

# ---------- 为什么一定要写？ ----------
# ① 别人 import 你的文件时，不会莫名其妙跑你的测试代码
# ② 你自己能随时直接运行这个文件做自测
# ③ 这是"可复用模块"的标准写法，所有专业代码都这样

