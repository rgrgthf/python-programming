# ============================================================
# 八、易错点汇总
# ============================================================
# 1. 模块文件里别写"直接执行的代码"（print/input/开文件），
#    会被 import 的人白白执行；要写就放 if __name__ 里
# 2. 别用 from xxx import *：污染命名空间，覆盖你的变量
# 3. import 找不到文件时看 sys.path：
#    import sys; print(sys.path)  查看搜索路径
#    自己的模块要和脚本同目录，或用 包 结构
# 4. 循环导入（A import B，B 又 import A）会报错，
#    设计时避免互相依赖
# 5. 改了模块文件不生效？——因为 Python 缓存了模块，
#    重启解释器，或用 importlib.reload(模块)

