#   pip list             查看已安装的库
#   pip install 库名      安装
#   pip uninstall 库名    卸载
#   pip install 库名 -i 国内镜像   国内加速安装（如清华镜像）

# ============================================================
# 六、包（package）—— 模块多了之后怎么组织
# ============================================================
# 当相关模块多起来，就把它们放进一个【包】文件夹：
#   mypkg/                  ← 包
#       __init__.py         ← 包的标志（可以空，也可以放初始化）
#       dose.py             ← 包里的模块
#       stock.py
#
# 导入包里的模块：
#   from mypkg import dose
#   from mypkg.dose import by_weight
#
# __init__.py 作用：
#   · 让 Python 认这个文件夹是包
#   · 可写初始化代码 / 定义 __all__（控制 from pkg import * 导入什么）
#
# 实际项目结构（药学场景）：
#   pharmacy_tools/          ← 包
#       __init__.py
#       dose.py               ← 剂量计算
#       stats.py              ← 实验统计
#       plotting.py           ← 出图
#   这样你的工具能像标准库一样被任何脚本 import。

