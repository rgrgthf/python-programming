# ============================================================
# 〇、先回答最重要的问题：为什么需要 OOP？
# ============================================================
# 你之前写的程序叫【面向过程】：程序 = 一堆函数按顺序调用。
# 它的特点是：数据（变量）和函数是分开的，靠参数传来传去。
#
# 面向过程在"简单程序"里很好用，但一到【复杂场景】就崩：
#   比如一个药房系统，要管理 病人、药品、处方、库存……
#   如果每个数据都用字典存、每个逻辑都靠函数传参，
#   代码会变成一团乱麻：改一个函数，七八处跟着崩，
#   数据是谁的、由谁负责改，越来越分不清。
#
# OOP（面向对象编程）给出的答案是：【把数据和操作这份数据的方法，
# 打包成一个整体】——这个整体就叫【对象】。
#   病人对象：自带 姓名/诊断/过敏史（数据），
#             自带 开药/查过敏（方法）。
#   药房只需要和"对象"打交道，不用再手动传一堆参数。
#
# 药学类比：病历
#   病历模板（类）：规定每份病历有哪些栏目（属性）、
#                   规定医生能对病历做什么操作（方法）。
#   张三的病历（对象）：一份具体的、填好了数据的病历。
#
# 一句话：【类是模板/图纸，对象是按模板造出来的具体实例】。
# 而且——你已经悄悄用过对象了：
#   s = "hello"      → s 是一个【字符串对象】
#   s.upper()        → 调用字符串对象的【方法】
#   lst = [1,2,3]    → lst 是一个【列表对象】
#   lst.append(4)    → 调用列表对象的方法
# 你以前一直在用对象，这一节学的是：如何【自己定义类】，造出你自己的对象。

# ============================================================
# 一、类（class） vs 对象（object）—— 图纸 vs 实物
# ============================================================
# · 类 = 图纸/模板：规定【有什么属性】【有什么行为】，但不具体。
# · 对象 = 按图纸造出来的【实物】：数据被填成了具体的值。
#
#   人是"类"（图纸：每个人都有名字、年龄；都会说话、走路）
#   小明、小红 是"人"这个类造出来的【对象】（名字被填成了具体的）
#
#   手机是"类"（图纸：有品牌、价格属性；能打电话、发消息的方法）
#   我的 iPhone 是对象（具体的：品牌=苹果，价格=5999）
#
# 关键理解：类描述【共同点】，对象才是【具体的那一份】。
# 一份图纸能造出无数台手机，一个类能造出无数个对象。


# ============================================================
# 二、定义一个类 —— 逐行拆解
# ============================================================
class Dog:
    """狗的类"""
    # __init__ 是【构造方法】：创建对象时【自动】调用
    def __init__(self, name, age):
        self.name = name      # 把传入的 name 记到【这个对象】身上
        self.age = age        # 把传入的 age 记到【这个对象】身上

    # 方法：定义在类里的函数，第一个参数【永远是 self】
    def bark(self):
        print(f"{self.name}：汪汪！")

    def show(self):
        print(f"我叫{self.name}，{self.age}岁")

# 创建对象：调用类名 = 自动调用 __init__
d1 = Dog("旺财", 3)   # Python 自动执行 Dog.__init__(d1, "旺财", 3)
d2 = Dog("来福", 5)   # Python 自动执行 Dog.__init__(d2, "来福", 5)

# 访问属性、调用方法
print(d1.name)      # → 旺财（属性，不带括号）
print(d2.age)       # → 5
d1.bark()           # → 旺财：汪汪！（方法，带括号）
d2.show()           # → 我叫来福，5岁

# ---------- 逐行理解这个类 ----------
# 1. class Dog:  声明定义一个类，类名【大写开头】（约定俗成）
# 2. __init__：双下划线开头 = 特殊方法（魔法方法）。
#    它负责【初始化】：对象刚造出来时，要把哪些数据存到对象身上。
#    它不叫 constructor（构造），而叫 initializer（初始化）更准确——
#    因为对象的内存是 Python 先分配好的，__init__ 只负责往里填数据。
# 3. self.name = name：把【参数 name】存成【对象自己的属性】。
#    左边 self.name 是"对象身上的名牌"，右边 name 是"传进来的值"。
# 4. def bark(self)：方法 = 定义在类里的函数。
#    方法第一个参数一定是 self，因为它要能访问"调用它的那个对象"。
#
# 属性 vs 方法的区分（以后会反复遇到）：
#   · 属性 = 数据（名词）→ 访问时不带括号：d1.name
#   · 方法 = 行为（动词）→ 调用时带括号：d1.bark()


# ============================================================
# 三、self 到底是什么？—— 90% 初学者卡在这里
# ============================================================
# self 就是【"我自己"】，指代【当前正在处理的那个对象】。
#
# 关键机制：【方法绑定】
# 当你写 d1.bark() 时，Python 偷偷做了一件事——
#   把对象 d1 作为第一个参数塞给了 bark：
#     d1.bark()  完全等价于  Dog.bark(d1)
#   bark 的第一个参数 self 接住了 d1，于是：
#     self.name  =  d1.name  =  "旺财"
#
# 所以定义方法时必须写 self：它是【接收调用者的信箱】。
# 如果你写 def bark(): （没有 self），
# 调用 d1.bark() 时 Python 照样把 d1 塞进来，但你的方法没有位置接它
#   → 报错：TypeError: bark() takes 0 positional arguments but 1 was given
#   （翻译：方法没留位置，但 Python 塞了个对象进来，接不住！）
#
# 重要：self 只是一个【约定俗成的名字】，不是关键字。
#   写成 def bark(this): 也合法，但全世界都写 self，请遵守约定。
#
# 核心区分：self.x vs x
#   · self.x = 对象的【属性】（贴在对象身上，一直存在）
#   · x      = 方法的【局部变量】（函数执行完就消失）
class Example:
    def __init__(self, x):
        self.x = x      # 对象的属性：会被保存下来
        y = 10          # 局部变量：这个函数一结束就没了

e = Example(5)
print(e.x)      # → 5（对象属性，外部能访问）
# print(e.y)    # ← 报错！y 是局部变量，不属于对象，外部根本看不到

# 一句话记忆：self. 就是"我的"。
#   在方法里想拿"这个对象的数据"，必须通过 self 指路。


