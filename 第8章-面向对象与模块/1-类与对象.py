# 五、实战：学生类 + 药学场景
# ============================================================
class Student:
    def __init__(self, name, score):
        self.name = name
        self.score = score

    def report(self):
        if self.score >= 60:
            print(f"{self.name}：及格（{self.score}分）")
        else:
            print(f"{self.name}：不及格（{self.score}分）")

# 创建多个对象（同一张图纸，造出不同实例）
s1 = Student("小明", 85)
s2 = Student("小红", 45)

s1.report()   # → 小明：及格（85分）
s2.report()   # → 小红：不及格（45分）

# 每个对象【独立保存自己的数据】——这是 OOP 的核心价值
students = [Student("张三", 90), Student("李四", 59)]
for s in students:
    s.report()

# ---------- 药学实战：药品类 ----------
# 试着理解：这个类怎么描述"药品"？对象怎么造出来？
class Drug:
    def __init__(self, name, price, dosage):
        self.name = name          # 药名
        self.price = price        # 价格
        self.dosage = dosage      # 单次剂量

    def show(self):
        print(f"{self.name}：{self.price}元/盒，单次{self.dosage}mg")

    def cost_per_dose(self):
        """计算单次用药成本（药学常用）"""
        return self.price / 30    # 假设一盒30片，算每片成本

loratadine = Drug("氯雷他定", 20, 10)   # 造一个氯雷他定对象
loratadine.show()
print(f"单次成本约 {loratadine.cost_per_dose():.2f} 元")

