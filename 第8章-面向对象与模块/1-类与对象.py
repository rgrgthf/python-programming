# 四、为什么需要 OOP？—— 面向过程 vs 面向对象 对比
# ============================================================
# 【面向过程写法】函数 + 手动管理数据：
def make_dog(name, age):
    return {"name": name, "age": age}   # 用字典存狗的数据

def bark(dog):
    print(f"{dog['name']}：汪汪！")       # 函数要自己知道数据长什么样

d = make_dog("旺财", 3)   # 手动创建
bark(d)                    # 手动把数据传给函数
# 问题：数据和函数是分开的，一旦狗的"结构"变了（比如加个品种字段），
#       所有操作狗的函数都得跟着改。

# 【OOP 写法】数据和操作打包成一个类：
class Dog2:
    def __init__(self, name, age):
        self.name, self.age = name, age
    def bark(self):
        print(f"{self.name}：汪汪！")

d = Dog2("旺财", 3)
d.bark()
# 狗的数据和"怎么叫"绑在一起了，以后想改狗的结构，
# 只改类内部即可，外面使用的人（d.bark()）完全不受影响。

# OOP 的三大好处（背下来）：
#   1.【封装】：数据和操作它的方法放一起，使用者不用关心内部细节
#   2.【独立】：每个对象有自己的属性，互不干扰（d1 是旺财，d2 是来福）
#   3.【可扩展】：继承、多态（后面内容），代码能越写越庞大而不乱
#
# 类比：面向过程像"散装的零件"，面向对象像"整台机器"——
#   零件再多也要自己一个个拼；机器拿来就能用，内部自己管自己。


