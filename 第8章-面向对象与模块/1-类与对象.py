# ============================================================
# 类与对象 — Python 的面向对象编程（OOP）
# ============================================================
# 之前你写的都是"面向过程"：一堆函数按顺序执行。
# OOP = 把"数据"和"操作数据的方法"打包成一个整体（对象）。
# 你已经用过很多对象了：s = "hello"（字符串对象）、lst.append()（列表方法）
# 这一章学【自己定义类】。

# ============================================================
# 一、类 vs 对象（类比：图纸 vs 实物）
# ============================================================
# 类（class）   = 图纸/模板：定义有什么属性和行为
# 对象（object）= 按图纸造出来的实物
#
#   class 是"人"这个类的图纸
#   小明、小红 是"人"这个类造出来的对象

# 例子：手机
#   类：手机（定义：有品牌、价格属性；能打电话、发消息的方法）
#   对象：我的 iPhone（具体的：品牌=苹果，价格=5999）


# ============================================================
# 二、定义一个类
# ============================================================
class Dog:
    """狗的类"""
    # __init__ 是"构造方法"：创建对象时自动调用
    def __init__(self, name, age):
        self.name = name      # self.name = 这个对象的名字属性
        self.age = age        # self.age = 这个对象的年龄属性

    # 方法：定义在类里的函数，第一个参数永远是 self
    def bark(self):
        print(f"{self.name}：汪汪！")

    def show(self):
        print(f"我叫{self.name}，{self.age}岁")

# 创建对象（调用类名 = 自动调用 __init__）
d1 = Dog("旺财", 3)
d2 = Dog("来福", 5)

# 访问属性、调用方法
print(d1.name)      # → 旺财（属性，不带括号）
print(d2.age)       # → 5
d1.bark()           # → 旺财：汪汪！（方法，带括号）
d2.show()           # → 我叫来福，5岁


# ============================================================
# 三、self 是什么？
# ============================================================
# self = "对象自己"。方法里用 self 访问"这个对象"的属性。
#
# 调 d1.bark() 时，Python 自动把 d1 传给 self：
#   d1.bark()  等价于  Dog.bark(d1)
#   self.name 就是 d1.name = "旺财"
#
# 不用 self 的变量是方法的局部变量，和对象无关
class Example:
    def __init__(self, x):
        self.x = x      # self.x = 对象的属性（要记住）
        y = 10          # y = 局部变量（用完就没了）

e = Example(5)
print(e.x)      # → 5（属性能访问）
# print(e.y)    # ← 报错！y 是局部变量，不属于对象


# ============================================================
# 四、为什么需要 OOP？（对比函数）
# ============================================================
# 面向过程写法：函数 + 手动管理数据
def make_dog(name, age):
    return {"name": name, "age": age}   # 用字典存
def bark(dog):
    print(f"{dog['name']}：汪汪！")
d = make_dog("旺财", 3)
bark(d)

# OOP 写法：数据和操作打包
class Dog2:
    def __init__(self, name, age):
        self.name, self.age = name, age
    def bark(self):
        print(f"{self.name}：汪汪！")
d = Dog2("旺财", 3)
d.bark()

# OOP 的好处：
#   1. 数据和方法在一起，不易混乱
#   2. 每个对象有自己的属性，互不干扰
#   3. 便于扩展（继承，后面讲）


# ============================================================
# 五、实战：一个简单的学生类
# ============================================================
class Student:
    def __init__(self, name, score):
        self.name = name
        self.score = score

    def report(self):
        if self.score >= 60:
            print(f"{self.name}：及格（{self.score}分）")
        else:
            print(f"{self.name}：不及格（{self.score}分）")

# 创建多个对象
s1 = Student("小明", 85)
s2 = Student("小红", 45)

s1.report()   # → 小明：及格（85分）
s2.report()   # → 小红：不及格（45分）

# 每个对象独立保存自己的数据
students = [Student("张三", 90), Student("李四", 59)]
for s in students:
    s.report()
