# 四、多重继承（了解，慎用）
# ============================================================
class Flyer:
    def fly(self):
        print("飞行中")

class Swimmer:
    def swim(self):
        print("游泳中")

class Duck(Flyer, Swimmer):        # 继承两个类
    pass

d = Duck()
d.fly()     # → 飞行中
d.swim()    # → 游泳中
# 多重继承能"多合一"，但有两个坑：
#   ① 两个父类有同名方法时，谁先谁后（按括号顺序，靠左优先）
#   ② 菱形继承（两个父类又有共同父类）时调用顺序复杂
# 结论：能用单继承/组合，就别用多重继承。实际项目里很罕见。

# ============================================================
# 五、isinstance() 与多态 — OOP 的"终极武器"
# ============================================================
print(isinstance(d, Duck))       # → True
print(isinstance(d, Flyer))      # → True（子类对象也是父类类型！）

# ---------- 多态：同一个动作，不同表现 ----------
animals = [Dog("旺财"), Cat("咪咪"), Bird("小黄")]
for a in animals:
    a.eat()     # 每个对象调用【自己的】eat（重写的用重写的）
# → 旺财 在吃东西（Animal 的）
# → 咪咪 在吃东西（Animal 的）
# → 小黄 在啄米吃（Bird 重写的）
#
# 这就是多态：循环里每个对象都是 Animal（父类），
# 但调用 eat() 时，各自执行各自的实现。
# 好处：调用方不需要知道每个对象具体是哪个子类，
#      只管"它一定会 eat()"——代码因此高度灵活、可扩展。
#
# 药学实战：多态处理不同给药途径
class DrugByRoute:
    def __init__(self, name):
        self.name = name
    def route(self):
        pass                     # 父类留空，子类各自实现（"抽象"雏形）

class Tablet(DrugByRoute):
    def route(self):
        print(f"{self.name}：口服给药")

class Injection(DrugByRoute):
    def route(self):
        print(f"{self.name}：静脉注射")

drugs = [Tablet("布洛芬片"), Injection("头孢曲松")]
for dg in drugs:
    dg.route()     # → 各走各的给药途径


