# 六、什么时候用继承？（is-a vs has-a）
# ============================================================
# ✅ 【is-a】关系：Dog 是一只 Animal → 用继承
# ❌ 【has-a】关系：车有发动机 → 用组合（不是继承）
#
# 判断口诀：子类【是】一种父类 吗？
#   Dog  is  a  Animal     → 继承 ✅
#   Car  has a  Engine     → 组合，不是继承 ❌
#
# 组合（在一个类里用另一个类的对象）往往更灵活，
# 继承会把父类和子类"焊死"，改父类可能影响所有子类。
# 新手倾向滥用继承，记住：能用组合就先组合，
# 除非非常确定"is-a"关系，再用继承。

# ============================================================
# 七、易错点汇总
# ============================================================
# 1. 子类 __init__ 不会自动调父类：忘写 super().__init__() →
#    AttributeError（父类存的属性不存在）
# 2. 重写 = 方法名和参数都跟父类一致，只改函数体；
#    签名不一致（参数数量不同）不是重写，是"新的方法"
# 3. 多重继承同名方法按括号顺序靠左优先；
#    实际开发优先单继承/组合
# 4. isinstance(子类对象, 父类) 返回 True，别被吓到，这是多态基础
# 5. 别乱继承：is-a 才用继承，has-a 用组合

