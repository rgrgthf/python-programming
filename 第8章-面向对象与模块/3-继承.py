# ============================================================
# 一、基本继承
# ============================================================
class Animal:                      # 父类（基类/超类）
    def __init__(self, name):
        self.name = name

    def eat(self):
        print(f"{self.name} 在吃东西")

    def sleep(self):
        print(f"{self.name} 在睡觉")

class Dog(Animal):                 # 子类：括号里写父类 = 继承
    def bark(self):                # 子类自己的方法
        print(f"{self.name}：汪汪！")

class Cat(Animal):                 # 另一个子类
    def meow(self):
        print(f"{self.name}：喵喵！")

d = Dog("旺财")
d.eat()          # → 旺财 在吃东西（继承来的！）
d.sleep()        # → 旺财 在睡觉（继承来的！）
d.bark()         # → 旺财：汪汪！（自己的）

c = Cat("咪咪")
c.eat()          # → 咪咪 在吃东西（继承的）
c.meow()         # → 咪咪：喵喵！（自己的）
# c.bark()       # ← 报错！猫没有叫的方法（子类只有自己+父类的方法）

# ---------- 继承的"属性查找顺序"（核心机制）----------
# 当你写 d.eat() 时，Python 按这个顺序找：
#   ① d 自己（对象）→ ② Dog 类 → ③ Animal 类（父类）→ ④ 报错
# 所以子类对象能"自动"用到父类的一切——因为找不到就往上找。
#
# 药学例子：基类存"共同点"，子类加"特有"
class DrugBase:                      # 药品基类：所有药共有的
    def __init__(self, name, price):
        self.name = name
        self.price = price
    def show(self):
        print(f"{self.name}：{self.price}元")

class Antibiotic(DrugBase):          # 抗生素：继承 + 特有属性
    def __init__(self, name, price, spectrum):
        super().__init__(name, price)  # 先让父类存 name/price
        self.spectrum = spectrum       # 抗菌谱是抗生素独有的
    def info(self):
        print(f"{self.name}：抗菌谱覆盖{self.spectrum}")

amox = Antibiotic("阿莫西林", 15, "革兰氏阳性菌")
amox.show()    # → 阿莫西林：15元（继承的）
amox.info()    # → 阿莫西林：抗菌谱覆盖革兰氏阳性菌（自己的）


# ============================================================
# 二、方法重写 — 子类改父类的方法（多态的第一步）
# ============================================================
class Bird(Animal):
    def eat(self):                 # 【重写】：方法名和父类一样 = 覆盖
        print(f"{self.name} 在啄米吃")

    def fly(self):
        print(f"{self.name} 在飞")

bird = Bird("小黄")
bird.eat()         # → 小黄 在啄米吃（覆盖了父类的"吃东西"）
bird.sleep()       # → 小黄 在睡觉（没重写的用父类的）

# ---------- 重写的意义：同名方法，不同行为 ----------
# 这就是【多态】的雏形：同一个 eat()，
# 不同子类对象调用时，各自用自己的版本。
# 后面你会看到：把不同子类对象放进同一个列表，
# 循环调用同一个方法，各自执行各自的实现——
# 这就是 OOP 最强大的能力之一。
#
# 重写不是覆盖删除父类方法，而是"子类这层"优先。
# 父类方法依然存在，其他子类、父类对象照常用父类的。


# ============================================================
# 三、super() — 调用父类的方法
# ============================================================
# 关键事实：【子类的 __init__ 不会自动调用父类的 __init__！】
# 如果父类 __init__ 里存了属性（如 self.name），
# 而子类 __init__ 没调 super().__init__()，那 self.name 就不存在，
# 一用就 AttributeError。

class Student(Animal):
    def __init__(self, name, score):
        super().__init__(name)     # 调用父类 __init__，把 name 交上去
        self.score = score         # 再加子类自己的属性

    def report(self):
        print(f"{self.name} 考了 {self.score} 分")

s = Student("小明", 85)
s.report()         # → 小明 考了 85 分
s.sleep()          # → 小明 在睡觉（父类方法也能用）
# 没有 super().__init__ 时，self.name 不存在 → AttributeError

# ---------- super() 的本质 ----------
# super() 不是"父类对象"，它返回一个"代理"，
# 作用是："从父类那边开始按顺序找这个方法"。
# 常见两种用法：
#   ① super().__init__(参数)  → 复用父类的初始化逻辑
#   ② super().方法名(参数)    → 复用父类某个方法（重写时"扩展"而不是覆盖）
#
# 药学应用：重写父类方法时"先调用父类再补充"
class CoughDrug(DrugBase):
    def __init__(self, name, price, ingredient):
        super().__init__(name, price)   # 父类存 name/price
        self.ingredient = ingredient    # 子类加成分
    def show(self):                     # 重写 show：先继承父类逻辑
        super().show()                  # 打印"xx：xx元"
        print(f"   成分：{self.ingredient}")  # 再补充一行

right = CoughDrug("右美沙芬", 25, "氢溴酸右美沙芬")
right.show()
# → 右美沙芬：25元
#     成分：氢溴酸右美沙芬


